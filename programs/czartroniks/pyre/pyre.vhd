-- Pyre: advected-field fire — a real 2D temperature field simulation
-- LZX Industries Community FPGA Program
--
-- Not scrolling noise: a 256x64 4-bit TEMPERATURE GRID lives in EBR and is
-- re-simulated every field by semi-Lagrangian advection.  Each cell gathers
-- (bilinear) from where its parcel came from one field ago, moving through a
-- velocity field made of curl noise (divergence-free turbulence from the
-- analytic derivatives of two octaves of smoothstep value noise), buoyancy
-- (hot cells rise faster -> pointed, stretching tongues), and entrainment
-- (flow converges toward hotter neighbours -> tongues self-sharpen and
-- separate).  Parcels cool by a base rate plus a temperature-proportional
-- term plus a random grain; cool parcels linger as smoke.  A flickering
-- burner at the bottom row (or, in Luma Mod, every bright video cell)
-- injects heat.  Cells are stored as 4 bits with hash-dithered stochastic
-- rounding, so sub-level cooling rates still act on average.  The grid is
-- swept one row per display row, just behind the raster, with a one-row
-- delayed write-back, so ONE grid bank is enough: the raster always sees
-- last field's complete state while this field's is computed above it.
-- K2 Width compresses the turbulence/burner lattices horizontally: narrow,
-- dense tongues at full.  Streams narrower than 1536 px (SD, 720p) run the
-- sim and display at half horizontal resolution (128 cell pairs) to fit
-- 480i's 3.2k-clock row budget and the display reader's 6-px cell minimum.
--
-- Display: a 3-row cache feeds a smoothstep-bilinear upsample (7.5x17 px
-- cells at 1080p), then a 256-entry blackbody palette ROM (limited-range
-- 10-bit YUV, U/V swapped for hardware).  Blue Flame negates the chroma.
-- Output is gated to neutral outside active video; every per-field action
-- fires once per field even when analog vsync serrates.
--
-- v1.0.4 (2026-10-18): resolution scaling.  The half-resolution modes keep
-- the 1080p fire's proportions: their cells are wider relative to the screen
-- height (720p 2x, SD 1.5x on its 4:3 screen), so the lattice x step per cell
-- is scaled up by that ratio (eddies, tongues and burner pockets keep their
-- 1080p size) and the horizontal velocity terms (curl u, entrainment, wind)
-- are scaled down by it (same sideways motion relative to the screen).  The
-- cell grid itself stays coarser there (display reader limit).  1080p unchanged.
--

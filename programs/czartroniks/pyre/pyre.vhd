      -- second cycle of the vertical DDA: derive row, weight, slots, change
      -- pulse from the registered accumulator (one cycle was the critical path)
      -- (the '0' default lives at the top of the process: placed here it
      -- overrode the hsync set and the row pointer never advanced -> black)
      if s_ystep = '1' then
        s_d <= s_yacc(21 downto 16);
        s_wy <= C_SS6(to_integer(s_yacc(15 downto 10)));
        s_slotA <= mod3("0" & s_yacc(21 downto 16));
        s_slotB <= mod3(("0" & s_yacc(21 downto 16)) + 1);
        if s_yacc(21 downto 16) /= s_d then
          s_rowfirst <= '1';
          s_dpulse <= '1';
          s_dval <= "0" & s_yacc(21 downto 16);
        end if;
      end if;

      if data_in.vsync_n = '0' and s_prev_vsync_n = '1' then
        s_ember   <= registers_in(6)(0);
        s_lumamod <= registers_in(6)(1);
        s_blue    <= registers_in(6)(2);
        s_overlay <= registers_in(6)(3);
        s_bypass  <= registers_in(6)(4);
      end if;

      if s_vsedge = '1' then
        if s_lcount > 100 then s_lines <= s_lcount; end if;
        s_lcount <= (others => '0');
        -- half horizontal resolution below 1536 px (SD, 720p)
        if s_wmeas < 1536 then
          s_half <= '1'; s_xmask <= x"7F";
        else
          s_half <= '0'; s_xmask <= x"FF";
        end if;
        s_yacc <= (others => '0');
        s_d <= (others => '0');
        s_wy <= (others => '0');
        s_slotA <= "00";
        s_slotB <= "01";
        s_rowfirst <= '1';
        s_dpulse <= '1';
        s_dval <= (others => '0');
      end if;
    end if;
  end process p_time;

  -- ========================================================================
  -- Per-field constants: one serial shift-add multiplier (P12 Blaze:
  -- (1023 - K1) x P12 blends the fuel from the knob toward the full-screen
  -- climax) + one serial restoring divider (x and y DDA increments from the
  -- measured width / line count), then derive.
  -- ========================================================================
  p_boost : process(clk)
    variable v_acc : unsigned(19 downto 0);
    variable v_rem : unsigned(13 downto 0);
    variable v_fb : unsigned(12 downto 0);
    variable v_t : unsigned(8 downto 0);
    variable v_qb : std_logic;
    variable v_k2 : unsigned(9 downto 0);
    variable v_k1 : unsigned(9 downto 0);
    variable v_gt : signed(5 downto 0);
    variable v_kt : unsigned(7 downto 0);
    variable v_ke : unsigned(4 downto 0);
    variable v_wk : unsigned(6 downto 0);
    variable v_wx : signed(13 downto 0);
    variable v_k13 : unsigned(12 downto 0);
    variable v_k10 : unsigned(9 downto 0);
  begin
    if rising_edge(clk) then
      s_sdid <= '0';
      if registers_in(8)(1 downto 0) = "00" then s_sdid <= '1'; end if;
      case bst is
        when BI =>
          if s_vsedge = '1' then
            b_p12 <= unsigned(registers_in(7));
            -- K1 spans 0..86% of the raw fuel range (tuned on hardware as the useful 0..100)
            v_k1 := unsigned(registers_in(0)) - resize(unsigned(registers_in(0)(9 downto 3)), 10)
                  - resize(unsigned(registers_in(0)(9 downto 6)), 10);
            s_fbk <= v_k1;
            b_op <= to_unsigned(1023, 10) - v_k1;
            -- turbulence gain (K4 512 -> 32) and base rise (K6 512 -> 21
            -- sixteenths of a cell per field) follow their knobs directly
            v_kt := resize(unsigned(registers_in(3)(9 downto 4)), 8);
            s_kt <= v_kt;
            s_vb16 <= resize(unsigned(registers_in(5)(9 downto 5)), 7) + 5;
            -- K2 Width: lattice x step per cell 16..47 sixteenths (1x .. 3x
            -- horizontal compression of the turbulence and burner pockets)
            v_k2 := unsigned(registers_in(1));
            v_wk := resize(v_k2(9 downto 5), 7) + 16;
            -- K5 Plume: buoyancy + entrainment
            s_kb <= unsigned(registers_in(4)(9 downto 4));
            v_ke := unsigned(registers_in(4)(9 downto 5));
            s_ke <= v_ke;
            -- Resolution scaling: half-mode cells are wider relative to the
            -- screen height (720p 2x, SD 1.5x): lattice step per cell up,
            -- horizontal velocity gains down by the same ratio (2/3 ~ 21/32)
            if s_half = '0' then
              s_wk <= v_wk;
              s_wk2 <= v_wk & '0';
              s_ktu <= v_kt;
              s_keu <= v_ke;
            elsif s_sdid = '0' then
              s_wk <= v_wk(5 downto 0) & '0';
              s_wk2 <= v_wk(5 downto 0) & "00";
              s_ktu <= v_kt srl 1;
              s_keu <= v_ke srl 1;
            else
              s_wk <= v_wk + (v_wk srl 1);
              s_wk2 <= (resize(v_wk, 8) + resize(v_wk srl 1, 8)) sll 1;
              v_k13 := (resize(v_kt, 13) sll 4) + (resize(v_kt, 13) sll 2) + resize(v_kt, 13);
              s_ktu <= v_k13(12 downto 5);
              v_k10 := (resize(v_ke, 10) sll 4) + (resize(v_ke, 10) sll 2) + resize(v_ke, 10);
              s_keu <= v_k10(9 downto 5);
            end if;
            -- K3 Smoke: cool-regime decay (slow when high) and gray gain
            s_csm <= resize((to_unsigned(1023, 10) - unsigned(registers_in(2))) srl 6, 5) + 1;
            s_sgain <= unsigned(registers_in(2)(9 downto 2));
            b_bit <= "1001";
            b_acc <= (others => '0');
            bst <= BM;
          end if;
        when BM =>
          if b_p12(to_integer(b_bit)) = '1' then
            v_acc := (b_acc sll 1) + resize(b_op, 20);
          else
            v_acc := b_acc sll 1;
          end if;
          b_acc <= v_acc;
          if b_bit = 0 then
            b_fuel <= v_acc;
            -- divide 1: incx = cells * 2^16 / width (256, or 128 in half mode)
            if s_half = '1' then
              b_n <= to_unsigned(128, 25) sll 16;
            else
              b_n <= to_unsigned(256, 25) sll 16;
            end if;
            b_dv <= s_wmeas;
            b_rem <= (others => '0');
            b_qt <= (others => '0');
            b_cnt <= to_unsigned(24, 5);
            bst <= BD1;
          else
            b_bit <= b_bit - 1;
          end if;
        when BD1 | BD2 =>
          v_rem := (b_rem & b_n(24));
          b_n <= b_n sll 1;
          if v_rem >= resize(b_dv, 14) then
            b_rem <= resize(v_rem - resize(b_dv, 14), 13);
            b_qt <= b_qt(23 downto 0) & '1';
            v_qb := '1';
          else
            b_rem <= v_rem(12 downto 0);
            b_qt <= b_qt(23 downto 0) & '0';
            v_qb := '0';
          end if;
          if b_cnt = 0 then
            if bst = BD1 then
              s_incx <= b_qt(14 downto 0) & v_qb;
              bst <= BD2;
              -- divide 2: incy = 61 * 2^16 / lines (rows 62/63 = burner, off-screen)
              b_n <= to_unsigned(61, 25) sll 16;
              b_dv <= s_lines;
              b_rem <= (others => '0');
              b_qt <= (others => '0');
              b_cnt <= to_unsigned(24, 5);
            else
              s_incy <= b_qt(14 downto 0) & v_qb;
              bst <= BF;
            end if;
          else
            b_cnt <= b_cnt - 1;
          end if;
        when BF =>
          -- effective fuel = K1 + (1023 - K1) * P12 / 1024 (Blaze): cooling base
          -- 31..0 (0 = parcels only cool by T/32 + grain -> whole screen),
          -- burner level 32..255, burner pocket / luma amplitude 0.25x..1.25x
          v_fb := resize(s_fbk, 13) + resize(b_fuel(19 downto 10), 13);
          if v_fb > 1023 then v_fb := to_unsigned(1023, 13); end if;
          s_cbase <= resize((to_unsigned(1023, 10) - v_fb(9 downto 0)) srl 5, 6);
          v_t := resize(v_fb(9 downto 3), 9) + resize(v_fb(9 downto 3), 9) + 32;
          if v_t > 255 then v_t := to_unsigned(255, 9); end if;
          s_srcl <= v_t(7 downto 0);
          s_samp <= resize(v_fb(9 downto 3), 8) + 32;
          bst <= BF2;
        when BF2 =>
          -- advance the noise lattices: eddies ride up with the flow
          -- (separate state: the clamp->add chain was the critical path)
          s_scroll1 <= s_scroll1 + resize(s_vb16(6 downto 1), 16) + resize(s_vb16(6 downto 2), 16);
          s_scroll2 <= s_scroll2 + resize(s_vb16, 16) + resize(s_vb16(6 downto 2), 16);
          -- gusts: every 24..87 fields (0.4..1.5 s) draw a new wind target
          -- from a centre-weighted random (sum of two 4-bit LFSR nibbles - 15,
          -- scaled 3/4: -11..+11 sixteenths of a cell per field, straight most
          -- likely); the wind eases toward it (1/16 per field) and both lattice
          -- drifts ride it, so the fire leans left, right or stands straight
          if s_gcnt = 0 then
            v_gt := resize(signed(resize(unsigned(s_lfsr_q(3 downto 0)), 6))
                         + signed(resize(unsigned(s_lfsr_q(7 downto 4)), 6)) - 15, 6);
            s_wtgt <= v_gt - (v_gt sra 2);
            s_gcnt <= resize(unsigned(s_lfsr_q(13 downto 8)), 8) + 24;
          else
            s_gcnt <= s_gcnt - 1;
          end if;
          s_wacc <= s_wacc + (((resize(s_wtgt, 10) sll 4) - s_wacc) sra 4);
          s_wind <= s_wacc(9 downto 4);
          -- wind in the u sum: x1 / x1/2 (720p) / x21/32 (SD), rounded
          if s_half = '0' then
            s_windu <= s_wacc(9 downto 4);
          elsif s_sdid = '0' then
            v_wx := resize(s_wacc, 14) + 16;
            s_windu <= v_wx(10 downto 5);
          else
            v_wx := (resize(s_wacc, 14) sll 4) + (resize(s_wacc, 14) sll 2) + resize(s_wacc, 14) + 256;
            s_windu <= resize(v_wx(13 downto 9), 6);
          end if;
          s_drift1 <= s_drift1 + unsigned(resize(s_wind sra 2, 12));
          s_drift2 <= s_drift2 + unsigned(resize(s_wind sra 2, 12))
                    + unsigned(resize(s_wind sra 3, 12));
          s_dofs <= s_dofs + 37;
          bst <= BI;
      end case;
    end if;
  end process p_boost;

  -- ========================================================================
  -- Simulation sequencer.  Job(d): prefetch grid row prow(d) into cache slot
  -- mod3(d+2); simulate row d-1 (phase A: velocity, phase B: gather/cool/
  -- burn, 20 clocks per cell, two cells in flight); write back row d-2 from
  -- the new-row buffer.  Jobs 64 and 65 run after vsync (row 63 + flush,
  -- prefetching rows 0 and 1 for the next field).
  -- ========================================================================
  p_seq : process(clk)
    variable v_d2 : unsigned(6 downto 0);
    variable v_nx : unsigned(7 downto 0);
    variable v_p1y, v_p2y : unsigned(15 downto 0);
    variable v_a : signed(17 downto 0);
    variable v_v : signed(12 downto 0);
    variable v_u : signed(12 downto 0);
    variable v_by : unsigned(10 downto 0);
    variable v_bx : unsigned(11 downto 0);
    variable v_l : unsigned(8 downto 0);
    variable v_cool : unsigned(8 downto 0);
    variable v_tn : unsigned(8 downto 0);
    variable v_sr : signed(10 downto 0);
    variable v_fl : signed(9 downto 0);
    variable v_q : unsigned(12 downto 0);
  begin
    if rising_edge(clk) then
      -- default strobes
      g_we <= '0';
      nr_we <= '0';
      c_we <= '0';

      -- pending-job bookkeeping
      -- after vsync: run every job the raster did not reach (the screen
      -- covers rows 0..61; rows 62/63 and the flush/prefetch jobs follow)
      if s_vsedge = '1' then j_chain <= '1'; j_cnext <= resize(s_d, 7) + 1; end if;
      if s_dpulse = '1' then j_pendd <= '1'; j_pdval <= s_dval; end if;

      -- multiplier pipelines: operands registered -> two partial products
      -- (low 5 / high 5 bits of the b operand) -> sum.  Latency 3.
      ma_pl <= ma_a * signed('0' & ma_b(4 downto 0));
      ma_ph <= ma_a * ma_b(9 downto 5);
      ma_p <= resize(ma_pl, 21) + shift_left(resize(ma_ph, 21), 5);
      mb_pl <= mb_a * signed('0' & mb_b(4 downto 0));
      mb_ph <= mb_a * mb_b(9 downto 5);
      mb_p <= resize(mb_pl, 20) + shift_left(resize(mb_ph, 20), 5);
      -- hash pipeline
      h_a <= hash_a(h_cx, h_cy, h_seed);
      h_b <= hash_b(h_a);

      case jst is
        when J_IDLE =>
          if j_chain = '1' or j_pendd = '1' then
            if j_chain = '1' then
              j_d <= j_cnext;
              v_d2 := j_cnext;
              j_cnext <= j_cnext + 1;
              if j_cnext >= 65 then j_chain <= '0'; end if;
            else
              j_d <= j_pdval; j_pendd <= '0';
              v_d2 := j_pdval;
            end if;
            -- prefetch row: d+2 (clamped 63 at the bottom; 0, 1 for jobs 64/65)
            if v_d2 = 64 then j_prow <= (others => '0');
            elsif v_d2 = 65 then j_prow <= to_unsigned(1, 6);
            elsif v_d2 >= 62 then j_prow <= to_unsigned(63, 6);
            else j_prow <= resize(v_d2 + 2, 6); end if;
            j_slot <= mod3(v_d2 + 2);
            -- sim row d-1, write-back row d-2
            j_r <= resize(v_d2 - 1, 6);
            j_rw <= resize(v_d2 - 2, 6);
            if v_d2 >= 1 and v_d2 <= 64 then j_simen <= '1'; else j_simen <= '0'; end if;
            if v_d2 >= 2 and v_d2 <= 65 then j_wben <= '1'; else j_wben <= '0'; end if;
            -- cell count for this field's resolution
            if s_half = '1' then
              j_pend <= to_unsigned(128, 9); j_nend <= to_unsigned(131, 9);
            else
              j_pend <= to_unsigned(256, 9); j_nend <= to_unsigned(259, 9);
            end if;
            j_px <= (others => '0');
            j_pv1 <= '0'; j_pv2 <= '0'; j_pv3 <= '0';
            jst <= J_PRE;
          end if;

        when J_PRE =>
          -- grid row -> cache slot, 3-deep address/valid pipe
          g_raddr <= j_prow & gxa(j_px(7 downto 0), s_half);
          j_px1 <= gxa(j_px(7 downto 0), s_half); j_px2 <= j_px1; j_px3 <= j_px2;
          if j_px < j_pend then j_pv1 <= '1'; j_px <= j_px + 1; else j_pv1 <= '0'; end if;
          j_pv2 <= j_pv1; j_pv3 <= j_pv2;
          c_we <= j_pv3;
          c_waddr <= j_slot & j_px3;
          c_wd <= g_qf;
          if j_px >= j_pend and j_pv1 = '0' and j_pv2 = '0' and j_pv3 = '0' then
            j_n <= (others => '0');
            st <= (others => '0');
            -- lattice x accumulators start at cell -2
            p1x <= s_drift1 - resize(s_wk2, 12);
            p2x <= s_drift2 - resize(s_wk2, 12);
            jst <= J_CELLS;
          end if;

        when J_CELLS =>
          -- period counter / step counter
          if st = 19 then
            st <= (others => '0');
            p1x <= p1x + resize(s_wk, 12);
            p2x <= p2x + resize(s_wk, 12);
            if j_n = j_nend then
              jst <= J_IDLE;
            else
              j_n <= j_n + 1;
            end if;
          else
            st <= st + 1;
          end if;

          -- ------------------------------------------------------------
          -- Phase A: curl-noise velocity for cell a_x (steps 0..19, spills
          -- into steps 0..7 of the next period).  Multiplier latency 3.
          -- ------------------------------------------------------------
          case to_integer(st) is
            when 0 =>
              -- neighbour read T(r, x+1) for the entrainment window
              v_nx := (a_x + 1) and s_xmask;
              g_raddr <= j_r & gxa(v_nx, s_half);
              v_p1y := resize(j_r & "0000", 16) - s_scroll1;
              v_p2y := resize(j_r & "0000", 16) - s_scroll2 + x"0450";
              p1y <= v_p1y; p2y <= v_p2y;
              -- entrainment window shift: T0 of this cell was last period's Tr
              tl <= t0; t0 <= tr;
              -- spill (previous cell): entrainment product (issued 17)
              ue <= ma_p(16 downto 8);
              ma_a <= resize(b2_8, 11); ma_b <= signed(resize(dy2, 10));
            when 1 =>
              h_cx <= "000" & p1x(11 downto 7); h_cy <= p1y(14 downto 7); h_seed <= x"1234";
              lut_idx <= p1x(6 downto 0);
            when 2 =>
              h_cx <= "000" & (p1x(11 downto 7) + 1); h_cy <= p1y(14 downto 7);
              lut_idx <= p1y(6 downto 0);
              -- spill: dpxs = dpx1 + dpx2 (A2_8*Dx2 issued 19)
              dpxs <= resize(dpx1, 11) + resize(ma_p(16 downto 7), 11);
            when 3 =>
              h_cx <= "000" & p1x(11 downto 7); h_cy <= p1y(14 downto 7) + 1;
              lut_idx <= p2x(5 downto 0) & '0';
              tr <= g_qf;
              -- spill: dpys = dpy1 + dpy2 (B2_8*Dy2 issued 0)
              dpys <= resize(dpy1, 11) + resize(ma_p(16 downto 7), 11);
              ma_a <= resize(dpxs, 11); ma_b <= signed(resize(s_kt, 10));
            when 4 =>
              h_cx <= "000" & (p1x(11 downto 7) + 1); h_cy <= p1y(14 downto 7) + 1;
              lut_idx <= p2y(5 downto 0) & '0';
              c00_1 <= h_b;
              sx1 <= lut_qf(16 downto 8); dx1 <= lut_qf(7 downto 0);
              ma_a <= resize(dpys, 11); ma_b <= signed(resize(s_ktu, 10));
            when 5 =>
              h_cx <= "00" & p2x(11 downto 6); h_cy <= p2y(13 downto 6); h_seed <= x"8EEF";
              c10_1 <= h_b;
              sy1 <= lut_qf(16 downto 8); dy1 <= lut_qf(7 downto 0);
            when 6 =>
              h_cx <= "00" & (p2x(11 downto 6) + 1); h_cy <= p2y(13 downto 6);
              c01_1 <= h_b;
              sx2 <= lut_qf(16 downto 8); dx2 <= lut_qf(7 downto 0);
              -- spill: vertical velocity = buoyancy - kt * dpsi/dx, clamped 0..95
              v_v := signed(resize(vbuoy, 13)) - resize(ma_p(20 downto 8), 13);
              if v_v < 0 then v16 <= (others => '0');
              elsif v_v > 95 then v16 <= to_unsigned(95, 7);
              else v16 <= unsigned(v_v(6 downto 0)); end if;
            when 7 =>
              h_cx <= "00" & p2x(11 downto 6); h_cy <= p2y(13 downto 6) + 1;
              c11_1 <= h_b;
              sy2 <= lut_qf(16 downto 8); dy2 <= lut_qf(7 downto 0);
              -- spill: horizontal velocity = kt * dpsi/dy + entrainment, clamped
              v_u := resize(ue, 13) + resize(ma_p(20 downto 8), 13) + resize(s_windu, 13);
              if v_u < -127 then u16 <= to_signed(-127, 8);
              elsif v_u > 127 then u16 <= to_signed(127, 8);
              else u16 <= v_u(7 downto 0); end if;
            when 8 =>
              h_cx <= "00" & (p2x(11 downto 6) + 1); h_cy <= p2y(13 downto 6) + 1;
              c00_2 <= h_b;
              da1 <= (signed(resize(c11_1, 10)) - signed(resize(c01_1, 10)))
                   - (signed(resize(c10_1, 10)) - signed(resize(c00_1, 10)));
              e10_1 <= signed(resize(c10_1, 9)) - signed(resize(c00_1, 9));
              e01_1 <= signed(resize(c01_1, 9)) - signed(resize(c00_1, 9));
            when 9 =>
              -- per-cell rounding dither hash (fixed pattern + slow phase)
              h_cx <= a_x; h_cy <= "00" & j_r; h_seed <= x"5A5A";
              c10_2 <= h_b;
              ma_a <= resize(da1, 11); ma_b <= signed('0' & sy1);
            when 10 =>
              c01_2 <= h_b;
              ma_a <= resize(da1, 11); ma_b <= signed('0' & sx1);
            when 11 =>
              c11_2 <= h_b;
              ma_a <= signed(resize(x17(t0), 11)); ma_b <= signed(resize(s_kb, 10));
            when 12 =>
              dth <= h_b + s_dofs;
              da2 <= (signed(resize(c11_2, 10)) - signed(resize(c01_2, 10)))
                   - (signed(resize(c10_2, 10)) - signed(resize(c00_2, 10)));
              e10_2 <= signed(resize(c10_2, 9)) - signed(resize(c00_2, 9));
              e01_2 <= signed(resize(c01_2, 9)) - signed(resize(c00_2, 9));
              v_a := (resize(e10_1, 18) sll 8) + resize(ma_p, 18);
              a1_8 <= v_a(17 downto 8);
            when 13 =>
              v_a := (resize(e01_1, 18) sll 8) + resize(ma_p, 18);
              b1_8 <= v_a(17 downto 8);
              ma_a <= resize(a1_8, 11); ma_b <= signed(resize(dx1, 10));
            when 14 =>
              -- buoyancy: vb16 + T0*kb/256  (kb 63 -> 4 cells at T 255)
              vbuoy <= resize(s_vb16, 8) + resize(unsigned(ma_p(13 downto 8)), 8);
              ma_a <= resize(b1_8, 11); ma_b <= signed(resize(dy1, 10));
            when 15 =>
              ma_a <= resize(da2, 11); ma_b <= signed('0' & sy2);
            when 16 =>
              dpx1 <= ma_p(16 downto 7);
              ma_a <= resize(da2, 11); ma_b <= signed('0' & sx2);
            when 17 =>
              dpy1 <= ma_p(16 downto 7);
              ma_a <= resize(signed(resize(x17(tr), 9)) - signed(resize(x17(tl), 9)), 11);
              ma_b <= signed(resize(s_keu, 10));
            when 18 =>
              v_a := (resize(e10_2, 18) sll 8) + resize(ma_p, 18);
              a2_8 <= v_a(17 downto 8);
            when 19 =>
              v_a := (resize(e01_2, 18) sll 8) + resize(ma_p, 18);
              b2_8 <= v_a(17 downto 8);
              ma_a <= resize(a2_8, 11); ma_b <= signed(resize(dx2, 10));
              -- copies for phase B: octave-2 corners (burner), dither (2 deep)
              cb00 <= c00_2; cb10 <= c10_2; cb01 <= c01_2; cb11 <= c11_2;
              sxb <= sx2; syb <= sy2;
              dthb <= dth; dthb2 <= dthb;
            when others => null;
          end case;

          -- ------------------------------------------------------------
          -- Phase B: gather / cool / burn for cell b_x (= n-1 in period
          -- n+... : uses u16/v16 of the previous period's phase A from step
          -- 8), finishing at step 5 of the period after (cell a_x there).
          -- ------------------------------------------------------------
          case to_integer(st) is
            when 0 =>
              -- write-back of the previous row reads cell n-1: its NEW value
              -- lands at step 5 of period n+3, so the old row's value is still
              -- intact (reading n-3 fetched the finished new row -> the grid
              -- shifted up one row per field)
              nr_raddr <= w_x;
              -- late phase (cell c_x): vertical lerp of the gather
              mb_a <= signed(resize(lt1, 10)) - signed(resize(lt0, 10));
              mb_b <= signed(resize(gfy4, 10));
            when 1 =>
              mb_a <= signed(resize(cb10, 10)) - signed(resize(cb00, 10));
              mb_b <= signed('0' & sxb);
            when 2 =>
              mb_a <= signed(resize(cb11, 10)) - signed(resize(cb01, 10));
              mb_b <= signed('0' & sxb);
            when 3 =>
              -- write back last row's cell (read from the new-row buffer at 0)
              if j_wben = '1' and j_n >= 1 and j_n <= j_pend then
                g_we <= '1';
                g_waddr <= j_rw & gxa(w_x, s_half);
                g_wd <= nr_qf;
              end if;
              -- luma fuel for this cell (bank of the sim row = not the display row's)
              if j_d(0) = '1' then fuelv <= f0_qf(9 downto 2); else fuelv <= f1_qf(9 downto 2); end if;
              -- late phase: advected temperature
              v_l := unsigned(resize(signed(resize(lt0, 10)) + resize(mb_p(13 downto 4), 10), 9));
              tadv <= v_l(7 downto 0);
            when 4 =>
              -- half mode: the odd column is a copy
              if j_wben = '1' and j_n >= 1 and j_n <= j_pend and s_half = '1' then
                g_we <= '1';
                g_waddr <= j_rw & (w_x(6 downto 0) & '1');
                g_wd <= nr_qf;
              end if;
              q0 <= cb00 + unsigned(mb_p(15 downto 8));
              -- late phase: cooling (fire regime = base + T/32 + grain; smoke = csm + grain)
              if tadv >= 40 then
                v_cool := resize(s_cbase, 9) + resize(tadv(7 downto 5), 9)
                        + resize(unsigned(s_lfsr_q(11 downto 10)), 9);
              else
                v_cool := resize(s_csm, 9) + resize(unsigned(s_lfsr_q(11 downto 10)), 9);
              end if;
              if resize(tadv, 9) > v_cool then tn1 <= tadv - v_cool(7 downto 0);
              else tn1 <= (others => '0'); end if;
            when 5 =>
              q1 <= cb01 + unsigned(mb_p(15 downto 8));
              -- late phase: burner (bottom two rows) / Luma Mod fuel / embers
              v_tn := resize(tn1, 9);
              if s_lumamod = '1' then
                if lsrc > tn1 then v_tn := resize(lsrc, 9); end if;
              else
                if j_r = 63 then
                  if src > tn1 then v_tn := resize(src, 9); end if;
                elsif j_r = 62 then
                  if src > 32 and (src - 32) > tn1 then v_tn := resize(src - 32, 9); end if;
                end if;
              end if;
              if s_ember = '1' and s_lfsr_q(15 downto 5) = "00000000000" then
                v_tn := to_unsigned(200, 9);
              end if;
              -- the value finished here was gathered in the previous period for
              -- cell b_x = n-4 (writing it to a_x = n-2 shifted the whole field
              -- two cells to the right every field)
              if j_simen = '1' and j_n >= 4 and j_n <= j_pend + 3 then nr_we <= '1'; end if;
              nr_waddr <= c_x;
              -- stochastic rounding to 4 bits: (t*15 + dither) / 256
              v_q := resize(v_tn(7 downto 0) & "0000", 13) - resize(v_tn(7 downto 0), 13)
                   + resize(dthb2, 13);
              nr_wd <= v_q(11 downto 8);
            when 6 =>
              mb_a <= signed(resize(q1, 10)) - signed(resize(q0, 10));
              mb_b <= signed('0' & syb);
            when 7 =>
              -- Luma Mod injection: (luma8 - 96) * amp
              mb_a <= signed(resize(fuelv, 10)) - 96;
              mb_b <= signed(resize(s_samp, 10));
            when 8 =>
              -- back-trace: by = r*16 + v16 (down), bx = x*16 - u16
              v_by := resize(j_r & "0000", 11) + resize(v16, 11);
              if v_by(10 downto 4) > 63 then gyi <= to_unsigned(63, 6);
              else gyi <= v_by(9 downto 4); end if;
              if v_by(10 downto 4) >= 63 then gyi1 <= to_unsigned(63, 6);
              else gyi1 <= v_by(9 downto 4) + 1; end if;
              gfy4 <= v_by(3 downto 0);
              v_bx := unsigned(signed(resize(b_x & "0000", 12)) - resize(u16, 12));
              gx <= v_bx(11 downto 4) and s_xmask;
              gfx4 <= v_bx(3 downto 0);
            when 9 =>
              g_raddr <= gyi & gxa(gx, s_half);
              psi <= q0 + unsigned(mb_p(15 downto 8));
            when 10 =>
              g_raddr <= gyi & gxa((gx + 1) and s_xmask, s_half);
              -- luma injection = clamp((luma8-96)*amp/128, 0..255)
              v_fl := resize(mb_p(17 downto 7), 10);
              if v_fl < 0 then lsrc <= (others => '0');
              elsif v_fl > 255 then lsrc <= (others => '1');
              else lsrc <= unsigned(v_fl(7 downto 0)); end if;
              -- burner pocket term: (psi-128) * amp
              mb_a <= signed(resize(psi, 10)) - 128;
              mb_b <= signed(resize(s_samp, 10));
            when 11 =>
              g_raddr <= gyi1 & gxa(gx, s_half);
            when 12 =>
              g_raddr <= gyi1 & gxa((gx + 1) and s_xmask, s_half);
              t00 <= x17(g_qf);
            when 13 =>
              t10 <= x17(g_qf);
              -- burner level: srcl + (psi-128)*amp/128 + random 0..31
              v_sr := resize(signed(resize(s_srcl, 9)), 11)
                    + resize(mb_p(17 downto 7), 11)
                    + resize(signed(resize(unsigned(s_lfsr_q(4 downto 0)), 9)), 11);
              if v_sr < 0 then src <= (others => '0');
              elsif v_sr > 255 then src <= (others => '1');
              else src <= unsigned(v_sr(7 downto 0)); end if;
            when 14 =>
              t01 <= x17(g_qf);
              mb_a <= signed(resize(t10, 10)) - signed(resize(t00, 10));
              mb_b <= signed(resize(gfx4, 10));
            when 15 =>
              t11 <= x17(g_qf);
            when 16 =>
              mb_a <= signed(resize(t11, 10)) - signed(resize(t01, 10));
              mb_b <= signed(resize(gfx4, 10));
            when 17 =>
              v_l := unsigned(resize(signed(resize(t00, 10)) + resize(mb_p(13 downto 4), 10), 9));
              lt0 <= v_l(7 downto 0);
            when 19 =>
              v_l := unsigned(resize(signed(resize(t01, 10)) + resize(mb_p(13 downto 4), 10), 9));
              lt1 <= v_l(7 downto 0);
            when others => null;
          end case;
      end case;
    end if;
  end process p_seq;

  -- cell indices: phase A cell = n-2, phase B cell = n-3 (sim-x units)
  a_x <= resize(j_n - 2, 8) and s_xmask;
  b_x <= resize(j_n - 3, 8) and s_xmask;
  c_x <= resize(j_n - 4, 8) and s_xmask;      -- late-phase (final write) cell
  w_x <= resize(j_n - 1, 8) and s_xmask;      -- write-back cell

  -- fuel bank read addresses: the display's accumulator reads bank(d parity)
  -- one cell ahead, the sim reads the other bank at its own cell
  f0_raddr <= cx1 + 1 when s_d(0) = '0' else b_x;
  f1_raddr <= b_x when s_d(0) = '0' else cx1 + 1;

  -- ========================================================================
  -- Display stage 1: horizontal DDA, cache reader, fuel accumulator
  -- ========================================================================
  p_d1 : process(clk)
    variable v_xn : unsigned(23 downto 0);
    variable v_fd, v_fa : signed(10 downto 0);
    variable v_cross : std_logic;
  begin
    if rising_edge(clk) then
      -- --- horizontal DDA (restarts every line) ---
      if data_in.hsync_n = '0' and s_prev_hsync_n = '1' then
        x_acc <= (others => '0');
        cx1 <= (others => '0');
        cx1p <= (others => '0');
        cr_pre <= (others => '0');
      elsif data_in.avid = '1' then
        v_xn := x_acc + resize(s_incx, 24);
        x_acc <= v_xn;
        cx1 <= v_xn(23 downto 16);
        fx1 <= v_xn(15 downto 8);
      end if;
      d_y1 <= unsigned(data_in.y);
      cx1p <= cx1;
      v_cross := '0';
      if cx1 /= cx1p then v_cross := '1'; end if;
      fx2 <= fx1;

      -- --- cache reader: 6-read preload after hsync, then free-running cx+2 ---
      cr_ph <= not cr_ph;
      cr_v1 <= '0';
      if cr_pre /= 15 then
        -- preload: tags 0..5 = curA curB nextA nextB nx2A nx2B at cx0, cx0+1, cx0+2
        case cr_pre is
          when "0000" => c_raddr <= s_slotA & gxa(cx1, s_half); cr_tag1 <= "000"; cr_v1 <= '1';
          when "0001" => c_raddr <= s_slotB & gxa(cx1, s_half); cr_tag1 <= "001"; cr_v1 <= '1';
          when "0010" => c_raddr <= s_slotA & gxa(cx1 + 1, s_half); cr_tag1 <= "010"; cr_v1 <= '1';
          when "0011" => c_raddr <= s_slotB & gxa(cx1 + 1, s_half); cr_tag1 <= "011"; cr_v1 <= '1';
          when "0100" => c_raddr <= s_slotA & gxa(cx1 + 2, s_half); cr_tag1 <= "100"; cr_v1 <= '1';
          when "0101" => c_raddr <= s_slotB & gxa(cx1 + 2, s_half); cr_tag1 <= "101"; cr_v1 <= '1';
          when others => null;
        end case;
        cr_pre <= cr_pre + 1;
      else
        if cr_ph = '0' then
          c_raddr <= s_slotA & gxa(cx1 + 2, s_half); cr_tag1 <= "100";
        else
          c_raddr <= s_slotB & gxa(cx1 + 2, s_half); cr_tag1 <= "101";
        end if;
        cr_v1 <= '1';
      end if;
      cr_tag2 <= cr_tag1; cr_tag3 <= cr_tag2;
      cr_v2 <= cr_v1; cr_v3 <= cr_v2;

      -- crossing: shift the cell window (cur <- next <- next2)
      if v_cross = '1' and cr_pre = 15 then
        curA <= nextA; curB <= nextB;
        nextA <= nx2A; nextB <= nx2B;
      end if;
      -- returning reads (data valid 3 clocks after the address register)
      if cr_v3 = '1' then
        case cr_tag3 is
          when "000" => curA <= x17(c_qf);
          when "001" => curB <= x17(c_qf);
          when "010" => nextA <= x17(c_qf);
          when "011" => nextB <= x17(c_qf);
          when "100" => nx2A <= x17(c_qf);
          when others => nx2B <= x17(c_qf);
        end case;
      end if;

      -- --- Luma Mod fuel accumulator: one-pole IIR per cell, banked by row parity ---
      f_we0 <= '0'; f_we1 <= '0';
      if s_d(0) = '0' then f_next <= f0_qf; else f_next <= f1_qf; end if;
      if data_in.avid = '1' or s_prev_avid = '1' then
        if v_cross = '1' or (data_in.avid = '0' and s_prev_avid = '1') then
          -- commit the finished cell
          f_waddr <= cx1p;
          f_wd <= f_acc;
          if s_d(0) = '0' then f_we0 <= '1'; else f_we1 <= '1'; end if;
          if s_rowfirst = '1' then f_acc <= d_y1; else f_acc <= f_next; end if;
        else
          v_fd := signed(resize(d_y1, 11)) - signed(resize(f_acc, 11));
          v_fa := signed(resize(f_acc, 11)) + (v_fd sra 3);
          f_acc <= unsigned(v_fa(9 downto 0));
        end if;
      end if;
    end if;
  end process p_d1;

  -- ========================================================================
  -- Display stages 3..12: smoothstep bilinear, palette, compose
  -- ========================================================================
  p_d2 : process(clk)
    variable v_ha, v_hb, v_t : signed(10 downto 0);
    variable v_cu, v_cv : unsigned(10 downto 0);
  begin
    if rising_edge(clk) then
      -- c3: horizontal deltas + weight
      dA3 <= signed(resize(nextA, 9)) - signed(resize(curA, 9));
      dB3 <= signed(resize(nextB, 9)) - signed(resize(curB, 9));
      cA3 <= curA; cB3 <= curB;
      wx3 <= C_SS6(to_integer(fx2(7 downto 2)));
      -- c4: products
      mA4 <= dA3 * signed('0' & wx3);
      mB4 <= dB3 * signed('0' & wx3);
      cA4 <= cA3; cB4 <= cB3;
      -- c5: horizontal lerps
      v_ha := signed(resize(cA4, 11)) + resize(mA4(14 downto 6), 11);
      v_hb := signed(resize(cB4, 11)) + resize(mB4(14 downto 6), 11);
      ha5 <= unsigned(v_ha(7 downto 0));
      hb5 <= unsigned(v_hb(7 downto 0));
      -- c6: vertical delta
      dv6 <= signed(resize(hb5, 9)) - signed(resize(ha5, 9));
      ha6 <= ha5;
      -- c7: product with the per-line weight
      mv7 <= dv6 * signed('0' & s_wy);
      ha7 <= ha6;
      -- c8: temperature at this pixel
      v_t := signed(resize(ha7, 11)) + resize(mv7(14 downto 6), 11);
      t8 <= unsigned(v_t(7 downto 0));
      -- c9: palette ROM read; smoke gray product; flags
      pal9 <= C_PAL(to_integer(t8));
      sm9 <= t8(5 downto 0) * s_sgain;
      if t8 >= 40 then fire9 <= '1'; else fire9 <= '0'; end if;
      if t8 < 40 and t8 >= 4 then smk9 <= '1'; else smk9 <= '0'; end if;
      -- c10: fabric hop off the ROM; gray luma 64 + T*gain/64
      pal10 <= pal9;
      gray10 <= to_unsigned(64, 10) + resize(sm9(13 downto 6), 10);
      fire10 <= fire9; smk10 <= smk9;
      -- c11: colour (Blue Flame = negated chroma: yellow->blue, red->cyan)
      y11 <= unsigned(pal10(29 downto 20));
      v_cu := resize(unsigned(pal10(19 downto 10)), 11);
      v_cv := resize(unsigned(pal10(9 downto 0)), 11);
      if s_blue = '1' then
        v_cu := to_unsigned(1024, 11) - v_cu;
        v_cv := to_unsigned(1024, 11) - v_cv;
      end if;
      u11 <= v_cu(9 downto 0);
      v11 <= v_cv(9 downto 0);
      gray11 <= gray10;
      fire11 <= fire10; smk11 <= smk10;
    end if;
  end process p_d2;

  -- c12: compose + blanking gate
  p_out : process(clk)
    variable v_vy, v_vu, v_vv : unsigned(9 downto 0);
  begin
    if rising_edge(clk) then
      v_vy := unsigned(vd_qb(29 downto 20));
      v_vu := unsigned(vd_qb(19 downto 10));
      v_vv := unsigned(vd_qb( 9 downto  0));

      if sync_avid(C_LATENCY - 2) = '0' then
        -- BLANKING GATE: neutral black outside active video
        y12 <= to_unsigned(64, 10);
        u12 <= to_unsigned(512, 10);
        v12 <= to_unsigned(512, 10);
      elsif s_overlay = '1' then
        if fire11 = '1' then
          y12 <= y11; u12 <= u11; v12 <= v11;
        elsif smk11 = '1' and gray11 > (to_unsigned(80, 10)
                         + (unsigned(s_lfsr_p(1 downto 0)) & "00")) then
          -- smoke 50/50 with the video, chroma halfway to neutral
          y12 <= ('0' & gray11(9 downto 1)) + ('0' & v_vy(9 downto 1));
          u12 <= to_unsigned(256, 10) + ('0' & v_vu(9 downto 1));
          v12 <= to_unsigned(256, 10) + ('0' & v_vv(9 downto 1));
        else
          y12 <= v_vy; u12 <= v_vu; v12 <= v_vv;
        end if;
      else
        if smk11 = '1' and gray11 > y11 then
          y12 <= gray11;
          u12 <= to_unsigned(512, 10);
          v12 <= to_unsigned(512, 10);
        else
          y12 <= y11; u12 <= u11; v12 <= v11;
        end if;
      end if;
    end if;
  end process p_out;

  -- ========================================================================
  -- Output
  -- ========================================================================
  data_out.y <= data_in.y when s_bypass = '1' else std_logic_vector(y12);
  data_out.u <= data_in.u when s_bypass = '1' else std_logic_vector(u12);
  data_out.v <= data_in.v when s_bypass = '1' else std_logic_vector(v12);
  data_out.hsync_n <= data_in.hsync_n when s_bypass = '1' else sync_hs(C_LATENCY - 1);
  data_out.vsync_n <= data_in.vsync_n when s_bypass = '1' else sync_vs(C_LATENCY - 1);
  data_out.field_n <= data_in.field_n;
  data_out.avid    <= data_in.avid when s_bypass = '1' else sync_avid(C_LATENCY - 1);

end architecture pyre;

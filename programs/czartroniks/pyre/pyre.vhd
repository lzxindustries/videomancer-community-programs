  -- 12-bit two-add value hash (inferno family), split across two stages
  function hash_a(cx, cy : unsigned(7 downto 0); seed : unsigned(15 downto 0))
    return unsigned is
    variable h16 : unsigned(15 downto 0);
    variable h : unsigned(11 downto 0);
  begin
    h16 := (cx & cy) xor seed;
    h16 := h16 xor (x"0" & h16(15 downto 4));
    h := h16(11 downto 0);
    return h + rotate_left(h, 5);
  end function;

  function hash_b(hin : unsigned(11 downto 0)) return unsigned is
    variable h : unsigned(11 downto 0);
  begin
    h := hin xor rotate_left(hin, 9);
    h := h + rotate_left(h, 3);
    h := h xor ("00000" & h(11 downto 5));
    return h(9 downto 2);
  end function;

  function mod3(d : unsigned(6 downto 0)) return unsigned is
  begin
    return C_MOD3(to_integer(d));
  end function;

  -- 4-bit cell -> 8-bit (x17)
  function x17(t : unsigned(3 downto 0)) return unsigned is
    variable r : unsigned(7 downto 0);
  begin
    r := t & t;
    return r;
  end function;

  -- grid-x address from a cell index (half mode: even columns)
  function gxa(x : unsigned(7 downto 0); half : std_logic) return unsigned is
    variable r : unsigned(7 downto 0);
  begin
    if half = '1' then r := x(6 downto 0) & '0'; else r := x; end if;
    return r;
  end function;


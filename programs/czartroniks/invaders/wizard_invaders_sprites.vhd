-- ============================================================
-- wizard_invaders_sprites.vhd
-- Sprite ROM package - Wizard Space Invaders for LZX Videomancer
--
-- 1-bit sprites. 1 = lit pixel, 0 = transparent.
-- Row 0 = top scanline. In each row vector the MSB (highest
-- index) is the leftmost pixel, bit 0 is the rightmost pixel.
--
-- To draw a sprite at screen origin (ox, oy):
--   if sx in [ox, ox+W) and sy in [oy, oy+H):
--     bit := SPRITE( sy-oy )( (W-1) - (sx-ox) );
--     if bit = 1 then output sprite colour; else passthrough.
--
-- Animated sprites have _F0/_F1[/_F2/_F3] frames. Drive the
-- frame index from a slow free-running counter.
--
-- Sprite inventory:
--   WIZARD               128x128  1 frame
--   GHOST                 48x48   2 frames
--   MITE                  48x48   2 frames
--   WORM                  48x48   2 frames
--   CRAWLER               48x48   2 frames
--   GREMLIN               48x48   2 frames
--   CRT_TV                64x64   2 frames
--   WAND_SHOT              8x16   1 frame
--   VIDEOMANCER_BUNKER   128x112  1 frame
--   EXPLOSION             48x48   4 frames
-- ============================================================


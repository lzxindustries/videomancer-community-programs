-- DVD Logo Bouncer (multi-logo) v1.0
--
-- v1.0.2 (2026-10-17): resolution scaling.  Positions, walls, speed, logo
-- size and the corner tolerance are in virtual 1080-line units: the beam
-- accumulators step per pixel / per field line by the video-timing-ID steps
-- (registers_in(8)) times the logo step -- 1.0 at 1080p (identical to
-- before), 1.5 at 720p, and at SD 2.0 across (a 1440-wide 4:3 window) and
-- 1080/486 per frame line (interlaced fields step two frame lines; the
-- bottom-field half-step offset keys on field_n, which the cores tie high,
-- so on hardware it is inert and SD fields are line-doubled).  So the logo
-- is the same size relative to screen height in every mode and unstretched
-- at SD, and the measured walls are in the same units (SD 1440 x 1080).  The SD 1.25x size
-- cap is gone: 3x (1152 x 522) fits the 1440 x 1080 SD window.  Away from
-- 1080p a logo can step up to 4 logo px per screen px (SD 0.5x), so the ROM
-- prefetch leads by 6 px there instead of 8 (8 only holds to 2.29).
-- Parked logos 1/3 enter 480 units left of the right wall (1440 at HD).
--
-- Up to 4 instances of a 384 x 174 1-bit "DVD VIDEO" bitmap drift across the
-- screen, bouncing off the active-area edges and off each other.  Each wall
-- hit and each new logo-on-logo collision advances that logo's color index
-- through an 8-color palette.  A CORNER hit (a wall bounce while within
-- C_CORNER_TOL px of the perpendicular wall) sets off a ~2 s party: every
-- logo strobes through the palette.
--
-- The bitmap lives in dvdlogo_logo_pkg.C_LOGO_ROM (auto-generated by
-- dvdlogo.py from dvd_logo_source.png), shared across all instances.
-- Address = row * 24 + (col >> 4); leftmost pixel of each word is the MSB.
-- Yosys infers ~17 iCE40 BRAMs.
--
-- Bitmap access — streaming prefetch.  Each logo consumes one 16-bit ROM
-- word per 16 pixels, so the single ROM read port is round-robined across
-- the 4 logos (slot = h_count mod 4).  Each slot fetches, 8 px ahead of the
-- beam, the word that logo is about to need into a 2-entry (even/odd word
-- index) per-logo buffer.  Every logo therefore has its own bitmap bit at
-- every pixel: overlapping logos never occlude each other with the black
-- rectangle of their bounding box — only lit glyph pixels count.
-- (Caveat: no prefetch slots exist left of h_count 0, so while a logo is
-- within ~8 px of the LEFT wall its first word can be one line stale — a
-- few-pixel sliver, only during wall contact.)
--
-- Overlap behavior (S11):
--   Bounce : logos collide.  Each colliding pair is pushed apart along the
--            axis of LEAST penetration only (the other axis keeps its
--            direction); where logos overlap visually, the lowest-index LIT
--            logo wins the color.
--   Mix    : logos pass through each other; where lit glyph pixels overlap
--            their palette colors mix additively (Y offsets sum, U/V offsets
--            sum, clamped to Y <= 768 and legal chroma).
--
-- Motion: positions are 13.8 fixed point.  P12 Speed sets the master speed
-- on an exponential curve (0.125 .. 32 px/frame); K1 Angle splits it between
-- X and Y (weights 25..100%, always summing to 125%).
--
-- Size (K2, 0.5x .. 3x of 384 x 174 virtual 1080-line units, every mode):
-- the renderer works in LOGO space.  One shared accumulator per axis
-- holds h_count * step and v_count * step (step = 1/scale, Q12, from a
-- serial divider); each logo adds a per-frame offset C_i = -x_i * step
-- (serial multiplier), so the per-pixel cost is one add per logo per axis —
-- the same as the unscaled delta it replaces.  The prefetch uses a second
-- H accumulator preloaded with 8 * step (its 8-px lead).  Scale and step
-- are latched together once per field; the knob is deadbanded and glided.
-- Prefetch stays correct down to 0.5x: a word then spans 8 screen px, so the
-- 8-px lead never reaches the word two ahead (same buffer parity).  (720p
-- and SD step up to 3 / 4 logo px per screen px; their 6-px lead keeps the
-- newest available fetch within 4 px, i.e. at most one word ahead.)
--
-- Physics (4-phase FSM, runs once per field on a vsync that follows active
-- video — analog vsync serrates, so a bare vsync_start can fire repeatedly).
-- Pause still runs it at zero velocity so a resized logo is kept on screen,
-- but commits no direction, colour or party changes.
--   Phase 0 : predict each logo's new position (21-bit add), then wait
--             1024 clocks so this field's logo size has been published
--   Phase 1 : clamp + wall bounce + near-wall flags (corner detection).  A
--             wall contact only counts as a bounce (colour, corner) when it
--             reverses the logo — a growing logo shoved off a wall doesn't
--   Phase 2 : serial pair engine, one pair per clock, 5-stage pipe:
--             fetch -> deltas -> abs -> hit/penetration diff -> accumulate
--             (no hits in Mix mode)
--   Phase 3 : commit positions, set separating directions on collision
--             axes, advance colors, trigger the corner party
--
-- Per-frame products (velocity = speed x weight, palette x brightness,
-- logo screen size, per-logo logo-space offsets) run on ONE serial
-- shift-add multiplier cycling 32 slots continuously.
--
-- Render pipeline (per pixel):
--   1 clk : timing_gen
--   1 clk : pixel_counter
--   1 clk : S1  — register H/V accumulators + per-logo offset snapshot
--   1 clk : S2a — 4 x logo-space (lx, ly) = accumulator + offset
--   1 clk : S2b — 4 x in-logo flags AND per-logo bitmap bit → lit flags
--   1 clk : S3  — gate per-logo palette contributions by lit flags
--   1 clk : S4  — pairwise sums + pairwise priority selects
--   1 clk : S5  — Bounce: priority pick / Mix: final sum + clamp
--   1 clk : S6  — re-bias offsets to Y / U / V codes
--   1 clk : out — wet select + blanking gate
--   total : 10 clocks (single latency in every mode)
--
-- Parameters:
--   reg(0)    : Angle     (shallow .. steep: Y weight 25..100%, X = 125% - Y)
--   reg(1)    : Size      (0.5x .. 3x, deadbanded + glided)
--   reg(2)    : Count     (top 2 bits → 1, 2, 3 or 4 active logos)
--   reg(3)    : Clr Step  (top 3 bits: step 1..7 per bounce, 8th = random)
--   reg(4)    : Tint      (top 3 bits: rotates the 8-color palette)
--   reg(5)    : Bright    (logo brightness 25..100%, both color modes)
--   reg(6)(0) : Color     (0 = mono: palette luma only, 1 = palette)
--   reg(6)(1) : Matte     (logo = window onto video over a black BG,
--                          a black knockout over a video BG)
--   reg(6)(2) : BG        (0 = passthrough, 1 = solid black)
--   reg(6)(3) : Pause     (1 = freeze position + color)
--   reg(6)(4) : Overlap   (0 = logos bounce off each other, 1 = pass
--                          through + colors mix where glyphs overlap)
--   reg(7)    : Speed     (master speed, exponential)

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

library work;
use work.all;
use work.core_pkg.all;
use work.video_timing_pkg.all;

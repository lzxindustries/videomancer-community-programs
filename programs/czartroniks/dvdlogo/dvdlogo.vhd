architecture dvdlogo of program_top is
    -- IO-align pad: 2 register stages after the program's own output so the
    -- data_in -> data_out latency (10 + 2 = 12 clocks) is a multiple of 4,
    -- as the SDK requires; must match processing_delay_clks in the TOML.
    constant C_PROCESSING_DELAY_CLKS : natural := 12;
    signal s_io_align_in : t_video_stream_yuv444_30b;
    type t_io_align_pad is array (0 to 1) of t_video_stream_yuv444_30b;
    signal s_io_align_pad : t_io_align_pad;

    -- ========================================================================
    -- Constants
    -- ========================================================================
    constant C_CHROMA_MID : unsigned(9 downto 0) := to_unsigned(512, 10);
    constant C_Y_BLACK    : unsigned(9 downto 0) := to_unsigned(64, 10);
    constant C_DELAY      : integer := 9;       -- 1 timing + 1 px_ctr + 7 stages
    constant N_LOGOS      : integer := 4;
    constant N_PAIRS      : integer := 6;       -- C(4,2) = 6

    -- Logo-space coordinates are Q6 (C_QF fraction bits), 20-bit signed:
    -- integer part = (19 downto 6); word bit = int(3:0); parity = int(4).
    constant C_QF         : integer := 6;

    constant C_CORNER_TOL : integer := 16;      -- virtual units from the far wall = corner
    constant C_Y_OFF_MAX  : integer := 704;     -- drawn luma cap: 64 + 704 = 768
    constant C_C_OFF_MAX  : integer := 448;     -- legal chroma: 512 +/- 448

    -- Pair index → (i, j).  Pair k covers (i_of(k), j_of(k)) with i < j.
    type t_pair_idx is array (0 to N_PAIRS - 1) of integer range 0 to N_LOGOS - 1;
    constant C_PAIR_I : t_pair_idx := (0, 0, 0, 1, 1, 2);
    constant C_PAIR_J : t_pair_idx := (1, 2, 3, 2, 3, 3);

    -- ========================================================================
    -- Per-logo state types
    -- ========================================================================
    type t_pos_arr   is array (0 to N_LOGOS - 1) of signed(11 downto 0);
    type t_pos21_arr is array (0 to N_LOGOS - 1) of signed(20 downto 0);
    type t_frac_arr  is array (0 to N_LOGOS - 1) of unsigned(7 downto 0);
    type t_color_arr is array (0 to N_LOGOS - 1) of unsigned(2 downto 0);

    -- ========================================================================
    -- Parameters
    -- ========================================================================
    signal s_angle_pot  : unsigned(9 downto 0);
    signal s_size_pot   : unsigned(9 downto 0);
    signal s_count_raw  : unsigned(9 downto 0);
    signal s_step_pot   : unsigned(9 downto 0);
    signal s_tint_pot   : unsigned(9 downto 0);
    signal s_bright_pot : unsigned(9 downto 0);
    signal s_color_mode : std_logic;
    signal s_matte      : std_logic;
    signal s_bg_black   : std_logic;
    signal s_pause      : std_logic;
    signal s_mix_logos  : std_logic;    -- 0 = bounce off each other, 1 = mix
    signal s_speed_pot  : unsigned(9 downto 0);

    -- 2-bit count = (s_count_raw[9:8]); active mask = "i <= count"
    signal s_count    : unsigned(1 downto 0);
    signal s_active   : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');

    signal s_step_sel : unsigned(2 downto 0);   -- 0..6 = step 1..7, 7 = random
    signal s_tint     : unsigned(2 downto 0);

    -- Master speed (px/frame, Q8) and the 25..100% weights (Q8, 64..256)
    signal s_speed_q8 : unsigned(12 downto 0) := (others => '0');
    signal s_wx       : unsigned(8 downto 0) := to_unsigned(256, 9);
    signal s_wy       : unsigned(8 downto 0) := to_unsigned(256, 9);
    signal s_gain     : unsigned(8 downto 0) := to_unsigned(256, 9);

    -- Velocity magnitudes (Q8) from the serial multiplier, and the signed
    -- +/- forms the predictor muxes between.
    signal s_vx_q8  : unsigned(12 downto 0) := (others => '0');
    signal s_vy_q8  : unsigned(12 downto 0) := (others => '0');
    signal s_vx_pos : signed(20 downto 0) := (others => '0');
    signal s_vx_neg : signed(20 downto 0) := (others => '0');
    signal s_vy_pos : signed(20 downto 0) := (others => '0');
    signal s_vy_neg : signed(20 downto 0) := (others => '0');

    signal s_lfsr   : unsigned(15 downto 0) := x"ACE1";

    -- Size.  Scale is Q8 (128..768 = 0.5x..3x).  The knob is deadbanded
    -- (held value moves only on a >3-code change), mapped + capped into a
    -- target, and the live scale glides toward it once per field.
    signal s_size_held  : unsigned(9 downto 0) := to_unsigned(205, 10);
    signal s_size_tgt   : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_size_glide : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_sz_saw     : std_logic := '0';
    signal s_sz_raw, s_sz_raw_d   : unsigned(9 downto 0) := (others => '0');
    signal s_sz_dif     : signed(10 downto 0) := (others => '0');
    signal s_sz_t1, s_sz_t2, s_sz_t3 : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_gl_diff    : signed(10 downto 0) := (others => '0');
    signal s_gl_step    : unsigned(9 downto 0) := (others => '0');
    signal s_gl_up, s_gl_dn : std_logic := '0';

    -- Serial restoring divider: step = 2^20 / scale (Q12 logo px per
    -- screen px, 1365..8192).  Publishes a consistent (scale, step) pair.
    signal s_div_cnt  : unsigned(4 downto 0) := (others => '0');
    signal s_div_d    : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_div_rem  : unsigned(9 downto 0) := (others => '0');
    signal s_div_q    : unsigned(13 downto 0) := (others => '0');
    signal s_pair_s   : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_pair_stp : unsigned(13 downto 0) := to_unsigned(4096, 14);

    -- Field-latched pair used by physics, multiplier and accumulators.
    signal s_scale_f : unsigned(9 downto 0) := to_unsigned(256, 10);
    signal s_step_f  : unsigned(13 downto 0) := to_unsigned(4096, 14);

    -- Logo size on screen (= 384 x scale, 174 x scale), from the multiplier.
    signal s_lw       : signed(12 downto 0) := to_signed(C_LOGO_W, 13);
    signal s_lh       : signed(12 downto 0) := to_signed(C_LOGO_H, 13);
    signal s_lwh_diff : signed(13 downto 0) := to_signed(C_LOGO_W - C_LOGO_H, 14);

    -- Logo-space beam accumulators (Q12): h_count*step, (h_count+8)*step
    -- for the prefetch lead, v_count*step.  Aligned with pixel_counter.
    signal s_hs  : unsigned(24 downto 0) := (others => '0');
    signal s_hsl : unsigned(24 downto 0) := (others => '0');
    signal s_vs  : unsigned(24 downto 0) := (others => '0');

    -- Resolution scaling: virtual 1080-line steps from the timing ID.  x step
    -- Q.1 per pixel (2/3/4 = 1.0/1.5/2.0), y step Q4.8 per FIELD line.  The
    -- beam accumulators step by these times the logo step (Q12): s_hstep per
    -- pixel, s_vstep (serial multiplier) per line; s_hsl_pre is the prefetch
    -- lead preload (8 px at 1080p as before, 6 px elsewhere); s_voff starts
    -- the bottom field half a field step down.
    signal s_xs      : unsigned(2 downto 0)  := to_unsigned(2, 3);
    signal s_ys      : unsigned(11 downto 0) := to_unsigned(256, 12);
    signal s_hstep   : unsigned(14 downto 0) := to_unsigned(4096, 15);
    signal s_hsl_pre : unsigned(17 downto 0) := to_unsigned(32768, 18);
    signal s_vstep   : unsigned(15 downto 0) := to_unsigned(4096, 16);
    signal s_voff    : unsigned(15 downto 0) := (others => '0');

    -- Per-logo logo-space offsets (Q6): -x_i * step, -y_i * step.
    type t_off_arr is array (0 to N_LOGOS - 1) of signed(19 downto 0);
    signal s_cx : t_off_arr := (others => (others => '0'));
    signal s_dy : t_off_arr := (others => (others => '0'));

    -- ========================================================================
    -- Timing + auto-measured resolution
    -- ========================================================================
    signal s_timing  : t_video_timing_port;
    signal s_h_count : unsigned(11 downto 0);
    signal s_v_count : unsigned(11 downto 0);

    -- Virtual-unit measure accumulators: Q.1 per pixel, Q.8 per field line.
    signal s_h_pixel_counter : unsigned(12 downto 0) := (others => '0');
    signal s_v_line_counter  : unsigned(19 downto 0) := (others => '0');
    signal s_measured_h      : unsigned(11 downto 0) := to_unsigned(960, 12);
    signal s_measured_v      : unsigned(11 downto 0) := to_unsigned(1080, 12);

    -- Pre-registered max bounce positions = active - logo_size, and the
    -- corner-tolerance thresholds below them.
    signal s_max_pos_x : signed(12 downto 0) := to_signed(0, 13);
    signal s_max_pos_y : signed(12 downto 0) := to_signed(0, 13);
    signal s_max_tol_x : signed(12 downto 0) := to_signed(0, 13);
    signal s_max_tol_y : signed(12 downto 0) := to_signed(0, 13);
    -- Park x of logos 1/3: 480 units left of the right wall (1440 at HD,
    -- 960 in the 1440-wide SD window).
    signal s_park_x    : signed(11 downto 0) := to_signed(1440, 12);

    -- ========================================================================
    -- Initial state — laid out as a 2x2 grid that's well-separated at HD
    -- (1920x1080 virtual units; every mode is 1080 units tall).  Inactive
    -- logos hold these values (logos 1/3 at s_park_x, which is 1440 at HD)
    -- so that turning Count up always introduces a new logo at a clean spot.
    -- ========================================================================
    constant C_INIT_X : t_pos_arr := (
        to_signed(  96, 12),
        to_signed(1440, 12),
        to_signed(  96, 12),
        to_signed(1440, 12)
    );
    constant C_INIT_Y : t_pos_arr := (
        to_signed( 64, 12),
        to_signed( 64, 12),
        to_signed(800, 12),
        to_signed(800, 12)
    );
    -- vx/vy direction so each logo heads toward screen-center.
    constant C_INIT_VX : std_logic_vector(0 to N_LOGOS - 1) := "1010";
    constant C_INIT_VY : std_logic_vector(0 to N_LOGOS - 1) := "1100";
    constant C_INIT_COLOR : t_color_arr := (
        "000",  -- white
        "001",  -- red
        "100",  -- green
        "110"   -- blue
    );

    signal s_logo_x    : t_pos_arr  := C_INIT_X;
    signal s_logo_y    : t_pos_arr  := C_INIT_Y;
    signal s_logo_xf   : t_frac_arr := (others => (others => '0'));
    signal s_logo_yf   : t_frac_arr := (others => (others => '0'));
    signal s_vx_sign   : std_logic_vector(0 to N_LOGOS - 1) := C_INIT_VX;
    signal s_vy_sign   : std_logic_vector(0 to N_LOGOS - 1) := C_INIT_VY;
    signal s_color_idx : t_color_arr := C_INIT_COLOR;

    -- Corner party: frames left, and the palette offset it strobes through.
    signal s_party    : unsigned(6 downto 0) := (others => '0');
    signal s_party_ph : unsigned(2 downto 0) := (others => '0');

    -- ========================================================================
    -- Physics FSM intermediates
    -- ========================================================================
    signal s_ph_phase : unsigned(1 downto 0) := "00";
    -- Set by active video, consumed by the physics step: one step per field
    -- even when an analog vsync serrates into several vsync_start pulses.
    signal s_saw_avid : std_logic := '0';
    -- After predicting, wait 1024 clocks before clamping: the size latch
    -- fires on the same vsync and the multiplier needs <= 512 clocks to
    -- publish the matching logo width/height, so walls use THIS field's size.
    signal s_ph_wait  : std_logic := '0';
    signal s_wait_cnt : unsigned(9 downto 0) := (others => '0');

    -- Phase 0 → 1 handoff: raw (unclamped) predicted positions, 13.8.
    signal s_pred_raw_x : t_pos21_arr := (others => (others => '0'));
    signal s_pred_raw_y : t_pos21_arr := (others => (others => '0'));

    -- Phase 1 → 2/3 handoff: clamped positions, signs, wall + near flags.
    signal s_pred_x   : t_pos21_arr := (others => (others => '0'));
    signal s_pred_y   : t_pos21_arr := (others => (others => '0'));
    signal s_pred_vx  : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_pred_vy  : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_bounce_x : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_bounce_y : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_near_x   : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_near_y   : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    -- Wall-compare flags, registered free-running from the raw predictions
    -- (valid long before phase 1 thanks to the 1024-clock wait), so phase 1
    -- is pure muxing.
    signal s_lo_x, s_hi_x : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');
    signal s_lo_y, s_hi_y : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');

    -- Serial pair engine (phase 2): counter + 4 pipeline stages.
    signal s_pcnt     : unsigned(3 downto 0) := (others => '0');
    signal s_pa_valid : std_logic := '0';
    signal s_pa_k     : integer range 0 to N_PAIRS - 1 := 0;
    signal s_pa_ax, s_pa_bx, s_pa_ay, s_pa_by : signed(12 downto 0)
                                                := (others => '0');
    signal s_pb_valid : std_logic := '0';
    signal s_pb_k     : integer range 0 to N_PAIRS - 1 := 0;
    signal s_pb_dx, s_pb_dy : signed(13 downto 0) := (others => '0');
    signal s_pc_valid : std_logic := '0';
    signal s_pc_k     : integer range 0 to N_PAIRS - 1 := 0;
    signal s_pc_adx, s_pc_ady : unsigned(12 downto 0) := (others => '0');
    signal s_pc_sx, s_pc_sy   : std_logic := '0';   -- '1' = logo i before j
    signal s_pd_valid : std_logic := '0';
    signal s_pd_k     : integer range 0 to N_PAIRS - 1 := 0;
    signal s_pd_hit   : std_logic := '0';
    signal s_pd_diff  : signed(13 downto 0) := (others => '0');  -- adx - ady
    signal s_pd_sx, s_pd_sy : std_logic := '0';

    -- Per-logo collision results, accumulated over the 6 pairs.
    signal s_cx_on, s_cx_dir : std_logic_vector(0 to N_LOGOS - 1)
                               := (others => '0');
    signal s_cy_on, s_cy_dir : std_logic_vector(0 to N_LOGOS - 1)
                               := (others => '0');
    signal s_newhit          : std_logic_vector(0 to N_LOGOS - 1)
                               := (others => '0');
    -- Previous frame's collision state per pair: colors advance only on a
    -- NEW collision, not every frame two logos stay in contact.
    signal s_was_colliding : std_logic_vector(0 to N_PAIRS - 1) := (others => '0');

    -- ========================================================================
    -- Serial shift-add multiplier — 32 slots x 16 clocks, free-running.
    --   slot = grp(4) & logo(3:2) & chan(1:0)
    --   grp 0: chan 0/1/2 = palette Y/U/V x gain; chan 3 = speed x X weight
    --          (logo 0), speed x Y weight (1), scale x 384 (2), x 174 (3)
    --   grp 1: chan 0 = x_i x step, chan 1 = y_i x step, chan 2 = step x
    --          virtual y step (the V beam step; every logo stores the same)
    -- ========================================================================
    signal s_mslot : unsigned(4 downto 0) := (others => '0');
    signal s_mcyc  : unsigned(3 downto 0) := (others => '0');
    signal s_ma    : unsigned(25 downto 0) := (others => '0');
    signal s_mb    : unsigned(11 downto 0) := (others => '0');
    signal s_macc  : unsigned(25 downto 0) := (others => '0');
    signal s_mneg  : std_logic := '0';

    -- ========================================================================
    -- Render pipeline registers
    -- ========================================================================
    -- S1
    signal s_stg1_hs     : signed(19 downto 0) := (others => '0');
    signal s_stg1_vs     : signed(19 downto 0) := (others => '0');
    signal s_bnd_cx      : t_off_arr   := (others => (others => '0'));
    signal s_bnd_dy      : t_off_arr   := (others => (others => '0'));
    signal s_bnd_active  : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');

    -- S2a — register logo-space lx[i], ly[i] (one add per axis per logo)
    type t_dx_arr is array (0 to N_LOGOS - 1) of signed(19 downto 0);
    signal s_stg2a_dx     : t_dx_arr := (others => (others => '0'));
    signal s_stg2a_dy     : t_dx_arr := (others => (others => '0'));
    signal s_stg2a_active : std_logic_vector(0 to N_LOGOS - 1)
                            := (others => '0');

    -- S2b — per-logo lit flags (in_bbox AND that logo's bitmap bit)
    signal s_stg2_lit : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');

    -- ========================================================================
    -- Streaming ROM prefetch — slot i (h_count mod 4) fetches logo i's word
    -- 8 px ahead of the beam into a 2-entry (word-index parity) buffer.
    -- PF0: bxf/byf deltas  PF1: validity + word address  PF2: ROM read
    -- PF3: buffer write.
    -- ========================================================================
    type t_word2   is array (0 to 1) of
                      std_logic_vector(C_LOGO_WORD_W - 1 downto 0);
    type t_buf_arr is array (0 to N_LOGOS - 1) of t_word2;
    signal s_pf_buf : t_buf_arr := (others => (others => (others => '0')));

    signal s_pf0_bxf : signed(19 downto 0) := (others => '0');   -- Q6
    signal s_pf0_byf : signed(19 downto 0) := (others => '0');   -- Q6
    signal s_pf0_idx : unsigned(1 downto 0) := (others => '0');

    signal s_pf1_addr  : unsigned(12 downto 0) := (others => '0');
    signal s_pf1_par   : std_logic := '0';
    signal s_pf1_idx   : unsigned(1 downto 0) := (others => '0');
    signal s_pf1_valid : std_logic := '0';

    signal s_pf2_word  : std_logic_vector(C_LOGO_WORD_W - 1 downto 0)
                         := (others => '0');
    signal s_pf2_par   : std_logic := '0';
    signal s_pf2_idx   : unsigned(1 downto 0) := (others => '0');
    signal s_pf2_valid : std_logic := '0';

    -- ========================================================================
    -- Per-frame palette registers — one (Y-offset above black, U-offset,
    -- V-offset) per logo, already scaled by Bright.  Written by the serial
    -- multiplier.  Mono mode zeroes the chroma offsets.
    -- ========================================================================
    type t_paly_arr   is array (0 to N_LOGOS - 1) of unsigned(9 downto 0);
    type t_paloff_arr is array (0 to N_LOGOS - 1) of signed(10 downto 0);
    signal s_pal_y  : t_paly_arr   := (others => (others => '0'));
    signal s_pal_uo : t_paloff_arr := (others => (others => '0'));
    signal s_pal_vo : t_paloff_arr := (others => (others => '0'));

    -- S3 — gated per-logo contributions
    signal s_stg3_y   : t_paly_arr   := (others => (others => '0'));
    signal s_stg3_uo  : t_paloff_arr := (others => (others => '0'));
    signal s_stg3_vo  : t_paloff_arr := (others => (others => '0'));
    signal s_stg3_lit : std_logic_vector(0 to N_LOGOS - 1) := (others => '0');

    -- S4 — pairwise sums (Mix) + pairwise priority selects (Bounce)
    signal s_stg4_ysum01, s_stg4_ysum23 : unsigned(10 downto 0)
                                          := (others => '0');
    signal s_stg4_uo01,   s_stg4_uo23   : signed(11 downto 0)
                                          := (others => '0');
    signal s_stg4_vo01,   s_stg4_vo23   : signed(11 downto 0)
                                          := (others => '0');
    signal s_stg4_sely01, s_stg4_sely23 : unsigned(9 downto 0)
                                          := (others => '0');
    signal s_stg4_seluo01, s_stg4_seluo23 : signed(10 downto 0)
                                            := (others => '0');
    signal s_stg4_selvo01, s_stg4_selvo23 : signed(10 downto 0)
                                            := (others => '0');
    signal s_stg4_lit01, s_stg4_lit23   : std_logic := '0';
    signal s_stg4_any                   : std_logic := '0';

    -- S5 — combined offsets (Y above black, U/V about 512)
    signal s_stg5_y    : unsigned(9 downto 0) := (others => '0');
    signal s_stg5_uo   : signed(10 downto 0) := (others => '0');
    signal s_stg5_vo   : signed(10 downto 0) := (others => '0');
    signal s_stg5_show : std_logic := '0';

    -- S6 — re-biased codes
    signal s_out_y    : unsigned(9 downto 0) := C_Y_BLACK;
    signal s_out_u    : unsigned(9 downto 0) := C_CHROMA_MID;
    signal s_out_v    : unsigned(9 downto 0) := C_CHROMA_MID;
    signal s_out_show : std_logic := '0';

    -- Final output register (wet select + blanking gate)
    signal s_fin_y : std_logic_vector(9 downto 0) := std_logic_vector(C_Y_BLACK);
    signal s_fin_u : std_logic_vector(9 downto 0) := std_logic_vector(C_CHROMA_MID);
    signal s_fin_v : std_logic_vector(9 downto 0) := std_logic_vector(C_CHROMA_MID);
    signal s_fin_sync : std_logic_vector(3 downto 0) := (others => '0');

    -- ========================================================================
    -- Sync + data delay
    -- ========================================================================
    -- Sync pipe entry i = data_in sync delayed i+1 clocks; entry 8 lines up
    -- with s_out_* (9 clocks), the output register adds the 10th.
    type t_sync_pipe is array (0 to C_DELAY - 1) of std_logic_vector(3 downto 0);
    signal s_sync_pipe : t_sync_pipe := (others => (others => '0'));

    type t_data_delay is array (0 to C_DELAY - 1) of std_logic_vector(9 downto 0);
    signal s_y_delay : t_data_delay := (others => (others => '0'));
    signal s_u_delay : t_data_delay := (others => (others => '0'));
    signal s_v_delay : t_data_delay := (others => (others => '0'));

    -- ========================================================================
    -- 8-color palette (U/V-swapped for the hardware, 90% amplitude so the
    -- brightest entries stay at Y <= 768).  Stored as offsets: Y above black
    -- (64), U/V magnitude about 512 plus a sign.
    --   0 white  1 red  2 orange  3 yellow  4 green  5 cyan  6 blue  7 magenta
    -- chan: 0 = Y, 1 = U, 2 = V
    -- ========================================================================
    function f_pal_mag(c : unsigned(2 downto 0); ch : unsigned(1 downto 0))
        return unsigned is
        variable v : integer range 0 to 1023;
    begin
        case ch is
            when "00" =>
                case c is
                    when "000"  => v := 701;
                    when "001"  => v := 236;
                    when "010"  => v := 467;
                    when "011"  => v := 699;
                    when "100"  => v := 463;
                    when "101"  => v := 553;
                    when "110"  => v := 264;
                    when others => v := 326;
                end case;
            when "01" =>
                case c is
                    when "000"  => v := 0;
                    when "001"  => v := 403;
                    when "010"  => v := 234;
                    when "011"  => v := 66;
                    when "100"  => v := 338;
                    when "101"  => v := 403;
                    when "110"  => v := 106;
                    when others => v := 338;
                end case;
            when others =>
                case c is
                    when "000"  => v := 0;
                    when "001"  => v := 136;
                    when "010"  => v := 270;
                    when "011"  => v := 403;
                    when "100"  => v := 267;
                    when "101"  => v := 136;
                    when "110"  => v := 303;
                    when others => v := 267;
                end case;
        end case;
        return to_unsigned(v, 10);
    end function;

    -- '1' where the U (ch 1) or V (ch 2) offset is negative.
    function f_pal_neg(c : unsigned(2 downto 0); ch : unsigned(1 downto 0))
        return std_logic is
    begin
        if ch = "01" then
            case c is
                when "100" | "101" | "110" => return '1';   -- green cyan blue
                when others                => return '0';
            end case;
        elsif ch = "10" then
            case c is
                when "001" | "010" | "011" | "100" => return '1';  -- r o y g
                when others                        => return '0';
            end case;
        else
            return '0';
        end if;
    end function;

    -- ========================================================================
    -- Resolution scaling: per-mode steps from the video timing ID.
    -- ========================================================================
    -- x step in half virtual units per pixel: 1080 2 (1.0), 720p 3 (1.5),
    -- SD 4 (2.0: 720 px span 1440 units, a 4:3 window of the 1080 canvas).
    function f_vstep_x(t : std_logic_vector(3 downto 0)) return unsigned is
    begin
        case to_integer(unsigned(t)) is
            when 0 | 4 | 8 | 12 => return to_unsigned(4, 3);
            when 5 | 6 | 14     => return to_unsigned(3, 3);
            when others         => return to_unsigned(2, 3);
        end case;
    end function;
    -- y step in Q4.8 virtual units per FIELD line (1080 / active lines,
    -- doubled for interlaced modes).
    function f_vstep_y(t : std_logic_vector(3 downto 0)) return unsigned is
    begin
        case to_integer(unsigned(t)) is
            when 0          => return to_unsigned(1138, 12);  -- 480i: 2 x 1080/486
            when 4          => return to_unsigned(576, 12);   -- 480p: 1080/480
            when 8          => return to_unsigned(960, 12);   -- 576i: 2 x 1080/576
            when 12         => return to_unsigned(480, 12);   -- 576p: 1080/576
            when 5 | 6 | 14 => return to_unsigned(384, 12);   -- 720p: 1.5
            when 1 | 2 | 10 => return to_unsigned(512, 12);   -- 1080i: 2.0
            when others     => return to_unsigned(256, 12);   -- 1080p: 1.0
        end case;
    end function;

begin

    -- ========================================================================
    -- Auto-Measure Active Resolution
    -- ========================================================================
    -- (in virtual units: SD 1440 x 1080, 720p and 1080 1920 x 1080; the
    -- steps are static per mode, so they are registered free-running)
    p_measure : process(clk)
    begin
        if rising_edge(clk) then
            s_xs <= f_vstep_x(registers_in(8)(3 downto 0));
            s_ys <= f_vstep_y(registers_in(8)(3 downto 0));

            if s_timing.hsync_start = '1' then
                if s_h_pixel_counter > 0 then
                    s_measured_h <= s_h_pixel_counter(12 downto 1);
                end if;
                s_h_pixel_counter <= (others => '0');
            elsif s_timing.avid = '1' then
                s_h_pixel_counter <= s_h_pixel_counter + s_xs;
            end if;

            if s_timing.vsync_start = '1' then
                if s_v_line_counter > 0 then
                    s_measured_v <= s_v_line_counter(19 downto 8);
                end if;
                s_v_line_counter <= (others => '0');
            elsif s_timing.avid_start = '1' then
                s_v_line_counter <= s_v_line_counter + s_ys;
            end if;
        end if;
    end process;

    p_resolution : process(clk)
    begin
        if rising_edge(clk) then
            -- Continuously refresh max-position bounds.  Every raster is at
            -- least 1440 x 1080 virtual units (SD), so even 3x (1152 x 522)
            -- fits and no clamp-to-zero is needed.
            s_max_pos_x <= signed(resize(s_measured_h, 13)) - s_lw;
            s_max_pos_y <= signed(resize(s_measured_v, 13)) - s_lh;
            s_max_tol_x <= s_max_pos_x - to_signed(C_CORNER_TOL, 13);
            s_max_tol_y <= s_max_pos_y - to_signed(C_CORNER_TOL, 13);
            s_lwh_diff  <= resize(s_lw, 14) - resize(s_lh, 14);
            if s_xs = 4 then
                s_park_x <= to_signed(960, 12);
            else
                s_park_x <= to_signed(1440, 12);
            end if;
        end if;
    end process;

    -- ========================================================================
    -- Register Mapping
    -- ========================================================================
    s_angle_pot  <= unsigned(registers_in(0));
    s_size_pot   <= unsigned(registers_in(1));
    s_count_raw  <= unsigned(registers_in(2));
    s_step_pot   <= unsigned(registers_in(3));
    s_tint_pot   <= unsigned(registers_in(4));
    s_bright_pot <= unsigned(registers_in(5));
    s_color_mode <= registers_in(6)(0);
    s_matte      <= registers_in(6)(1);
    s_bg_black   <= registers_in(6)(2);
    s_pause      <= registers_in(6)(3);
    s_mix_logos  <= registers_in(6)(4);
    s_speed_pot  <= unsigned(registers_in(7));

    s_count    <= s_count_raw(9 downto 8);
    s_tint     <= s_tint_pot(9 downto 7);
    s_step_sel <= s_step_pot(9 downto 7);

    -- ========================================================================
    -- Control curves (all registered, quasi-static).
    --   Speed : (128 + m) << e >> 2 with e = P12[9:7], m = P12[6:0]
    --           → 32 .. 8160 Q8 = 0.125 .. 32 px/frame, one octave per 1/8.
    --   Gain  : 64 + k - k/4 with k = pot[9:2] → 64..256 (25..100%).
    --   Angle : Y weight = 64 + k - k/4 (25..100%), X weight = 320 - Y.
    -- ========================================================================
    p_controls : process(clk)
        variable v_base : unsigned(14 downto 0);
        variable v_k    : unsigned(8 downto 0);
    begin
        if rising_edge(clk) then
            v_base := resize(to_unsigned(128, 8) + s_speed_pot(6 downto 0), 15);
            v_base := shift_left(v_base, to_integer(s_speed_pot(9 downto 7)));
            s_speed_q8 <= v_base(14 downto 2);

            v_k  := resize(s_angle_pot(9 downto 2), 9);
            v_k  := to_unsigned(64, 9) + v_k - shift_right(v_k, 2);
            s_wy <= v_k;
            s_wx <= to_unsigned(320, 9) - v_k;
            v_k    := resize(s_bright_pot(9 downto 2), 9);
            s_gain <= to_unsigned(64, 9) + v_k - shift_right(v_k, 2);

            s_vx_pos <= signed(resize(s_vx_q8, 21));
            s_vx_neg <= -signed(resize(s_vx_q8, 21));
            s_vy_pos <= signed(resize(s_vy_q8, 21));
            s_vy_neg <= -signed(resize(s_vy_q8, 21));

            if s_party /= 0 then
                s_party_ph <= s_party(3 downto 1);
            else
                s_party_ph <= (others => '0');
            end if;

            -- Galois LFSR (x^16 + x^14 + x^13 + x^11 + 1) for random steps
            if s_lfsr(0) = '1' then
                s_lfsr <= shift_right(s_lfsr, 1) xor x"B400";
            else
                s_lfsr <= shift_right(s_lfsr, 1);
            end if;
        end if;
    end process;

    -- Active mask: logo i is active when i <= count.
    p_active : process(clk)
    begin
        if rising_edge(clk) then
            for i in 0 to N_LOGOS - 1 loop
                if to_unsigned(i, 2) <= s_count then
                    s_active(i) <= '1';
                else
                    s_active(i) <= '0';
                end if;
            end loop;
        end if;
    end process;

    -- ========================================================================
    -- Video Timing Generator + Pixel Counter
    -- ========================================================================
    timing_gen_inst : entity work.video_timing_generator
        port map (
            clk         => clk,
            ref_hsync_n => data_in.hsync_n,
            ref_vsync_n => data_in.vsync_n,
            ref_avid    => data_in.avid,
            timing      => s_timing
        );

    pixel_counter_inst : entity work.pixel_counter
        port map (
            clk     => clk,
            timing  => s_timing,
            h_count => s_h_count,
            v_count => s_v_count
        );

    -- ========================================================================
    -- Size control.  Deadband → map (128 + k*5/8) →
    -- per-field glide (diff/8, at least 1) → serial divider → field latch.
    -- Runs on its own saw-active vsync guard so it stays live under Pause.
    -- ========================================================================
    p_size : process(clk)
        variable v_r    : unsigned(10 downto 0);
        variable v_bit  : std_logic;
        variable v_abs  : signed(10 downto 0);
        variable v_stp  : unsigned(9 downto 0);
    begin
        if rising_edge(clk) then
            -- One op per stage: these are quasi-static but STA-timed at the
            -- pixel clock (a fused add+compare+enable here failed HD timing).
            -- Deadband: register raw, register the difference, then test.
            s_sz_raw   <= s_size_pot;
            s_sz_raw_d <= s_sz_raw;
            s_sz_dif   <= signed(resize(s_sz_raw, 11))
                          - signed(resize(s_size_held, 11));
            if s_sz_dif > 3 or s_sz_dif < -3 then
                s_size_held <= s_sz_raw_d;
            end if;

            -- Map 128 + k/2 + k/8 (no SD cap: in virtual units 3x fits SD).
            s_sz_t1 <= to_unsigned(128, 10) + shift_right(s_size_held, 1);
            s_sz_t2 <= shift_right(s_size_held, 3);
            s_sz_t3 <= s_sz_t1 + s_sz_t2;
            s_size_tgt <= s_sz_t3;

            -- Glide step = |target - glide| / 8, at least 1, precomputed.
            s_gl_diff <= signed(resize(s_size_tgt, 11))
                         - signed(resize(s_size_glide, 11));
            v_abs := abs(s_gl_diff);
            v_stp := shift_right(unsigned(v_abs(9 downto 0)), 3);
            if v_stp = 0 then
                v_stp := to_unsigned(1, 10);
            end if;
            s_gl_step <= v_stp;
            s_gl_up   <= '0';
            s_gl_dn   <= '0';
            if s_gl_diff > 0 then
                s_gl_up <= '1';
            elsif s_gl_diff < 0 then
                s_gl_dn <= '1';
            end if;

            if s_timing.avid = '1' then
                s_sz_saw <= '1';
            end if;
            if s_timing.vsync_start = '1' and s_sz_saw = '1' then
                s_sz_saw  <= '0';
                s_scale_f <= s_pair_s;
                s_step_f  <= s_pair_stp;
                if s_gl_up = '1' then
                    s_size_glide <= s_size_glide + s_gl_step;
                elsif s_gl_dn = '1' then
                    s_size_glide <= s_size_glide - s_gl_step;
                end if;
            end if;

            -- Divider: numerator 2^20 fed MSB first (a single 1 at step 1).
            if s_div_cnt = 0 then
                s_div_d   <= s_size_glide;
                s_div_rem <= (others => '0');
                s_div_q   <= (others => '0');
                s_div_cnt <= s_div_cnt + 1;
            elsif s_div_cnt <= 21 then
                if s_div_cnt = 1 then
                    v_bit := '1';
                else
                    v_bit := '0';
                end if;
                v_r := s_div_rem & v_bit;
                if v_r >= resize(s_div_d, 11) then
                    v_r     := v_r - resize(s_div_d, 11);
                    s_div_q <= s_div_q(12 downto 0) & '1';
                else
                    s_div_q <= s_div_q(12 downto 0) & '0';
                end if;
                s_div_rem <= v_r(9 downto 0);
                s_div_cnt <= s_div_cnt + 1;
            else
                s_pair_s   <= s_div_d;
                s_pair_stp <= s_div_q;
                s_div_cnt  <= (others => '0');
            end if;
        end if;
    end process;

    -- ========================================================================
    -- Logo-space beam accumulators — same reset/advance conditions as
    -- pixel_counter, so s_hs = h_count * step exactly, on the same clock.
    -- ========================================================================
    -- (Scaled per pixel / per line by the virtual steps; quasi-static terms
    -- are precomputed one op per stage.  At 1080p s_hstep = s_vstep = step.)
    p_accum : process(clk)
    begin
        if rising_edge(clk) then
            case s_xs is
                when "011"  => s_hstep <= resize(s_step_f, 15)
                                          + resize(s_step_f(13 downto 1), 15);
                when "100"  => s_hstep <= shift_left(resize(s_step_f, 15), 1);
                when others => s_hstep <= resize(s_step_f, 15);
            end case;
            if s_xs = 2 then
                s_hsl_pre <= shift_left(resize(s_hstep, 18), 3);
            else
                s_hsl_pre <= shift_left(resize(s_hstep, 18), 2)
                             + shift_left(resize(s_hstep, 18), 1);
            end if;
            if data_in.field_n = '0' then
                s_voff <= shift_right(s_vstep, 1);
            else
                s_voff <= (others => '0');
            end if;

            if s_timing.hsync_start = '1' then
                s_hs  <= (others => '0');
                s_hsl <= resize(s_hsl_pre, 25);
            elsif s_timing.avid = '1' then
                s_hs  <= s_hs  + s_hstep;
                s_hsl <= s_hsl + s_hstep;
            end if;

            if s_timing.vsync_start = '1' then
                s_vs <= resize(s_voff, 25);
            elsif s_timing.avid_start = '1' then
                s_vs <= s_vs + s_vstep;
            end if;
        end if;
    end process;

    -- ========================================================================
    -- Serial multiplier.  Load on cycle 0, 12 shift-add steps on cycles
    -- 1..12, store on cycle 13, idle to 15.
    -- ========================================================================
    p_mul : process(clk)
        variable v_i   : integer range 0 to N_LOGOS - 1;
        variable v_ch  : unsigned(1 downto 0);
        variable v_eff : unsigned(2 downto 0);
        variable v_res : unsigned(13 downto 0);
        variable v_off : unsigned(18 downto 0);
    begin
        if rising_edge(clk) then
            v_i  := to_integer(s_mslot(3 downto 2));
            v_ch := s_mslot(1 downto 0);

            if s_mcyc = 0 then
                v_eff  := s_color_idx(v_i) + s_tint + s_party_ph;
                s_mneg <= '0';
                if s_mslot(4) = '1' then
                    s_ma <= resize(s_step_f, 26);
                    if v_ch = "00" then
                        s_mb <= resize(unsigned(s_logo_x(v_i)(10 downto 0)), 12);
                    elsif v_ch = "10" then
                        s_mb <= s_ys;
                    else
                        s_mb <= resize(unsigned(s_logo_y(v_i)(10 downto 0)), 12);
                    end if;
                elsif v_ch = "11" then
                    case v_i is
                        when 0 =>
                            s_ma <= resize(s_speed_q8, 26);
                            s_mb <= resize(s_wx, 12);
                        when 1 =>
                            s_ma <= resize(s_speed_q8, 26);
                            s_mb <= resize(s_wy, 12);
                        when 2 =>
                            s_ma <= resize(s_scale_f, 26);
                            s_mb <= to_unsigned(C_LOGO_W, 12);
                        when others =>
                            s_ma <= resize(s_scale_f, 26);
                            s_mb <= to_unsigned(C_LOGO_H, 12);
                    end case;
                else
                    if v_ch = "00" or s_color_mode = '1' then
                        s_ma <= resize(f_pal_mag(v_eff, v_ch), 26);
                    else
                        s_ma <= (others => '0');        -- mono: no chroma
                    end if;
                    s_mneg <= f_pal_neg(v_eff, v_ch);
                    s_mb   <= resize(s_gain, 12);
                end if;
                s_macc <= (others => '0');
            elsif s_mcyc <= 12 then
                if s_mb(0) = '1' then
                    s_macc <= s_macc + s_ma;
                end if;
                s_ma <= shift_left(s_ma, 1);
                s_mb <= shift_right(s_mb, 1);
            elsif s_mcyc = 13 then
                v_res := s_macc(21 downto 8);
                v_off := s_macc(24 downto 6);
                if s_mslot(4) = '1' then
                    if v_ch = "00" then
                        s_cx(v_i) <= -signed(resize(v_off, 20));
                    elsif v_ch = "01" then
                        s_dy(v_i) <= -signed(resize(v_off, 20));
                    elsif v_ch = "10" then
                        s_vstep <= s_macc(23 downto 8);   -- step x ys (Q12)
                    end if;
                else
                    case v_ch is
                        when "00" =>
                            s_pal_y(v_i) <= v_res(9 downto 0);
                        when "01" =>
                            if s_mneg = '1' then
                                s_pal_uo(v_i) <= -signed(resize(v_res(9 downto 0), 11));
                            else
                                s_pal_uo(v_i) <= signed(resize(v_res(9 downto 0), 11));
                            end if;
                        when "10" =>
                            if s_mneg = '1' then
                                s_pal_vo(v_i) <= -signed(resize(v_res(9 downto 0), 11));
                            else
                                s_pal_vo(v_i) <= signed(resize(v_res(9 downto 0), 11));
                            end if;
                        when others =>
                            case v_i is
                                when 0 =>
                                    s_vx_q8 <= v_res(12 downto 0);
                                when 1 =>
                                    s_vy_q8 <= v_res(12 downto 0);
                                when 2 =>
                                    s_lw <= signed(resize(v_res(10 downto 0), 13));
                                when others =>
                                    s_lh <= signed(resize(v_res(10 downto 0), 13));
                            end case;
                    end case;
                end if;
            end if;

            s_mcyc <= s_mcyc + 1;
            if s_mcyc = 15 then
                s_mslot <= s_mslot + 1;
            end if;
        end if;
    end process;

    -- ========================================================================
    -- Physics — 4-phase FSM, once per field.
    -- ========================================================================
    p_physics : process(clk)
        variable v_pos             : signed(20 downto 0);
        variable v_new_x, v_new_y  : signed(20 downto 0);
        variable v_int_x, v_int_y  : signed(12 downto 0);
        variable v_vxs, v_vys      : std_logic;
        variable v_bx, v_by        : std_logic;
        variable v_k               : integer range 0 to N_PAIRS - 1;
        variable v_i, v_j          : integer range 0 to N_LOGOS - 1;
        variable v_d               : signed(13 downto 0);
        variable v_step            : unsigned(2 downto 0);
        variable v_corner          : std_logic;
    begin
        if rising_edge(clk) then
            if s_timing.avid = '1' then
                s_saw_avid <= '1';
            end if;

            case to_integer(s_ph_phase) is

                -- ----------------------------------------------------
                -- Phase 0: predict (sign-mux + 21-bit add per axis).
                -- Paused: zero velocity (walls still clamp a resize).
                -- ----------------------------------------------------
                when 0 =>
                    if s_ph_wait = '1' then
                        s_wait_cnt <= s_wait_cnt + 1;
                        if s_wait_cnt = 1023 then
                            s_ph_wait  <= '0';
                            s_ph_phase <= to_unsigned(1, 2);
                        end if;
                    elsif s_timing.vsync_start = '1' and s_saw_avid = '1' then
                        for i in 0 to N_LOGOS - 1 loop
                            v_pos := resize(s_logo_x(i), 13)
                                     & signed(s_logo_xf(i));
                            if s_pause = '1' then
                                s_pred_raw_x(i) <= v_pos;
                            elsif s_vx_sign(i) = '1' then
                                s_pred_raw_x(i) <= v_pos + s_vx_pos;
                            else
                                s_pred_raw_x(i) <= v_pos + s_vx_neg;
                            end if;
                            v_pos := resize(s_logo_y(i), 13)
                                     & signed(s_logo_yf(i));
                            if s_pause = '1' then
                                s_pred_raw_y(i) <= v_pos;
                            elsif s_vy_sign(i) = '1' then
                                s_pred_raw_y(i) <= v_pos + s_vy_pos;
                            else
                                s_pred_raw_y(i) <= v_pos + s_vy_neg;
                            end if;
                        end loop;
                        s_saw_avid <= '0';
                        s_ph_wait  <= '1';
                        s_wait_cnt <= (others => '0');
                    end if;

                -- ----------------------------------------------------
                -- Phase 1: clamp + sign flip on wall hit; near-wall
                -- flags for corner detection; reset the pair engine.
                -- The low wall bounces only once the floor goes NEGATIVE:
                -- with sub-pixel speeds a logo leaving x=0 stays in
                -- pixel 0 for a few frames, and "<= 0" would re-bounce it
                -- (and re-advance its colour) every one of them.
                -- ----------------------------------------------------
                when 1 =>
                    for i in 0 to N_LOGOS - 1 loop
                        v_new_x := s_pred_raw_x(i);
                        v_new_y := s_pred_raw_y(i);
                        v_vxs   := s_vx_sign(i);
                        v_vys   := s_vy_sign(i);
                        v_bx    := '0';
                        v_by    := '0';

                        if s_lo_x(i) = '1' then
                            v_new_x := (others => '0');
                            v_vxs   := '1';
                            v_bx    := not s_vx_sign(i);
                        elsif s_hi_x(i) = '1' then
                            v_new_x := s_max_pos_x & "00000000";
                            v_vxs   := '0';
                            v_bx    := s_vx_sign(i);
                        end if;
                        if s_lo_y(i) = '1' then
                            v_new_y := (others => '0');
                            v_vys   := '1';
                            v_by    := not s_vy_sign(i);
                        elsif s_hi_y(i) = '1' then
                            v_new_y := s_max_pos_y & "00000000";
                            v_vys   := '0';
                            v_by    := s_vy_sign(i);
                        end if;

                        s_pred_x(i)   <= v_new_x;
                        s_pred_y(i)   <= v_new_y;
                        s_pred_vx(i)  <= v_vxs;
                        s_pred_vy(i)  <= v_vys;
                        s_bounce_x(i) <= v_bx;
                        s_bounce_y(i) <= v_by;
                    end loop;
                    s_cx_on  <= (others => '0');
                    s_cy_on  <= (others => '0');
                    s_newhit <= (others => '0');
                    s_pcnt   <= (others => '0');
                    s_ph_phase <= to_unsigned(2, 2);

                -- ----------------------------------------------------
                -- Phase 2: feed pairs 0..5 into the pair pipe, wait for
                -- the last one to accumulate.
                -- ----------------------------------------------------
                when 2 =>
                    s_pcnt <= s_pcnt + 1;
                    if s_pcnt = 10 then
                        s_ph_phase <= to_unsigned(3, 2);
                    end if;

                -- ----------------------------------------------------
                -- Phase 3: commit.  Collision axes get separating
                -- directions; colors advance on wall hits and NEW
                -- collisions; a corner hit starts the party.
                -- ----------------------------------------------------
                when 3 =>
                    v_corner := '0';
                    for i in 0 to N_LOGOS - 1 loop
                        if s_step_sel = 7 then
                            v_step := s_lfsr(3 * i + 2 downto 3 * i);
                            if v_step = 0 then
                                v_step := to_unsigned(5, 3);
                            end if;
                        else
                            v_step := s_step_sel + 1;
                        end if;

                        if s_active(i) = '1' then
                            s_logo_x(i)  <= s_pred_x(i)(19 downto 8);
                            s_logo_y(i)  <= s_pred_y(i)(19 downto 8);
                            s_logo_xf(i) <= unsigned(s_pred_x(i)(7 downto 0));
                            s_logo_yf(i) <= unsigned(s_pred_y(i)(7 downto 0));
                            if s_pause = '0' then
                                if s_cx_on(i) = '1' then
                                    s_vx_sign(i) <= s_cx_dir(i);
                                else
                                    s_vx_sign(i) <= s_pred_vx(i);
                                end if;
                                if s_cy_on(i) = '1' then
                                    s_vy_sign(i) <= s_cy_dir(i);
                                else
                                    s_vy_sign(i) <= s_pred_vy(i);
                                end if;
                                if s_bounce_x(i) = '1' or s_bounce_y(i) = '1'
                                   or s_newhit(i) = '1' then
                                    s_color_idx(i) <= s_color_idx(i) + v_step;
                                end if;
                                if (s_bounce_x(i) = '1' and s_near_y(i) = '1') or
                                   (s_bounce_y(i) = '1' and s_near_x(i) = '1') then
                                    v_corner := '1';
                                end if;
                            end if;
                        else
                            -- Inactive: park at initial state.  When the
                            -- user raises Count, this logo enters the
                            -- screen at a known non-overlapping spot.
                            if i = 1 or i = 3 then
                                s_logo_x(i) <= s_park_x;
                            else
                                s_logo_x(i) <= C_INIT_X(i);
                            end if;
                            s_logo_y(i)    <= C_INIT_Y(i);
                            s_logo_xf(i)   <= (others => '0');
                            s_logo_yf(i)   <= (others => '0');
                            s_vx_sign(i)   <= C_INIT_VX(i);
                            s_vy_sign(i)   <= C_INIT_VY(i);
                            s_color_idx(i) <= C_INIT_COLOR(i);
                        end if;
                    end loop;

                    if v_corner = '1' then
                        s_party <= (others => '1');
                    elsif s_party /= 0 and s_pause = '0' then
                        s_party <= s_party - 1;
                    end if;

                    s_ph_phase <= to_unsigned(0, 2);

                when others =>
                    s_ph_phase <= to_unsigned(0, 2);
            end case;

            -- ----------------------------------------------------
            -- Wall / near-wall compare flags (free-running).
            -- ----------------------------------------------------
            for i in 0 to N_LOGOS - 1 loop
                v_int_x := s_pred_raw_x(i)(20 downto 8);
                v_int_y := s_pred_raw_y(i)(20 downto 8);
                s_lo_x(i) <= v_int_x(12);
                s_lo_y(i) <= v_int_y(12);
                if v_int_x >= s_max_pos_x then
                    s_hi_x(i) <= '1';
                else
                    s_hi_x(i) <= '0';
                end if;
                if v_int_y >= s_max_pos_y then
                    s_hi_y(i) <= '1';
                else
                    s_hi_y(i) <= '0';
                end if;
                if v_int_x < to_signed(C_CORNER_TOL, 13)
                   or v_int_x >= s_max_tol_x then
                    s_near_x(i) <= '1';
                else
                    s_near_x(i) <= '0';
                end if;
                if v_int_y < to_signed(C_CORNER_TOL, 13)
                   or v_int_y >= s_max_tol_y then
                    s_near_y(i) <= '1';
                else
                    s_near_y(i) <= '0';
                end if;
            end loop;

            -- ----------------------------------------------------
            -- Pair pipe (free-running; only fed during phase 2).
            -- ----------------------------------------------------
            -- A: fetch the pair's integer positions
            if s_pcnt < 6 then
                v_k := to_integer(s_pcnt(2 downto 0));
            else
                v_k := 0;
            end if;
            if s_ph_phase = 2 and s_pcnt < 6 then
                s_pa_valid <= '1';
            else
                s_pa_valid <= '0';
            end if;
            s_pa_k  <= v_k;
            s_pa_ax <= s_pred_x(C_PAIR_I(v_k))(20 downto 8);
            s_pa_bx <= s_pred_x(C_PAIR_J(v_k))(20 downto 8);
            s_pa_ay <= s_pred_y(C_PAIR_I(v_k))(20 downto 8);
            s_pa_by <= s_pred_y(C_PAIR_J(v_k))(20 downto 8);

            -- B: deltas
            s_pb_valid <= s_pa_valid;
            s_pb_k     <= s_pa_k;
            s_pb_dx    <= resize(s_pa_ax, 14) - resize(s_pa_bx, 14);
            s_pb_dy    <= resize(s_pa_ay, 14) - resize(s_pa_by, 14);

            -- C: magnitudes + which logo is first on each axis
            s_pc_valid <= s_pb_valid;
            s_pc_k     <= s_pb_k;
            s_pc_sx    <= s_pb_dx(13);
            s_pc_sy    <= s_pb_dy(13);
            v_d        := abs(s_pb_dx);
            s_pc_adx   <= unsigned(v_d(12 downto 0));
            v_d        := abs(s_pb_dy);
            s_pc_ady   <= unsigned(v_d(12 downto 0));

            -- D: overlap test + penetration comparison term
            s_pd_valid <= s_pc_valid;
            s_pd_k     <= s_pc_k;
            s_pd_sx    <= s_pc_sx;
            s_pd_sy    <= s_pc_sy;
            if s_mix_logos = '0' and
               s_active(C_PAIR_I(s_pc_k)) = '1' and
               s_active(C_PAIR_J(s_pc_k)) = '1' and
               s_pc_adx < unsigned(s_lw) and
               s_pc_ady < unsigned(s_lh) then
                s_pd_hit <= '1';
            else
                s_pd_hit <= '0';
            end if;
            s_pd_diff <= signed(resize(s_pc_adx, 14)) - signed(resize(s_pc_ady, 14));

            -- E: accumulate.  Penetration x = W - adx, y = H - ady; push
            -- apart along x when x penetrates less: adx - ady > W - H.
            if s_pd_valid = '1' then
                v_i := C_PAIR_I(s_pd_k);
                v_j := C_PAIR_J(s_pd_k);
                if s_pd_hit = '1' then
                    if s_pd_diff > s_lwh_diff then
                        s_cx_on(v_i)  <= '1';
                        s_cx_on(v_j)  <= '1';
                        s_cx_dir(v_i) <= not s_pd_sx;   -- i left of j → i goes left
                        s_cx_dir(v_j) <= s_pd_sx;
                    else
                        s_cy_on(v_i)  <= '1';
                        s_cy_on(v_j)  <= '1';
                        s_cy_dir(v_i) <= not s_pd_sy;
                        s_cy_dir(v_j) <= s_pd_sy;
                    end if;
                    if s_was_colliding(s_pd_k) = '0' then
                        s_newhit(v_i) <= '1';
                        s_newhit(v_j) <= '1';
                    end if;
                end if;
                s_was_colliding(s_pd_k) <= s_pd_hit;
            end if;
        end if;
    end process;

    -- ========================================================================
    -- Streaming ROM prefetch.  Slot i = h_count mod 4 serves logo i; each
    -- slot computes the word that logo needs 8 px ahead of the beam (in
    -- logo space: lead accumulator + the logo's offset) and fetches it into
    -- s_pf_buf(i)(word-index parity).  A word lasts 16/step >= 8 px and is
    -- refreshed every 4, so the double buffer always holds the current word
    -- by the time the render pipeline samples it.
    -- ========================================================================
    p_prefetch : process(clk)
        variable v_i     : integer range 0 to N_LOGOS - 1;
        variable v_valid : std_logic;
        variable v_by    : unsigned(7 downto 0);
        variable v_bxi   : signed(13 downto 0);
        variable v_byi   : signed(13 downto 0);
    begin
        if rising_edge(clk) then
            -- PF0: per-slot logo-space coords (one 20-bit add per axis)
            v_i := to_integer(s_h_count(1 downto 0));
            s_pf0_bxf <= signed(resize(s_hsl(24 downto C_QF), 20)) + s_cx(v_i);
            s_pf0_byf <= signed(resize(s_vs(24 downto C_QF), 20)) + s_dy(v_i);
            s_pf0_idx <= s_h_count(1 downto 0);

            -- PF1: bounds check + word address (by * 24 + bx >> 4), on the
            -- integer parts.
            v_bxi := s_pf0_bxf(19 downto C_QF);
            v_byi := s_pf0_byf(19 downto C_QF);
            if v_bxi >= to_signed(0, 14) and v_bxi < to_signed(C_LOGO_W, 14) and
               v_byi >= to_signed(0, 14) and v_byi < to_signed(C_LOGO_H, 14) then
                v_valid := '1';
            else
                v_valid := '0';
            end if;

            if v_valid = '1' then
                v_by := unsigned(v_byi(7 downto 0));
                s_pf1_addr <= resize(shift_left(resize(v_by, 13), 4), 13)
                            + resize(shift_left(resize(v_by, 13), 3), 13)
                            + resize(unsigned(v_bxi(8 downto 4)), 13);
            else
                s_pf1_addr <= (others => '0');
            end if;
            s_pf1_par   <= v_bxi(4);
            s_pf1_idx   <= s_pf0_idx;
            s_pf1_valid <= v_valid;

            -- PF2: synchronous ROM read (BRAM)
            s_pf2_word  <= C_LOGO_ROM(to_integer(s_pf1_addr));
            s_pf2_par   <= s_pf1_par;
            s_pf2_idx   <= s_pf1_idx;
            s_pf2_valid <= s_pf1_valid;

            -- PF3: buffer write
            if s_pf2_valid = '1' then
                if s_pf2_par = '1' then
                    s_pf_buf(to_integer(s_pf2_idx))(1) <= s_pf2_word;
                else
                    s_pf_buf(to_integer(s_pf2_idx))(0) <= s_pf2_word;
                end if;
            end if;
        end if;
    end process;

    -- ========================================================================
    -- S1 — logo-space beam (Q6) + per-logo offset snapshot
    -- ========================================================================
    p_stage1 : process(clk)
    begin
        if rising_edge(clk) then
            s_stg1_hs <= signed(resize(s_hs(24 downto C_QF), 20));
            s_stg1_vs <= signed(resize(s_vs(24 downto C_QF), 20));
            for i in 0 to N_LOGOS - 1 loop
                s_bnd_cx(i)     <= s_cx(i);
                s_bnd_dy(i)     <= s_dy(i);
                s_bnd_active(i) <= s_active(i);
            end loop;
        end if;
    end process;

    -- ========================================================================
    -- S2a — per-logo logo-space coords (one 20-bit add per axis)
    -- ========================================================================
    p_stage2a : process(clk)
    begin
        if rising_edge(clk) then
            for i in 0 to N_LOGOS - 1 loop
                s_stg2a_dx(i)     <= s_stg1_hs + s_bnd_cx(i);
                s_stg2a_dy(i)     <= s_stg1_vs + s_bnd_dy(i);
                s_stg2a_active(i) <= s_bnd_active(i);
            end loop;
        end if;
    end process;

    -- ========================================================================
    -- S2b — per-logo lit flags: inside the logo AND that logo's bitmap bit
    --       set (bit sampled from the prefetch buffer, even/odd word by
    --       integer bit 4).  Works on the integer part of lx / ly.
    -- ========================================================================
    p_stage2b : process(clk)
        variable v_in_x : std_logic;
        variable v_in_y : std_logic;
        variable v_bit  : std_logic;
        variable v_word : std_logic_vector(C_LOGO_WORD_W - 1 downto 0);
        variable v_lx   : signed(13 downto 0);
        variable v_ly   : signed(13 downto 0);
    begin
        if rising_edge(clk) then
            for i in 0 to N_LOGOS - 1 loop
                v_lx := s_stg2a_dx(i)(19 downto C_QF);
                v_ly := s_stg2a_dy(i)(19 downto C_QF);
                if v_lx >= to_signed(0, 14)
                   and v_lx < to_signed(C_LOGO_W, 14) then
                    v_in_x := '1';
                else
                    v_in_x := '0';
                end if;
                if v_ly >= to_signed(0, 14)
                   and v_ly < to_signed(C_LOGO_H, 14) then
                    v_in_y := '1';
                else
                    v_in_y := '0';
                end if;

                if v_lx(4) = '1' then
                    v_word := s_pf_buf(i)(1);
                else
                    v_word := s_pf_buf(i)(0);
                end if;
                v_bit := v_word(C_LOGO_WORD_W - 1 - to_integer(
                             unsigned(v_lx(3 downto 0))));

                s_stg2_lit(i) <= v_in_x and v_in_y and s_stg2a_active(i)
                                 and v_bit;
            end loop;
        end if;
    end process;

    -- ========================================================================
    -- S3 — gate per-logo palette contributions by the lit flags.
    -- ========================================================================
    p_stage3 : process(clk)
    begin
        if rising_edge(clk) then
            for i in 0 to N_LOGOS - 1 loop
                if s_stg2_lit(i) = '1' then
                    s_stg3_y(i)  <= s_pal_y(i);
                    s_stg3_uo(i) <= s_pal_uo(i);
                    s_stg3_vo(i) <= s_pal_vo(i);
                else
                    s_stg3_y(i)  <= (others => '0');
                    s_stg3_uo(i) <= (others => '0');
                    s_stg3_vo(i) <= (others => '0');
                end if;
            end loop;
            s_stg3_lit <= s_stg2_lit;
        end if;
    end process;

    -- ========================================================================
    -- S4 — pairwise partial sums (Mix path) + pairwise priority selects
    --      (Bounce path: lowest-index lit logo wins).
    -- ========================================================================
    p_stage4 : process(clk)
    begin
        if rising_edge(clk) then
            s_stg4_ysum01 <= resize(s_stg3_y(0), 11) + resize(s_stg3_y(1), 11);
            s_stg4_ysum23 <= resize(s_stg3_y(2), 11) + resize(s_stg3_y(3), 11);
            s_stg4_uo01 <= resize(s_stg3_uo(0), 12) + resize(s_stg3_uo(1), 12);
            s_stg4_uo23 <= resize(s_stg3_uo(2), 12) + resize(s_stg3_uo(3), 12);
            s_stg4_vo01 <= resize(s_stg3_vo(0), 12) + resize(s_stg3_vo(1), 12);
            s_stg4_vo23 <= resize(s_stg3_vo(2), 12) + resize(s_stg3_vo(3), 12);

            if s_stg3_lit(0) = '1' then
                s_stg4_sely01  <= s_stg3_y(0);
                s_stg4_seluo01 <= s_stg3_uo(0);
                s_stg4_selvo01 <= s_stg3_vo(0);
            else
                s_stg4_sely01  <= s_stg3_y(1);
                s_stg4_seluo01 <= s_stg3_uo(1);
                s_stg4_selvo01 <= s_stg3_vo(1);
            end if;
            if s_stg3_lit(2) = '1' then
                s_stg4_sely23  <= s_stg3_y(2);
                s_stg4_seluo23 <= s_stg3_uo(2);
                s_stg4_selvo23 <= s_stg3_vo(2);
            else
                s_stg4_sely23  <= s_stg3_y(3);
                s_stg4_seluo23 <= s_stg3_uo(3);
                s_stg4_selvo23 <= s_stg3_vo(3);
            end if;
            s_stg4_lit01 <= s_stg3_lit(0) or s_stg3_lit(1);
            s_stg4_lit23 <= s_stg3_lit(2) or s_stg3_lit(3);
            s_stg4_any   <= s_stg3_lit(0) or s_stg3_lit(1)
                            or s_stg3_lit(2) or s_stg3_lit(3);
        end if;
    end process;

    -- ========================================================================
    -- S5 — final combine, still as offsets.  Bounce: priority pick.  Mix:
    --      additive sum, Y offset capped at 704 (Y <= 768), U/V offsets
    --      clamped to +/-448 (never chroma code 0 = saturated green).
    -- ========================================================================
    p_stage5 : process(clk)
        variable v_ysum : unsigned(11 downto 0);
        variable v_uo   : signed(12 downto 0);
        variable v_vo   : signed(12 downto 0);
    begin
        if rising_edge(clk) then
            if s_mix_logos = '1' then
                v_ysum := resize(s_stg4_ysum01, 12) + resize(s_stg4_ysum23, 12);
                if v_ysum > to_unsigned(C_Y_OFF_MAX, 12) then
                    s_stg5_y <= to_unsigned(C_Y_OFF_MAX, 10);
                else
                    s_stg5_y <= v_ysum(9 downto 0);
                end if;

                v_uo := resize(s_stg4_uo01, 13) + resize(s_stg4_uo23, 13);
                v_vo := resize(s_stg4_vo01, 13) + resize(s_stg4_vo23, 13);
                if v_uo < to_signed(-C_C_OFF_MAX, 13) then
                    s_stg5_uo <= to_signed(-C_C_OFF_MAX, 11);
                elsif v_uo > to_signed(C_C_OFF_MAX, 13) then
                    s_stg5_uo <= to_signed(C_C_OFF_MAX, 11);
                else
                    s_stg5_uo <= v_uo(10 downto 0);
                end if;
                if v_vo < to_signed(-C_C_OFF_MAX, 13) then
                    s_stg5_vo <= to_signed(-C_C_OFF_MAX, 11);
                elsif v_vo > to_signed(C_C_OFF_MAX, 13) then
                    s_stg5_vo <= to_signed(C_C_OFF_MAX, 11);
                else
                    s_stg5_vo <= v_vo(10 downto 0);
                end if;
            else
                -- Priority pick: single palette entries are always legal.
                if s_stg4_lit01 = '1' then
                    s_stg5_y  <= s_stg4_sely01;
                    s_stg5_uo <= s_stg4_seluo01;
                    s_stg5_vo <= s_stg4_selvo01;
                else
                    s_stg5_y  <= s_stg4_sely23;
                    s_stg5_uo <= s_stg4_seluo23;
                    s_stg5_vo <= s_stg4_selvo23;
                end if;
            end if;
            s_stg5_show <= s_stg4_any;
        end if;
    end process;

    -- ========================================================================
    -- S6 — re-bias offsets to codes: Y = 64 + yo, U/V = 512 + offset.
    -- ========================================================================
    p_stage6 : process(clk)
        variable v_c : signed(10 downto 0);
    begin
        if rising_edge(clk) then
            s_out_y <= s_stg5_y + C_Y_BLACK;
            v_c     := s_stg5_uo + to_signed(512, 11);
            s_out_u <= unsigned(v_c(9 downto 0));
            v_c     := s_stg5_vo + to_signed(512, 11);
            s_out_v <= unsigned(v_c(9 downto 0));
            s_out_show <= s_stg5_show;
        end if;
    end process;

    -- ========================================================================
    -- Sync + data delay
    -- ========================================================================
    p_delay : process(clk)
    begin
        if rising_edge(clk) then
            s_sync_pipe(0) <= data_in.field_n & data_in.avid &
                              data_in.vsync_n & data_in.hsync_n;
            for i in 1 to C_DELAY - 1 loop
                s_sync_pipe(i) <= s_sync_pipe(i - 1);
            end loop;

            s_y_delay(0) <= data_in.y;
            s_u_delay(0) <= data_in.u;
            s_v_delay(0) <= data_in.v;
            for i in 1 to C_DELAY - 1 loop
                s_y_delay(i) <= s_y_delay(i - 1);
                s_u_delay(i) <= s_u_delay(i - 1);
                s_v_delay(i) <= s_v_delay(i - 1);
            end loop;
        end if;
    end process;

    -- ========================================================================
    -- Output register: wet select + blanking gate.  Outside the
    -- latency-aligned avid the output is forced to neutral black so the
    -- encoders never see video/garbage in the blanking interval.
    -- ========================================================================
    p_out : process(clk)
    begin
        if rising_edge(clk) then
            if s_sync_pipe(C_DELAY - 1)(2) = '0' then
                s_fin_y <= std_logic_vector(C_Y_BLACK);
                s_fin_u <= std_logic_vector(C_CHROMA_MID);
                s_fin_v <= std_logic_vector(C_CHROMA_MID);
            elsif s_out_show = '1' and s_matte = '0' then
                s_fin_y <= std_logic_vector(s_out_y);
                s_fin_u <= std_logic_vector(s_out_u);
                s_fin_v <= std_logic_vector(s_out_v);
            elsif s_out_show = '1' and s_bg_black = '1' then
                -- Matte over black: the logo is a window onto the video.
                s_fin_y <= s_y_delay(C_DELAY - 1);
                s_fin_u <= s_u_delay(C_DELAY - 1);
                s_fin_v <= s_v_delay(C_DELAY - 1);
            elsif s_out_show = '1' or s_bg_black = '1' then
                -- Matte over video: the logo knocks a black hole in it.
                -- Or no logo over a black background.
                s_fin_y <= std_logic_vector(C_Y_BLACK);
                s_fin_u <= std_logic_vector(C_CHROMA_MID);
                s_fin_v <= std_logic_vector(C_CHROMA_MID);
            else
                s_fin_y <= s_y_delay(C_DELAY - 1);
                s_fin_u <= s_u_delay(C_DELAY - 1);
                s_fin_v <= s_v_delay(C_DELAY - 1);
            end if;
            s_fin_sync <= s_sync_pipe(C_DELAY - 1);
        end if;
    end process;

    s_io_align_in.y       <= s_fin_y;
    s_io_align_in.u       <= s_fin_u;
    s_io_align_in.v       <= s_fin_v;
    s_io_align_in.hsync_n <= s_fin_sync(0);
    s_io_align_in.vsync_n <= s_fin_sync(1);
    s_io_align_in.avid    <= s_fin_sync(2);
    s_io_align_in.field_n <= s_fin_sync(3);

    -- IO-align pad: video and syncs delayed together, so only the total
    -- latency changes (10 -> 12).
    p_io_align_pad : process(clk)
    begin
        if rising_edge(clk) then
            s_io_align_pad(0) <= s_io_align_in;
            for i in 1 to 1 loop
                s_io_align_pad(i) <= s_io_align_pad(i - 1);
            end loop;
        end if;
    end process p_io_align_pad;

    data_out <= s_io_align_pad(1);

end architecture dvdlogo;

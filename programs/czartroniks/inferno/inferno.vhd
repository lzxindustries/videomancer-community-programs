-- Inferno: Procedural flame — domain-warped multi-octave value noise,
-- PIXELATED: every screen coordinate feeding the engine is quantized to a
-- block grid (K2 Pixels, 8..70 px at 1080p, same share of the screen height in
-- every mode), the palette is
-- posterized to 32 steps and smoke to 16, embers are per-block hashes and
-- all per-pixel dither is gone — a deliberately retro, fake-looking fire
-- (Pyre is the realistic one).
-- LZX Industries Community FPGA Program
--
-- Algorithm (shader-style fire, streaming at 1 px/clk, no divides):
--   1. World coords in 1/16 px units rise over time (sub-pixel advection);
--      the warp field rises slower than the flame body so shapes evolve
--      as they climb.  A slow sine-integrated lateral drift sways the flame.
--   2. A low-frequency value noise domain-warps x — real turbulence,
--      licking tongues instead of sinusoidal wobble.
--   3. Three octaves of smooth value noise (smoothstep bilinear; 64-step
--      fraction on the tall cells) at 2:1..4:1 vertical stretch; the finest
--      octave is ridged for filaments.  A second, coarser/slower layer
--      (dark red) composites by max in heat space.
--   4. Vertical gradient (1 heat unit per line, start value servo-locked to
--      the measured frame height — no divide, adapts to any video mode)
--      minus a noise "cut" -> ragged flame heat field.
--   5. 1024-entry palette ROM in BRAM (fire / dark red / blue / violet
--      banks, generated by genpal.py; limited-range 64..768 luma), LFSR heat
--      dither breaks contour banding.
--   6. S8 Luma Mod: quarter-res Canny edges re-root the gradient per column.
--   Output is gated to neutral black outside active video; per-field state
--   updates fire once per field even when analog vsync serrates.
--
-- v2.0.3 (2026-10-18): resolution scaling.  Block grid, world coordinates,
-- gradient (heat per line), Luma-Mod roots and the zoom centre run in
-- virtual 1080-line units (x step 1/1.5/2 per pixel, y step per field line
-- from the timing ID): 720p and SD show the 1080p blocks and flame heights
-- relative to screen height, square blocks on a 4:3 SD screen (SD = the
-- centre 1440 units).  The Canny detector stays at pixel scale.  1080p is
-- unchanged.
--

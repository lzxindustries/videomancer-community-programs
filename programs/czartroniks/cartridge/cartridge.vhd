    signal s_pb_st  : unsigned(2 downto 0) := (others => '0');
    signal s_pb_e   : unsigned(9 downto 0) := (others => '0');
    signal s_pb_i   : unsigned(3 downto 0) := (others => '0');
    signal s_pb_rom, s_pb_m : std_logic_vector(23 downto 0) := (others => '0');
    signal s_pb_ady, s_pb_adu, s_pb_adv : unsigned(7 downto 0) := (others => '0');
    signal s_pb_d   : unsigned(9 downto 0) := (others => '0');
    signal s_pb_min : unsigned(9 downto 0) := (others => '1');
    signal s_pb_idx : unsigned(3 downto 0) := (others => '0');
    signal s_pb_we  : std_logic := '0';
    signal s_pb_wa  : unsigned(9 downto 0) := (others => '0');
    signal s_pb_wd  : std_logic_vector(3 downto 0) := (others => '0');

    --------------------------------------------------------------------------
    -- Line-RAM stages (@n = clocks after data_in)
    --------------------------------------------------------------------------
    signal s_cnt    : unsigned(10 downto 0) := (others => '0');
    signal s_a_x    : unsigned(10 downto 0) := (others => '0');
    signal s_a_y, s_a_u, s_a_v : unsigned(9 downto 0) := (others => '0');
    signal s_a_av   : std_logic := '0';
    type t_w20 is array (2 to 5) of std_logic_vector(19 downto 0);
    signal s_lw20   : t_w20 := (others => (others => '0'));
    type t_x is array (2 to 5) of unsigned(10 downto 0);
    signal s_lx     : t_x := (others => (others => '0'));
    type t_av is array (2 to 5) of std_logic;
    signal s_lav    : t_av := (others => '0');
    signal s_rd3    : std_logic_vector(31 downto 0) := (others => '0');
    signal s_dv4    : signed(9 downto 0) := (others => '0');
    signal s_y1_4, s_y1_5 : std_logic_vector(7 downto 0) := (others => '0');
    signal s_c4, s_c5 : unsigned(3 downto 0) := (others => '0');
    signal s_ev5    : std_logic := '0';
    signal s_we6    : std_logic := '0';
    signal s_wa6    : unsigned(10 downto 0) := (others => '0');
    signal s_wd6    : std_logic_vector(31 downto 0) := (others => '0');
    signal s_inkv6  : std_logic := '0';

    --------------------------------------------------------------------------
    -- Pixel chain (content = row y-1)
    --------------------------------------------------------------------------
    type t_taps is array (0 to 16) of unsigned(7 downto 0);
    signal s_t      : t_taps := (others => (others => '0'));
    type t_tav is array (0 to 16) of std_logic;
    signal s_ta     : t_tav := (others => '0');
    type t_cc is array (0 to 9) of std_logic_vector(11 downto 0);
    signal s_cc     : t_cc := (others => (others => '0'));
    type t_iv is array (7 to 13) of std_logic;
    signal s_iv     : t_iv := (others => '0');
    signal s_d13    : signed(9 downto 0) := (others => '0');
    signal s_tl12, s_tr12 : unsigned(7 downto 0) := (others => '0');
    signal s_tokl12, s_tokr12 : std_logic := '0';
    signal s_ok13   : std_logic := '0';
    signal s_y13    : unsigned(7 downto 0) := (others => '0');
    signal s_yi14   : unsigned(7 downto 0) := (others => '0');
    signal s_ym15   : signed(10 downto 0) := (others => '0');
    signal s_rp16   : signed(19 downto 0) := (others => '0');
    signal s_yr17, s_yr18, s_yr19 : unsigned(9 downto 0) := (others => '0');
    signal s_pr19   : unsigned(7 downto 0) := (others => '0');
    signal s_ycel20, s_ylut20, s_ylut21 : unsigned(9 downto 0) := (others => '0');
    signal s_bay20  : signed(4 downto 0) := (others => '0');
    signal s_doff21 : signed(13 downto 0) := (others => '0');
    signal s_yl22, s_ul22, s_vl22 : unsigned(9 downto 0) := (others => '0');
    signal s_idx24  : unsigned(3 downto 0) := (others => '0');
    signal s_py26, s_pu26, s_pv26 : unsigned(7 downto 0) := (others => '0');
    signal s_py27, s_pu27, s_pv27 : unsigned(7 downto 0) := (others => '0');
    signal s_pr28, s_py28, s_pu28, s_pv28 : unsigned(7 downto 0) := (others => '0');
    signal s_ys29   : unsigned(9 downto 0) := to_unsigned(64, 10);
    signal s_pu29, s_pv29 : unsigned(7 downto 0) := to_unsigned(128, 8);
    -- original pixel (S9) and edge flag carried from the tap centre
    type t_org is array (14 to 29) of std_logic_vector(19 downto 0);
    signal s_org    : t_org := (others => (others => '0'));
    type t_ed is array (14 to 29) of std_logic;
    signal s_ed     : t_ed := (others => '0');
    type t_yc is array (21 to 28) of unsigned(9 downto 0);
    signal s_yc     : t_yc := (others => (others => '0'));
    signal s_y30    : unsigned(9 downto 0) := to_unsigned(64, 10);
    signal s_u30, s_v30 : unsigned(9 downto 0) := to_unsigned(512, 10);
    -- output conditioning: [1 2 1] window, g1 the centre
    signal s_g1y, s_g2y : unsigned(9 downto 0) := to_unsigned(64, 10);
    signal s_g1u, s_g2u, s_g1v, s_g2v : unsigned(9 downto 0) := to_unsigned(512, 10);
    signal s_y32    : unsigned(9 downto 0) := to_unsigned(64, 10);
    signal s_u32, s_v32 : unsigned(9 downto 0) := to_unsigned(512, 10);
    signal s_y33    : unsigned(9 downto 0) := to_unsigned(64, 10);
    signal s_u33, s_v33 : unsigned(9 downto 0) := to_unsigned(512, 10);

    type t_bit_shift is array (0 to C_LAT - 1) of std_logic;
    signal s_hsync_sr : t_bit_shift := (others => '1');
    signal s_vsync_sr : t_bit_shift := (others => '1');
    signal s_field_sr : t_bit_shift := (others => '1');
    signal s_avid_sr  : t_bit_shift := (others => '0');
    signal s_gav_sr   : t_bit_shift := (others => '0');

begin

    s_k_edge   <= unsigned(registers_in(0));
    s_k_levels <= unsigned(registers_in(1));
    s_k_width  <= unsigned(registers_in(2));
    s_k_pal    <= unsigned(registers_in(3));
    s_k_dither <= unsigned(registers_in(4));
    s_k_range  <= unsigned(registers_in(5));
    s_p_ink    <= unsigned(registers_in(7));

    --------------------------------------------------------------------------
    -- Memories
    --------------------------------------------------------------------------
    p_lram : process(clk)
    begin
        if rising_edge(clk) then
            s_rd <= r_line(to_integer(s_a_x));
            if s_we6 = '1' then
                r_line(to_integer(s_wa6)) <= s_wd6;
            end if;
        end if;
    end process;

    p_mem : process(clk)
    begin
        if rising_edge(clk) then
            s_lut_q <= qlut(to_integer(s_yl22(9 downto 6) & s_ul22(9 downto 7) & s_vl22(9 downto 7)));
            if s_pb_we = '1' then
                qlut(to_integer(s_pb_wa)) <= s_pb_wd;
            end if;
            s_pyc_q <= C_PAL_YC(to_integer(s_zone & s_idx24));
            s_pb_q  <= C_PAL_B(to_integer(s_zone & s_idx24));
            s_pq18  <= C_POST(to_integer(s_lev & s_yr17(9 downto 4)));
            s_pq27  <= C_POST(to_integer(s_lev & s_py26(7 downto 2)));
        end if;
    end process;

    --------------------------------------------------------------------------
    -- Palette LUT builder: for every Y4 Cr3 Cb3 cell (centred on 64k / 128k
    -- in 10-bit, so black and neutral sit on cell centres) find the nearest
    -- of the zone's 16 match colours, 2|dy| + |du| + |dv|.  ~1.1 ms a pass.
    --------------------------------------------------------------------------
    p_pal_build : process(clk)
        variable v_yq, v_uq, v_vq : unsigned(7 downto 0);
    begin
        if rising_edge(clk) then
            s_pb_we  <= '0';
            s_pb_rom <= C_MATCH(to_integer(s_zone & s_pb_i));
            v_yq := s_pb_e(9 downto 6) & "0000";
            v_uq := s_pb_e(5 downto 3) & "00000";
            v_vq := s_pb_e(2 downto 0) & "00000";
            case to_integer(s_pb_st) is
                when 0 =>
                    s_pb_st <= s_pb_st + 1;
                when 1 =>
                    s_pb_m  <= s_pb_rom;
                    s_pb_st <= s_pb_st + 1;
                when 2 =>
                    s_pb_ady <= f_absd8(unsigned(s_pb_m(23 downto 16)), v_yq);
                    s_pb_adu <= f_absd8(unsigned(s_pb_m(15 downto 8)), v_uq);
                    s_pb_adv <= f_absd8(unsigned(s_pb_m(7 downto 0)), v_vq);
                    s_pb_st  <= s_pb_st + 1;
                when 3 =>
                    s_pb_d  <= shift_left(resize(s_pb_ady, 10), 1) + resize(s_pb_adu, 10) + resize(s_pb_adv, 10);
                    s_pb_st <= s_pb_st + 1;
                when 4 =>
                    if s_pb_d < s_pb_min then
                        s_pb_min <= s_pb_d;
                        s_pb_idx <= s_pb_i;
                    end if;
                    if s_pb_i = 15 then
                        s_pb_st <= s_pb_st + 1;
                    else
                        s_pb_i  <= s_pb_i + 1;
                        s_pb_st <= (others => '0');
                    end if;
                when others =>
                    s_pb_we  <= '1';
                    s_pb_wa  <= s_pb_e;
                    s_pb_wd  <= std_logic_vector(s_pb_idx);
                    s_pb_e   <= s_pb_e + 1;
                    s_pb_i   <= (others => '0');
                    s_pb_min <= (others => '1');
                    s_pb_st  <= (others => '0');
            end case;
        end if;
    end process;

    --------------------------------------------------------------------------
    -- Generated avid
    --------------------------------------------------------------------------
    p_gavid : process(clk)
    begin
        if rising_edge(clk) then
            g_hsq <= data_in.hsync_n;
            g_hsr <= g_hsq and not data_in.hsync_n;
            g_avq <= data_in.avid;
            g_avr <= data_in.avid and not g_avq;

            if g_hsr = '1' then
                g_ph  <= '0';
                g_arm <= '1';
            else
                g_ph <= not g_ph;
            end if;
            g_rsr <= g_rsr(1 downto 0) & '0';
            -- registered: g_sel never changes within two clocks of g_rsr(0)
            if (g_sel = '0' and g_rsr(0) = '1') or (g_sel = '1' and g_rsr(1) = '1') then
                g_go <= '1';
            else
                g_go <= '0';
            end if;
            if g_avr = '1' and g_arm = '1' then
                g_arm    <= '0';
                g_rsr(0) <= '1';
                g_sel    <= g_ph xor g_par;
                if g_ph = '1' then
                    if g_pc /= 15 then g_pc <= g_pc + 1; end if;
                else
                    if g_pc /= 0 then g_pc <= g_pc - 1; end if;
                end if;
            end if;
            if g_pc = 15 then g_par <= '1';
            elsif g_pc = 0 then g_par <= '0'; end if;

            if g_go = '1' then
                g_avid <= '1';
                g_cnt  <= (others => '0');
            elsif g_avid = '1' then
                g_cnt <= g_cnt + 1;
                if g_cnt = g_wm1 or g_hsr = '1' then
                    g_avid <= '0';
                end if;
            end if;
        end if;
    end process p_gavid;

    --------------------------------------------------------------------------
    -- Controls + line timing
    --------------------------------------------------------------------------
    p_ctrl : process(clk)
        variable v_k13 : unsigned(13 downto 0);
        variable v_ws  : unsigned(2 downto 0);
        variable v_w   : unsigned(1 downto 0);
        variable v_t   : unsigned(6 downto 0);
    begin
        if rising_edge(clk) then
            -- threshold: 2 + K1 * 13/128 (8-bit luma units, 2..105), then
            -- P12 takes off up to 3/4 of it
            v_k13 := shift_left(resize(s_k_edge, 14), 3) + shift_left(resize(s_k_edge, 14), 2) + resize(s_k_edge, 14);
            s_thb <= to_unsigned(2, 7) + v_k13(13 downto 7);
            s_tp  <= s_thb * s_p_ink(9 downto 4);
            s_tp3 <= shift_left(resize(s_tp, 15), 1) + resize(s_tp, 15);
            v_t := s_thb - s_tp3(14 downto 8);
            if v_t < 2 or v_t > s_thb then
                s_thr_c <= to_unsigned(2, 7);
            else
                s_thr_c <= v_t;
            end if;
            -- the firmware loads a labelled default as the label INDEX; honour
            -- it only until the knob first reads a real position
            if s_k_levels >= 8 then s_live2 <= '1'; end if;
            if s_k_width  >= 4 then s_live3 <= '1'; end if;
            if s_k_pal    >= 8 then s_live4 <= '1'; end if;
            if s_live2 = '0' and s_k_levels < 8 then
                s_lev_c <= s_k_levels(2 downto 0);
            else
                s_lev_c <= s_k_levels(9 downto 7);
            end if;
            if s_live3 = '0' and s_k_width < 4 then
                v_w := s_k_width(1 downto 0);
            else
                v_w := s_k_width(9 downto 8);
            end if;
            if s_live4 = '0' and s_k_pal < 8 then
                s_zone_c <= s_k_pal(2 downto 0);
            else
                s_zone_c <= s_k_pal(9 downto 7);
            end if;
            v_ws := resize(v_w, 3) + resize(s_p_ink(9 downto 8), 3);
            if v_ws > 3 then
                s_wsel_c <= "11";
            else
                s_wsel_c <= v_ws(1 downto 0);
            end if;

            -- timing-ID class, free-running (static while a mode runs)
            case to_integer(unsigned(registers_in(8)(3 downto 0))) is
                when 0 | 4 | 8 | 12 => s_cls_sd <= '1'; s_cls_7 <= '0';
                when 5 | 6 | 14     => s_cls_sd <= '0'; s_cls_7 <= '1';
                when others         => s_cls_sd <= '0'; s_cls_7 <= '0';
            end case;

            -- line timing on the live input
            s_prev_avid <= data_in.avid;
            if data_in.avid = '1' then
                s_gap <= (others => '0');
                s_rx  <= s_rx + 1;
            else
                s_rx <= (others => '0');
                if s_gap(11) = '0' then
                    s_gap <= s_gap + 1;
                end if;
            end if;
            if s_prev_avid = '1' and data_in.avid = '0' then
                s_lw <= s_rx;
            end if;
            if s_prev_avid = '0' and data_in.avid = '1' then
                if s_gap(11) = '1' then
                    s_lidx <= (others => '0');
                    s_lcnt <= (others => '0');
                else
                    if s_lidx /= 2 then s_lidx <= s_lidx + 1; end if;
                    s_lcnt <= s_lcnt + 1;
                end if;
            end if;
            if s_lidx = 0 then s_row0 <= '1'; else s_row0 <= '0'; end if;
            if s_lidx = 2 then s_vok <= '1'; else s_vok <= '0'; end if;

            -- latch everything while the frame is in vertical blanking
            if s_gap(11) = '1' then
                s_thrp   <= signed(resize(s_thr_c, 10));
                s_thrn   <= -signed(resize(s_thr_c, 10));
                if s_cls_sd = '1' then
                    s_wsel <= C_TAP_SD(to_integer(s_wsel_c));
                    s_ext  <= C_EXT_SD(to_integer(s_wsel_c));
                elsif s_cls_7 = '1' then
                    s_wsel <= C_TAP_7(to_integer(s_wsel_c));
                    s_ext  <= C_EXT_7(to_integer(s_wsel_c));
                else
                    s_wsel <= C_TAP_HD(to_integer(s_wsel_c));
                    s_ext  <= C_EXT(to_integer(s_wsel_c));
                end if;
                s_lev    <= s_lev_c;
                s_zone   <= s_zone_c;
                s_range  <= s_k_range(9 downto 2);
                s_dfrac  <= s_k_dither(9 downto 2);
                s_inkt   <= registers_in(6)(0);
                s_order  <= registers_in(6)(1);
                s_keep   <= registers_in(6)(2);
                s_lumacel <= registers_in(6)(3);
                s_inv    <= registers_in(6)(4);
                s_hd     <= s_lw(10);
                g_wm1    <= s_lw - 1;
            end if;
        end if;
    end process p_ctrl;

    --------------------------------------------------------------------------
    -- Line RAM read-modify-write + vertical ink (@1 .. @6)
    --------------------------------------------------------------------------
    p_line : process(clk)
        variable v_u6, v_v6 : unsigned(5 downto 0);
    begin
        if rising_edge(clk) then
            -- @1: register the live pixel, column from the avid rise
            s_a_y <= unsigned(data_in.y); s_a_u <= unsigned(data_in.u); s_a_v <= unsigned(data_in.v);
            s_a_av <= data_in.avid;
            if data_in.avid = '1' then
                s_a_x <= s_cnt;
                s_cnt <= s_cnt + 1;
            else
                s_a_x <= (others => '0');
                s_cnt <= (others => '0');
            end if;
            -- @2: RAM read lands; pack the live pixel Y8 Cr6 Cb6
            v_u6 := f_c6(s_a_u);
            v_v6 := f_c6(s_a_v);
            s_lw20(2) <= std_logic_vector(s_a_y(9 downto 2)) & std_logic_vector(v_u6) & std_logic_vector(v_v6);
            s_lx(2) <= s_a_x; s_lav(2) <= s_a_av;
            -- @3: fabric copy of the RAM word
            s_rd3 <= s_rd;
            -- @4: vertical gradient, row y (live) - row y-2
            -- (SD: row y-1 - row y-2, so an edge marks one field line, not
            -- the two straddling it -- one field line is already ~2 px tall)
            if s_cls_sd = '1' then
                s_dv4 <= signed(resize(unsigned(s_rd3(31 downto 24)), 10)) - signed(resize(unsigned(s_rd3(11 downto 4)), 10));
            else
                s_dv4 <= signed(resize(unsigned(s_lw20(3)(19 downto 12)), 10)) - signed(resize(unsigned(s_rd3(11 downto 4)), 10));
            end if;
            s_y1_4 <= s_rd3(31 downto 24);
            s_c4   <= unsigned(s_rd3(3 downto 0));
            -- @5: vertical edge (rows above the frame masked)
            if (s_dv4 > s_thrp or s_dv4 < s_thrn) and s_vok = '1' then
                s_ev5 <= '1';
            else
                s_ev5 <= '0';
            end if;
            s_y1_5 <= s_y1_4;
            s_c5   <= s_c4;
            -- @6: ink counter: reload on an edge, count down after it; write
            -- {live row, old row y-1 luma, counter} back to the same column
            if s_row0 = '1' then
                s_inkv6 <= '0';
                s_wd6 <= s_lw20(5) & s_y1_5 & "0000";
            elsif s_ev5 = '1' then
                s_inkv6 <= '1';
                s_wd6 <= s_lw20(5) & s_y1_5 & std_logic_vector(s_ext);
            elsif s_c5 /= 0 then
                s_inkv6 <= '1';
                s_wd6 <= s_lw20(5) & s_y1_5 & std_logic_vector(s_c5 - 1);
            else
                s_inkv6 <= '0';
                s_wd6 <= s_lw20(5) & s_y1_5 & "0000";
            end if;
            s_we6 <= s_lav(5);
            s_wa6 <= s_lx(5);
            for i in 3 to 5 loop
                s_lw20(i) <= s_lw20(i - 1); s_lx(i) <= s_lx(i - 1); s_lav(i) <= s_lav(i - 1);
            end loop;
        end if;
    end process p_line;

    --------------------------------------------------------------------------
    -- Pixel pipeline on row y-1 (@4 .. @33)
    --------------------------------------------------------------------------
    p_pix : process(clk)
        variable v_l, v_r : unsigned(7 downto 0);
        variable v_okl, v_okr : std_logic;
        variable v_bx, v_by : unsigned(1 downto 0);
        variable v_ink : std_logic;
        variable v_sy, v_su, v_sv : unsigned(11 downto 0);
        variable v_d, v_yo : unsigned(9 downto 0);
    begin
        if rising_edge(clk) then
            -- @4..@12: taps on the stored row (centre = t(8)), chroma, avid
            s_t(0)  <= unsigned(s_rd3(31 downto 24));
            s_ta(0) <= s_lav(3);
            s_cc(0) <= s_rd3(23 downto 12);
            for i in 1 to 16 loop
                s_t(i) <= s_t(i - 1); s_ta(i) <= s_ta(i - 1);
            end loop;
            for i in 1 to 9 loop
                s_cc(i) <= s_cc(i - 1);
            end loop;
            s_iv(7) <= s_inkv6;
            for i in 8 to 13 loop
                s_iv(i) <= s_iv(i - 1);
            end loop;
            -- @13: horizontal gradient across the selected spacing; both taps
            -- must lie inside the line (no ink bars at the frame sides)
            -- (v0.2.2: six spacings now, so the taps are picked a clock
            -- early from one tap upstream -- the same samples, s_t(i) is
            -- s_t(i-1) a clock later -- and the subtract stays alone)
            case to_integer(s_wsel) is
                when 0 =>      v_l := s_t(8);  v_r := s_t(6); v_okl := s_ta(8);  v_okr := s_ta(6);
                when 1 =>      v_l := s_t(9);  v_r := s_t(5); v_okl := s_ta(9);  v_okr := s_ta(5);
                when 2 =>      v_l := s_t(10); v_r := s_t(4); v_okl := s_ta(10); v_okr := s_ta(4);
                when 3 =>      v_l := s_t(11); v_r := s_t(3); v_okl := s_ta(11); v_okr := s_ta(3);
                when 4 =>      v_l := s_t(12); v_r := s_t(2); v_okl := s_ta(12); v_okr := s_ta(2);
                when others => v_l := s_t(15); v_r := unsigned(s_rd3(31 downto 24));
                               v_okl := s_ta(15); v_okr := s_lav(3);
            end case;
            s_tl12 <= v_l; s_tr12 <= v_r; s_tokl12 <= v_okl; s_tokr12 <= v_okr;
            s_d13  <= signed(resize(s_tr12, 10)) - signed(resize(s_tl12, 10));
            s_ok13 <= s_tokl12 and s_tokr12;
            s_y13  <= s_t(8);
            -- @14: ink flag; invert (16 <-> 235); original pixel for S9
            if ((s_d13 > s_thrp or s_d13 < s_thrn) and s_ok13 = '1') or s_iv(13) = '1' then
                s_ed(14) <= '1';
            else
                s_ed(14) <= '0';
            end if;
            if s_inv = '1' then
                if s_y13 > 251 then
                    s_yi14 <= (others => '0');
                else
                    s_yi14 <= 251 - s_y13;
                end if;
            else
                s_yi14 <= s_y13;
            end if;
            s_org(14) <= std_logic_vector(s_y13) & s_cc(9);
            -- @15..@17: range, y = 64 + (y - 64) * range / 64
            s_ym15 <= signed(resize(s_yi14 & "00", 11)) - 64;
            s_rp16 <= s_ym15 * signed('0' & s_range);
            s_yr17 <= f_clamp10(resize(shift_right(s_rp16, 6), 13) + 64);
            -- @18: band ROM lands (p_mem); @19: fabric copy
            s_yr18 <= s_yr17;
            s_yr19 <= s_yr18;
            s_pr19 <= unsigned(s_pq18);
            -- @20: cel luma = bands (or the ranged luma when Off); the
            -- palette sees the bands only in Cel First order
            if s_lev = 0 then
                s_ycel20 <= s_yr19;
                s_ylut20 <= s_yr19;
            else
                s_ycel20 <= s_pr19 & "00";
                if s_order = '0' then
                    s_ylut20 <= s_pr19 & "00";
                else
                    s_ylut20 <= s_yr19;
                end if;
            end if;
            -- Bayer cell: 2 px x 2 rows in HD, 1 px x 1 field line in SD.
            -- v0.2.2: SD keyed its rows on {line, field}, but field_n is tied
            -- high on the hardware, so SD only ever dithered on Bayer rows 0
            -- and 2 (8 of the 16 levels); it now steps all four per line.
            if s_avid_sr(17) = '1' then s_bx <= s_bx + 1; else s_bx <= (others => '0'); end if;
            if s_hd = '1' then
                v_bx := s_bx(2 downto 1);
                v_by := s_lcnt(2 downto 1);
            else
                v_bx := s_bx(1 downto 0);
                v_by := s_lcnt(1 downto 0);
            end if;
            s_bay20 <= to_signed(C_BAYER(to_integer(v_by & v_bx)), 5) - 8;
            -- @21: dither offset
            s_doff21 <= resize(s_bay20 * signed('0' & s_dfrac), 14);
            s_ylut21 <= s_ylut20;
            -- @22: dither + cell-centring bias -> LUT address
            s_yl22 <= f_clamp10(signed(resize(s_ylut21, 14)) + shift_right(s_doff21, 3) + 32);
            s_ul22 <= f_clamp10(signed(resize(unsigned(s_org(21)(11 downto 6)) & "0000", 14)) + shift_right(s_doff21, 4) + 64);
            s_vl22 <= f_clamp10(signed(resize(unsigned(s_org(21)(5 downto 0)) & "0000", 14)) + shift_right(s_doff21, 4) + 64);
            -- @23: LUT read lands; @24: index copy
            s_idx24 <= unsigned(s_lut_q);
            -- @25: palette ROM read lands; @26: colour copy
            s_py26 <= unsigned(s_pyc_q(15 downto 8));
            s_pu26 <= unsigned(s_pyc_q(7 downto 0));
            s_pv26 <= unsigned(s_pb_q(7 downto 0));
            -- @27: band ROM (palette luma) lands; @28: fabric copy
            s_py27 <= s_py26; s_pu27 <= s_pu26; s_pv27 <= s_pv26;
            s_py28 <= s_py27; s_pu28 <= s_pu27; s_pv28 <= s_pv27;
            s_pr28 <= unsigned(s_pq27);
            -- @29: luma choice (cel bands / banded palette / palette)
            if s_lumacel = '1' then
                s_ys29 <= f_legal(s_yc(28));
            elsif s_order = '1' and s_lev /= 0 then
                s_ys29 <= s_pr28 & "00";
            else
                s_ys29 <= s_py28 & "00";
            end if;
            s_pu29 <= s_pu28; s_pv29 <= s_pv28;
            -- @30: compose: black outside the source and on the first row
            -- (it shows the line before the frame); ink / original / fill
            v_ink := s_ed(29);
            if s_avid_sr(28) = '0' or s_row0 = '1' then
                s_y30 <= to_unsigned(64, 10);
                s_u30 <= to_unsigned(512, 10);
                s_v30 <= to_unsigned(512, 10);
            elsif v_ink = '1' and s_keep = '1' then
                s_y30 <= f_legal(unsigned(s_org(29)(19 downto 12)) & "00");
                s_u30 <= unsigned(s_org(29)(11 downto 6)) & "0000";
                s_v30 <= unsigned(s_org(29)(5 downto 0)) & "0000";
            elsif v_ink = '1' and s_inkt = '1' then
                s_y30 <= C_DARK(to_integer(s_zone)) & "00";
                s_u30 <= s_pu29 & "00";
                s_v30 <= s_pv29 & "00";
            elsif v_ink = '1' then
                s_y30 <= to_unsigned(64, 10);
                s_u30 <= to_unsigned(512, 10);
                s_v30 <= to_unsigned(512, 10);
            else
                s_y30 <= s_ys29;
                s_u30 <= s_pu29 & "00";
                s_v30 <= s_pv29 & "00";
            end if;
            -- @31..@32: horizontal [1 2 1]/4 (g1 the centre)
            s_g1y <= s_y30;  s_g2y <= s_g1y;
            s_g1u <= s_u30;  s_g2u <= s_g1u;
            s_g1v <= s_v30;  s_g2v <= s_g1v;
            v_sy := resize(s_g2y, 12) + shift_left(resize(s_g1y, 12), 1) + resize(s_y30, 12);
            v_su := resize(s_g2u, 12) + shift_left(resize(s_g1u, 12), 1) + resize(s_u30, 12);
            v_sv := resize(s_g2v, 12) + shift_left(resize(s_g1v, 12), 1) + resize(s_v30, 12);
            s_y32 <= v_sy(11 downto 2);
            s_u32 <= v_su(11 downto 2);
            s_v32 <= v_sv(11 downto 2);
            -- @33: luma toward black, 64 + 13/16 (y - 64) (white ~775);
            -- neutral outside the generated avid
            v_d  := s_y32 - 64;
            v_yo := s_y32 - shift_right(v_d, 3) - shift_right(v_d, 4);
            if s_gav_sr(31) = '1' then
                s_y33 <= v_yo;
                s_u33 <= s_u32;
                s_v33 <= s_v32;
            else
                s_y33 <= to_unsigned(64, 10);
                s_u33 <= to_unsigned(512, 10);
                s_v33 <= to_unsigned(512, 10);
            end if;
            -- chains
            for i in 15 to 29 loop
                s_org(i) <= s_org(i - 1);
                s_ed(i)  <= s_ed(i - 1);
            end loop;
            s_yc(21) <= s_ycel20;
            for i in 22 to 28 loop
                s_yc(i) <= s_yc(i - 1);
            end loop;
            -- sync chain (source syncs; source avid for the content; generated
            -- avid for the output)
            s_hsync_sr(0) <= data_in.hsync_n;
            s_vsync_sr(0) <= data_in.vsync_n;
            s_field_sr(0) <= data_in.field_n;
            s_avid_sr(0)  <= data_in.avid;
            s_gav_sr(0)   <= g_avid;
            for i in 1 to C_LAT - 1 loop
                s_hsync_sr(i) <= s_hsync_sr(i - 1);
                s_vsync_sr(i) <= s_vsync_sr(i - 1);
                s_field_sr(i) <= s_field_sr(i - 1);
                s_avid_sr(i)  <= s_avid_sr(i - 1);
                s_gav_sr(i)   <= s_gav_sr(i - 1);
            end loop;
        end if;
    end process p_pix;

    s_io_align_in.y       <= std_logic_vector(s_y33);
    s_io_align_in.u       <= std_logic_vector(s_u33);
    s_io_align_in.v       <= std_logic_vector(s_v33);
    s_io_align_in.hsync_n <= s_hsync_sr(C_LAT - 1);
    s_io_align_in.vsync_n <= s_vsync_sr(C_LAT - 1);
    s_io_align_in.field_n <= s_field_sr(C_LAT - 1);
    s_io_align_in.avid    <= s_gav_sr(C_LAT - 1);

    -- IO-align pad: video and syncs delayed together, so only the total
    -- latency changes (33 -> 36).
    p_io_align_pad : process(clk)
    begin
        if rising_edge(clk) then
            s_io_align_pad(0) <= s_io_align_in;
            for i in 1 to 2 loop
                s_io_align_pad(i) <= s_io_align_pad(i - 1);
            end loop;
        end if;
    end process p_io_align_pad;

    data_out <= s_io_align_pad(2);

end architecture cartridge;

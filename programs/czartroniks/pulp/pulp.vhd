begin

    ------------------------------------------------------------------------
    -- shared multiplier: operands and product both registered; a value
    -- written to s_ma/s_mb in step k is readable from s_mp in step k+2
    ------------------------------------------------------------------------
    p_mult : process(clk)
    begin
        if rising_edge(clk) then
            s_mp <= s_ma * s_mb;
        end if;
    end process p_mult;

    ------------------------------------------------------------------------
    -- vblank sequencer
    ------------------------------------------------------------------------
    p_seq : process(clk)
        variable v_g    : unsigned(7 downto 0);
        variable v_lbit : integer range 0 to 3;
        variable v_base : unsigned(3 downto 0);
        variable v_ik   : integer range 0 to 15;
        variable v_pr   : unsigned(11 downto 0);
        variable v_cx, v_hf : unsigned(10 downto 0);
        variable v_jit, v_by : unsigned(10 downto 0);
        variable v_bx   : unsigned(10 downto 0);
        variable v_k    : unsigned(1 downto 0);
        variable v_i    : integer range 0 to 2;
        variable v_w2, v_w38, v_w58, v_off : unsigned(10 downto 0);
        variable v_h2, v_h3, v_h23, v_yof : unsigned(10 downto 0);
        variable v_t7   : unsigned(6 downto 0);
        variable v_trr, v_trg, v_trb : unsigned(7 downto 0);
        variable v_f11  : unsigned(10 downto 0);
    begin
        if rising_edge(clk) then
            -- Resolution scaling (v1.0.3): the screen ladder is cells per
            -- 1080p pixel; 720p (x1.5) and SD (720 px wide, x2) scale the
            -- base frequency so a K1 setting is the same fraction of the
            -- screen height in every mode.  Decoded every clock from the
            -- timing ID (static while a mode runs).
            case to_integer(unsigned(registers_in(8)(3 downto 0))) is
                when 5 | 6 | 14     => s_fsc <= "01";
                when 0 | 4 | 8 | 12 => s_fsc <= "10";
                when others         => s_fsc <= "00";
            end case;

            -- hysteresis helper, free-running on the knob the sequencer
            -- put in s_hk (top 7 bits): the 16-zone index of k-8 and of
            -- k+8.  A held zone moves up only once k is 8 counts into the
            -- next zone, down only once it is 8 counts into the one below.
            v_t7 := s_hk - 1;
            if s_hk = 0 then
                s_ha <= (others => '0');
            else
                s_ha <= v_t7(6 downto 3);
            end if;
            v_t7 := s_hk + 1;
            if s_hk = 127 then
                s_hb <= (others => '1');
            else
                s_hb <= v_t7(6 downto 3);
            end if;

            if data_in.avid = '1' then
                s_vsa <= '1';
            end if;
            -- Per-frame start: the FIRST vsync edge after active video.
            -- Analog vsync serrates; restarting on every edge ran the
            -- bubble timer 2-5x faster on analog sources than on HDMI.
            if data_in.vsync_n = '0' and s_prev_vsync_n = '1'
               and s_vsa = '1' then
                s_vsa <= '0';
                s_k1 <= unsigned(registers_in(0));
                s_k2 <= unsigned(registers_in(1));
                s_k3 <= unsigned(registers_in(2));
                s_k4 <= unsigned(registers_in(3));
                s_k5 <= unsigned(registers_in(4));
                s_k6 <= unsigned(registers_in(5));
                s_p12 <= unsigned(registers_in(7));
                s_bw      <= not registers_in(6)(0);   -- switch 7
                s_poster  <= registers_in(6)(1);       -- switch 8
                s_panels  <= registers_in(6)(2);       -- switch 9
                s_bubbles <= registers_in(6)(3);       -- switch 10
                s_spot    <= registers_in(6)(4);       -- switch 11

                s_frame <= s_frame + 1;
                s_lfsr  <= f_lfsr(s_lfsr);

                s_ph <= to_unsigned(1, 3);
                s_st <= (others => '0');
            elsif s_ph /= 0 and data_in.avid = '0' then
                case to_integer(s_ph) is

                    ----------------------------------------------------
                    -- PH1: scalar derives
                    ----------------------------------------------------
                    when 1 =>
                        case to_integer(s_st) is
                            when 0 =>
                                -- base screen frequency + wet amount
                                -- (ladder runs coarse -> fine, so the
                                -- held K1 zone is inverted: knob up =
                                -- bigger cells, matching the px label)
                                v_f11 := C_FRQ(to_integer(not s_z1));
                                case s_fsc is
                                    when "01"   => s_f <= v_f11 + shift_right(v_f11, 1);
                                    when "10"   => s_f <= shift_left(v_f11, 1);
                                    when others => s_f <= v_f11;
                                end case;
                                s_wet10 <= f_sat10(resize(s_p12 & "00", 13)
                                           + resize(s_p12 & '0', 13));
                                s_ma <= to_unsigned(2929, 13);
                                s_mb <= resize(s_p12, 13);
                            when 2 =>
                                -- press low zone: sweep toward 2.5px cells
                                if s_mp(21 downto 10) > 1023 then
                                    v_pr := to_unsigned(1023, 12);
                                else
                                    v_pr := resize(s_mp(21 downto 10), 12);
                                end if;
                                s_ma <= resize(to_unsigned(1638, 11)
                                               - s_f, 13);
                                s_mb <= resize(to_unsigned(1023, 12)
                                               - v_pr, 13);
                            when 4 =>
                                if s_p12 < 358 then
                                    s_f <= s_f + resize(s_mp(21 downto 10), 11);
                                end if;
                                if s_p12 >= 716 then
                                    s_ma <= resize(s_p12 - 716, 13);
                                else
                                    s_ma <= (others => '0');
                                end if;
                                s_mb <= to_unsigned(427, 13);
                            when 6 =>
                                -- press high zone: coarsen toward 4x cells
                                if s_mp(16 downto 7) > 1023 then
                                    v_pr := to_unsigned(1023, 12);
                                else
                                    v_pr := resize(s_mp(16 downto 7), 12);
                                end if;
                                s_ma <= resize(s_f - resize(
                                    s_f(10 downto 2), 11), 13);
                                s_mb <= resize(v_pr, 13);
                            when 8 =>
                                if s_p12 >= 716 then
                                    s_f <= s_f - resize(s_mp(21 downto 10), 11);
                                end if;
                                -- ink boost above 60% press
                                if s_p12 >= 614 then
                                    s_ma <= resize(s_p12 - 614, 13);
                                else
                                    s_ma <= (others => '0');
                                end if;
                                s_mb <= to_unsigned(307, 13);
                            when 10 =>
                                s_ie <= f_sat10(resize(s_k3, 11)
                                        + resize(s_mp(19 downto 10), 11));
                                -- register: LINEAR in K6 (it was
                                -- K6^2, which left the bottom third of
                                -- the knob, and the default, invisible)
                                s_ma <= resize(s_k6, 13);
                                s_mb <= to_unsigned(144, 13);
                            when 12 =>
                                s_mis9 <= resize(s_mp(17 downto 10), 9);
                            when 14 =>
                                if s_ie >= 512 then
                                    s_ma <= resize(s_ie - 512, 13);
                                    s_bsign <= '0';
                                else
                                    s_ma <= resize(to_unsigned(512, 10)
                                            - s_ie, 13);
                                    s_bsign <= '1';
                                end if;
                                s_mb <= to_unsigned(389, 13);
                            when 16 =>
                                if s_bsign = '1' then
                                    s_bias <= -signed(resize(
                                        s_mp(17 downto 10), 10));
                                else
                                    s_bias <= signed(resize(
                                        s_mp(17 downto 10), 10));
                                end if;
                                s_ma <= resize(s_ie, 13);
                                s_mb <= to_unsigned(115, 13);
                            when 18 =>
                                v_g := to_unsigned(20, 8)
                                       + resize(s_mp(17 downto 10), 8);
                                s_g8 <= v_g;
                                s_ma <= resize(v_g, 13);
                                if s_p12 >= 716 then
                                    s_mb <= resize(s_p12 - 716, 13);
                                else
                                    s_mb <= (others => '0');
                                end if;
                            when 20 =>
                                -- pop-art gain relax, then a 4-position
                                -- shift code (1/2, 1/4, 1/8, off)
                                v_g := s_g8 - resize(s_mp(16 downto 9), 8);
                                if v_g >= 96 then
                                    s_gc <= "00";
                                elsif v_g >= 48 then
                                    s_gc <= "01";
                                elsif v_g >= 24 then
                                    s_gc <= "10";
                                else
                                    s_gc <= "11";
                                end if;
                            when 21 =>
                                -- posterize: S8 = full comic flats at ANY
                                -- Press; off, the Press ramp tops out at
                                -- half, so the switch always flips the
                                -- look (it used to be dead above 70%)
                                if s_poster = '1' then
                                    s_pa <= to_unsigned(4, 3);
                                elsif s_p12 >= 524 then
                                    s_pa <= to_unsigned(2, 3);
                                else
                                    s_pa <= (others => '0');
                                end if;
                                s_ma <= resize(s_k5, 13);
                                s_mb <= to_unsigned(306, 13);
                            when 23 =>
                                s_th <= to_unsigned(428, 10)
                                        - resize(s_mp(18 downto 10), 10);
                                s_dil <= s_k5(9 downto 8);
                                if s_k5 > 40 then
                                    s_lineon <= '1';
                                else
                                    s_lineon <= '0';
                                end if;
                                -- paper: four preset stocks
                                case s_z4(3 downto 2) is
                                    when "00" =>
                                        s_pap_r <= to_unsigned(993, 10);
                                        s_pap_g <= to_unsigned(988, 10);
                                        s_pap_b <= to_unsigned(967, 10);
                                    when "01" =>
                                        s_pap_r <= to_unsigned(967, 10);
                                        s_pap_g <= to_unsigned(927, 10);
                                        s_pap_b <= to_unsigned(834, 10);
                                    when "10" =>
                                        s_pap_r <= to_unsigned(925, 10);
                                        s_pap_g <= to_unsigned(860, 10);
                                        s_pap_b <= to_unsigned(700, 10);
                                    when others =>
                                        s_pap_r <= to_unsigned(870, 10);
                                        s_pap_g <= to_unsigned(780, 10);
                                        s_pap_b <= to_unsigned(560, 10);
                                end case;
                                case s_z4(3 downto 2) is
                                    when "00"   => s_gsh <= "101";
                                    when "01"   => s_gsh <= "100";
                                    when "10"   => s_gsh <= "100";
                                    when others => s_gsh <= "011";
                                end case;
                            when 24 =>
                                -- dot shape + per-shape square scaling,
                                -- from the held 16-zone K2 index
                                case to_integer(s_z2) is
                                    when 0 to 2 =>
                                        s_shp <= "000";     -- line
                                        s_sac <= "00";
                                        s_sbc <= "11";
                                    when 3 to 5 =>
                                        s_shp <= "001";     -- diamond
                                        s_sac <= "00";
                                        s_sbc <= "11";
                                    when 6 to 9 =>
                                        s_shp <= "010";     -- round
                                        s_sac <= "00";
                                        s_sbc <= "00";
                                    when 10 to 12 =>
                                        s_shp <= "011";     -- elliptical
                                        s_sac <= "01";
                                        s_sbc <= "00";
                                    when others =>
                                        s_shp <= "100";     -- square
                                        s_sac <= "00";
                                        s_sbc <= "11";
                                end case;
                                s_spm <= s_spot and not s_bw;
                                -- ragged-edge noise: coarse screens step
                                -- down (amplitude must shrink as cells grow
                                -- or it reads as spray-paint fuzz)
                                if s_f < 100 then
                                    s_nsel <= "00";
                                else
                                    s_nsel <= "01";
                                end if;
                            when 25 =>
                                s_ph <= to_unsigned(2, 3);
                                s_st <= (others => '0');
                            when others =>
                                null;
                        end case;
                        if s_st /= 25 then
                            s_st <= s_st + 1;
                        end if;

                    ----------------------------------------------------
                    -- PH2: DDA increments + plate phase offsets
                    ----------------------------------------------------
                    when 2 =>
                        case to_integer(s_st) is
                            when 0 =>
                                s_ma <= resize(s_f, 13);
                                s_mb <= to_unsigned(989, 13);  -- cos15
                            when 1 =>
                                s_ma <= resize(s_f, 13);
                                s_mb <= to_unsigned(265, 13);  -- sin15
                            when 2 =>
                                s_Ac <= resize(s_mp(21 downto 10), 12);
                            when 3 =>
                                s_Bc <= resize(s_mp(21 downto 10), 12);
                                s_ma <= resize(s_mis9, 13);
                                s_mb <= resize(s_Ac, 13);
                            when 4 =>
                                s_ma <= resize(s_mis9, 13);
                                s_mb <= resize(s_Bc, 13);
                            when 5 =>
                                s_ouc <= resize(s_mp(15 downto 4), 12);
                            when 6 =>
                                s_ovc <= (not resize(s_mp(15 downto 4), 12))
                                         + 1;
                                s_ma <= resize(s_f, 13);
                                s_mb <= to_unsigned(724, 13);  -- cos45
                            when 8 =>
                                s_Ak <= resize(s_mp(21 downto 10), 12);
                                s_ma <= resize(s_mis9, 13);
                                s_mb <= resize(s_f, 13);
                            when 10 =>
                                s_ouy <= resize(s_mp(16 downto 5), 12);
                            when 11 =>
                                -- M plate line-register corrections:
                                -- Lc gets du_M + dv_C, Ls gets dv_M + du_C
                                -- with du_M = -du_C, dv_M = -dv_C
                                s_lco <= s_ovc - s_ouc;
                                s_lso <= s_ouc - s_ovc;
                            when 12 =>
                                s_ph <= to_unsigned(3, 3);
                                s_cc <= to_unsigned(1, 4);
                                s_sc <= (others => '0');
                                -- seed the LUT DP with bare paper (RGB)
                                s_lwa <= (others => '0');
                                s_lwd <= std_logic_vector(s_pap_r)
                                         & std_logic_vector(s_pap_g)
                                         & std_logic_vector(s_pap_b);
                                s_lwen <= '1';
                            when others =>
                                null;
                        end case;
                        if s_st /= 12 then
                            s_st <= s_st + 1;
                        end if;

                    ----------------------------------------------------
                    -- PH3: ink LUT RGB build (DP over combinations,
                    -- one EBR read + one write per combination)
                    ----------------------------------------------------
                    when 3 =>
                        s_lwen <= '0';
                        if s_cc(0) = '1' then
                            v_lbit := 0;
                        elsif s_cc(1) = '1' then
                            v_lbit := 1;
                        elsif s_cc(2) = '1' then
                            v_lbit := 2;
                        else
                            v_lbit := 3;
                        end if;
                        v_base := s_cc;
                        v_base(v_lbit) := '0';
                        -- S11 SPOT: a two-colour press.  C and Y print
                        -- as bare paper, M becomes a warm spot red, K
                        -- stays black -- or turns red too in B&W, for a
                        -- one-ink red print.  All of it lives in the LUT
                        -- build; the pixel path only swaps M's tone.
                        if s_spot = '1' and (v_lbit = 0 or v_lbit = 2) then
                            v_trr := to_unsigned(255, 8);
                            v_trg := to_unsigned(255, 8);
                            v_trb := to_unsigned(255, 8);
                        elsif s_spot = '1' and (v_lbit = 1 or s_bw = '1') then
                            v_trr := to_unsigned(245, 8);
                            v_trg := to_unsigned(52, 8);
                            v_trb := to_unsigned(40, 8);
                        else
                            v_trr := C_TR_R(v_lbit);
                            v_trg := C_TR_G(v_lbit);
                            v_trb := C_TR_B(v_lbit);
                        end if;
                        case to_integer(s_sc) is
                            when 0 =>
                                s_lra <= v_base;
                            when 2 =>
                                s_ma <= resize(
                                    unsigned(lutq(29 downto 20)), 13);
                                s_mb <= resize(v_trr, 13);
                            when 3 =>
                                s_ma <= resize(
                                    unsigned(lutq(19 downto 10)), 13);
                                s_mb <= resize(v_trg, 13);
                            when 4 =>
                                s_wR <= resize(s_mp(17 downto 8), 10);
                                s_ma <= resize(
                                    unsigned(lutq(9 downto 0)), 13);
                                s_mb <= resize(v_trb, 13);
                            when 5 =>
                                s_wG <= resize(s_mp(17 downto 8), 10);
                            when 6 =>
                                s_lwa <= s_cc;
                                s_lwd <= std_logic_vector(s_wR)
                                         & std_logic_vector(s_wG)
                                         & std_logic_vector(
                                             resize(s_mp(17 downto 8), 10));
                                s_lwen <= '1';
                                if s_cc = 15 then
                                    s_ph <= to_unsigned(4, 3);
                                    s_cc <= (others => '0');
                                else
                                    s_cc <= s_cc + 1;
                                end if;
                                s_sc <= (others => '0');
                            when others =>
                                null;
                        end case;
                        if s_sc /= 6 then
                            s_sc <= s_sc + 1;
                        end if;

                    ----------------------------------------------------
                    -- PH4: LUT RGB -> YUV (BT.601), converted in place.
                    -- Video-range output: Y = 64 + 0.6875 Y' (bright paper
                    -- ~740, under the ~768 drawn-luma cap where the
                    -- hardware still shows the stock's tint; full CMYK
                    -- ~75, above black), chroma 512 +- 0.876 C' (the
                    -- 896-per-unit swing; |C| <= 448, so no clamps).
                    -- Stored U/V-SWAPPED (hardware order: the u slot
                    -- carries Cr) -- the input latch swaps to match.
                    ----------------------------------------------------
                    when 4 =>
                        s_lwen <= '0';
                        case to_integer(s_sc) is
                            when 0 =>
                                s_lra <= s_cc;
                            when 2 =>
                                s_cR <= unsigned(lutq(29 downto 20));
                                s_cB <= unsigned(lutq(9 downto 0));
                                s_ma <= resize(
                                    unsigned(lutq(29 downto 20)), 13);
                                s_mb <= to_unsigned(77, 13);
                            when 3 =>
                                s_ma <= resize(
                                    unsigned(lutq(19 downto 10)), 13);
                                s_mb <= to_unsigned(150, 13);
                            when 4 =>
                                s_acc21 <= resize(s_mp, 21);
                                s_ma <= resize(s_cB, 13);
                                s_mb <= to_unsigned(29, 13);
                            when 5 =>
                                s_acc21 <= s_acc21 + resize(s_mp, 21);
                            when 6 =>
                                s_yv <= resize(
                                    shift_right(s_acc21 + resize(s_mp, 21), 8),
                                    10);
                            when 7 =>
                                if s_cB >= s_yv then
                                    s_ma <= resize(s_cB - s_yv, 13);
                                    s_dsign <= '0';
                                else
                                    s_ma <= resize(s_yv - s_cB, 13);
                                    s_dsign <= '1';
                                end if;
                                s_mb <= to_unsigned(126, 13);
                            when 8 =>
                                if s_cR >= s_yv then
                                    s_ma <= resize(s_cR - s_yv, 13);
                                    s_bsign <= '0';
                                else
                                    s_ma <= resize(s_yv - s_cR, 13);
                                    s_bsign <= '1';
                                end if;
                                s_mb <= to_unsigned(160, 13);
                            when 9 =>
                                -- Cb
                                if s_dsign = '1' then
                                    s_wG <= to_unsigned(512, 10)
                                            - s_mp(17 downto 8);
                                else
                                    s_wG <= to_unsigned(512, 10)
                                            + s_mp(17 downto 8);
                                end if;
                                s_ma <= resize(s_yv, 13);
                                s_mb <= to_unsigned(176, 13);
                            when 10 =>
                                -- Cr
                                if s_bsign = '1' then
                                    s_wR <= to_unsigned(512, 10)
                                            - s_mp(17 downto 8);
                                else
                                    s_wR <= to_unsigned(512, 10)
                                            + s_mp(17 downto 8);
                                end if;
                            when 11 =>
                                s_lwa <= s_cc;
                                s_lwd <= std_logic_vector(
                                             to_unsigned(64, 10)
                                             + s_mp(17 downto 8))
                                         & std_logic_vector(s_wR)
                                         & std_logic_vector(s_wG);
                                s_lwen <= '1';
                                if s_cc = 15 then
                                    s_ph <= to_unsigned(5, 3);
                                    s_st <= (others => '0');
                                else
                                    s_cc <= s_cc + 1;
                                end if;
                                s_sc <= (others => '0');
                            when others =>
                                null;
                        end case;
                        if s_sc /= 11 then
                            s_sc <= s_sc + 1;
                        end if;

                    ----------------------------------------------------
                    -- PH5: layout + bubble FSM
                    ----------------------------------------------------
                    when 5 =>
                        case to_integer(s_st) is
                            when 0 =>
                                s_lwen <= '0';
                                -- linework/border/text ink colour
                                if s_bw = '1' then
                                    s_lra <= "1000";
                                else
                                    s_lra <= "1111";
                                end if;
                                -- ONE gutter + border weight for the whole
                                -- page, derived from the field height and
                                -- doubled horizontally when the source is
                                -- interlaced (a field line covers ~2x the
                                -- display height that a pixel covers in
                                -- width), so every gap looks square.
                                --
                                -- Built ONE add per step: this whole chain
                                -- lands in vblank, but STA times it every
                                -- clock, and as a single cone it WAS the
                                -- routed critical path (s_h -> s_omxb,
                                -- 68 MHz).  House rule, the hard way.
                                --
                                -- gutter 3 + h/128 lines (SD 4-5, 1080i 7,
                                -- 720p 8, 1080p 11); border weight by
                                -- height band (SD 2, 1080i/720p 3, 1080p 5)
                                s_guy <= to_unsigned(3, 5)
                                         + resize(s_h(10 downto 7), 5);
                                case s_h(10 downto 9) is
                                    when "00"   => s_bwy <= to_unsigned(2, 4);
                                    when "01"   => s_bwy <= to_unsigned(3, 4);
                                    when "10"   => s_bwy <= to_unsigned(5, 4);
                                    when others => s_bwy <= to_unsigned(6, 4);
                                end case;
                                if s_w > (s_h & '0') then
                                    s_wide <= '1';
                                else
                                    s_wide <= '0';
                                end if;
                            when 1 =>
                                if s_wide = '1' then        -- wide pixels
                                    s_gux <= resize(s_guy & '0', 6);
                                    s_bwx <= resize(s_bwy & '0', 5);
                                else                        -- square pixels
                                    s_gux <= resize(s_guy, 6);
                                    s_bwx <= resize(s_bwy, 5);
                                end if;
                            when 2 =>
                                -- A split lays paper on BOTH sides of its
                                -- rule: |x-P| < g spans 2g-1 px.  The page
                                -- margin is set to exactly that same 2g-1,
                                -- so the space around the page is identical
                                -- to the space between two panels.
                                s_omx <= resize(s_gux & '0', 7) - 1;
                                s_omy <= resize(s_guy & '0', 6) - 1;
                            when 3 =>
                                s_omxb <= s_omx + resize(s_bwx, 7);
                                s_omyb <= s_omy + resize(s_bwy, 6);
                                s_wmg <= s_w - resize(s_omx, 11);
                                s_hmg <= s_h - resize(s_omy, 11);
                            when 4 =>
                                s_wmgb <= s_wmg - resize(s_bwx, 11);
                                s_hmgb <= s_hmg - resize(s_bwy, 11);
                            when 5 =>
                                s_ink_y <= unsigned(lutq(29 downto 20));
                                s_ink_u <= unsigned(lutq(19 downto 10));
                                s_ink_v <= unsigned(lutq(9 downto 0));
                                -- fresh layout every time PANELS flips on
                                if s_panels = '1' and s_panels_d = '0' then
                                    s_tpl <= s_lfsr(2 downto 0);
                                    s_lfsr <= f_lfsr(s_lfsr);
                                end if;
                            when 6 =>
                                -- comic page template table (fractions of
                                -- the captured frame size, shift-adds)
                                v_w2  := '0' & s_w(10 downto 1);
                                v_w38 := resize(s_w(10 downto 2), 11)
                                         + resize(s_w(10 downto 3), 11);
                                v_w58 := v_w2 + resize(s_w(10 downto 3), 11);
                                v_h2  := '0' & s_h(10 downto 1);
                                v_h3  := resize(s_h(10 downto 2), 11)
                                         + resize(s_h(10 downto 4), 11)
                                         + resize(s_h(10 downto 6), 11);
                                v_h23 := s_h - v_h3;
                                v_off := to_unsigned(2047, 11);
                                v_yof := to_unsigned(2047, 11);
                                -- the bubble slots' vertical bands
                                s_b3a <= v_h3;
                                s_b3b <= v_h23;
                                -- sprite scale: square on screen in every
                                -- mode, and always shorter than a band
                                s_bxs <= s_w(10) and s_w(9);    -- >= 1536
                                if s_h >= 768 then
                                    s_bys <= "10";              -- 1080p
                                elsif s_h >= 384 then
                                    s_bys <= "01";              -- 1080i, 720p
                                else
                                    s_bys <= "00";              -- SD fields
                                end if;
                                s_gate_en <= '0';
                                -- Each row carries ONE column split (A =
                                -- top row, B = the rows below), which is
                                -- all real comic grammar needs and pays
                                -- for the page border ring.
                                case s_tpl is
                                    when "000" =>   -- six panels: 3 tiers of 2
                                        s_ry1 <= v_h3;  s_ry2 <= v_h23;
                                        s_rxaA <= v_w2; s_rxaB <= v_w2;
                                    when "001" =>   -- tall left + 3 right
                                        s_ry1 <= v_h3;  s_ry2 <= v_h23;
                                        s_gate_en <= '1';
                                        s_rxaA <= v_w38; s_rxaB <= v_w38;
                                    when "010" =>   -- 2x2 grid
                                        s_ry1 <= v_h2;  s_ry2 <= v_yof;
                                        s_rxaA <= v_w2; s_rxaB <= v_w2;
                                    when "011" =>   -- 3 newspaper strips
                                        s_ry1 <= v_h3;  s_ry2 <= v_h23;
                                        s_rxaA <= v_off; s_rxaB <= v_off;
                                    when "100" =>   -- splash top + 2 below
                                        s_ry1 <= v_h2;  s_ry2 <= v_yof;
                                        s_rxaA <= v_off; s_rxaB <= v_w2;
                                    when "101" =>   -- 2 up top + splash
                                        s_ry1 <= v_h2;  s_ry2 <= v_yof;
                                        s_rxaA <= v_w2;  s_rxaB <= v_off;
                                    when "110" =>   -- staggered 2x2
                                        s_ry1 <= v_h2;  s_ry2 <= v_yof;
                                        s_rxaA <= v_w38; s_rxaB <= v_w58;
                                    when others =>  -- strip top + 2x2 page
                                        s_ry1 <= v_h3;  s_ry2 <= v_h23;
                                        s_rxaA <= v_off; s_rxaB <= v_w2;
                                end case;
                            when 7 =>
                                -- Re-roll ONE slot per tick, round-robin,
                                -- so bubbles pop in and out continuously
                                -- with 2-3 up at any time.  The whole slot
                                -- is assembled here and written to the RAM
                                -- as one word.  (No need to clear slots
                                -- when BUBBLES is off -- the switch gates
                                -- the sprite at E2.)
                                if s_btimer /= 0 then
                                    s_btimer <= s_btimer - 1;
                                    bwen <= '0';
                                else
                                    s_btimer <= to_unsigned(35, 9)
                                        + resize(s_lfsr(5 downto 0), 9);
                                    if s_rr = 2 then
                                        s_rr <= (others => '0');
                                    else
                                        s_rr <= s_rr + 1;
                                    end if;
                                    v_i := to_integer(s_rr);
                                    s_bkind <= s_bkind + 1;
                                    if s_bkind = 3 then
                                        v_k := "10";        -- burst
                                    elsif s_bkind(0) = '1' then
                                        v_k := "01";        -- thought
                                    else
                                        v_k := "00";        -- speech
                                    end if;
                                    if s_bxs = '1' then
                                        v_hf := to_unsigned(128, 11);
                                    else
                                        v_hf := to_unsigned(64, 11);
                                    end if;
                                    -- x: anywhere across the page, centres
                                    -- 1/8 .. 7/8 of the width (the old
                                    -- w/8 + w/4 + w/8 + w/16 ladder topped
                                    -- out at 9/16 -- the right ~40% of the
                                    -- page never got a bubble)
                                    v_cx := resize(s_w(10 downto 3), 11);
                                    if s_lfsr(8) = '1' then
                                        v_cx := v_cx
                                            + resize(s_w(10 downto 1), 11);
                                    end if;
                                    if s_lfsr(9) = '1' then
                                        v_cx := v_cx
                                            + resize(s_w(10 downto 3), 11);
                                    end if;
                                    if s_lfsr(10) = '1' then
                                        v_cx := v_cx
                                            + resize(s_w(10 downto 3), 11);
                                    end if;
                                    -- store only the anchor the mirror
                                    -- direction will actually use
                                    if s_lfsr(7) = '1' then
                                        v_bx := v_cx + v_hf;
                                    else
                                        v_bx := v_cx - v_hf;
                                    end if;
                                    -- y: jitter inside this slot's band,
                                    -- so the sprite never crosses it
                                    case s_bys is
                                        when "10" => v_jit := resize(
                                            s_lfsr(3 downto 0) & "00", 11);
                                        when "01" => v_jit := resize(
                                            s_lfsr(3 downto 0) & '0', 11);
                                        when others => v_jit := resize(
                                            s_lfsr(3 downto 0), 11);
                                    end case;
                                    case v_i is
                                        when 0      => v_by := v_jit;
                                        when 1      => v_by := s_b3a + v_jit;
                                        when others => v_by := s_b3b + v_jit;
                                    end case;
                                    bwa <= to_unsigned(v_i, 8);
                                    bwd <= std_logic_vector(v_bx)
                                           & std_logic_vector(v_by)
                                           & std_logic_vector(v_k)
                                           & s_lfsr(7)
                                           -- ~75% occupied -> 2-3 on screen
                                           & (s_lfsr(11) or s_lfsr(12));
                                    bwen <= '1';
                                    s_lfsr <= f_lfsr(s_lfsr);
                                end if;
                            when 8 =>
                                s_panels_d <= s_panels;
                                -- one write per re-roll: a write enable
                                -- left high rewrote the slot all frame
                                -- long, colliding with the pixel reads
                                bwen <= '0';
                                s_hk <= s_k1(9 downto 3);
                            -- stepped-control hysteresis (s_ha/s_hb land
                            -- two steps after s_hk is loaded); the held
                            -- zones are used from the next frame on
                            when 10 =>
                                if s_ha > s_z1 then
                                    s_z1 <= s_ha;
                                elsif s_hb < s_z1 then
                                    s_z1 <= s_hb;
                                end if;
                                s_hk <= s_k2(9 downto 3);
                            when 12 =>
                                if s_ha > s_z2 then
                                    s_z2 <= s_ha;
                                elsif s_hb < s_z2 then
                                    s_z2 <= s_hb;
                                end if;
                                s_hk <= s_k4(9 downto 3);
                            when 14 =>
                                if s_ha > s_z4 then
                                    s_z4 <= s_ha;
                                elsif s_hb < s_z4 then
                                    s_z4 <= s_hb;
                                end if;
                                s_ph <= (others => '0');
                            when others =>
                                null;
                        end case;
                        if s_st /= 14 then
                            s_st <= s_st + 1;
                        end if;

                    when others =>
                        s_ph <= (others => '0');
                end case;
            end if;
        end if;
    end process p_seq;

    ------------------------------------------------------------------------
    -- main pixel pipeline E1..E13
    ------------------------------------------------------------------------
    p_pix : process(clk)
        variable v_um, v_vm : unsigned(11 downto 0);
        variable v_vk : unsigned(11 downto 0);
        variable v_eu, v_ev : unsigned(9 downto 0);
        variable v_bx, v_by : unsigned(7 downto 0);
        variable v_sum  : unsigned(11 downto 0);
        variable v_mac  : signed(12 downto 0);
        variable v_nz   : signed(7 downto 0);
        variable v_q    : unsigned(9 downto 0);
        variable v_t    : unsigned(9 downto 0);
        variable v_dq   : signed(11 downto 0);
        variable v_ink  : std_logic_vector(0 to 3);
        variable v_cmb  : unsigned(3 downto 0);
        variable v_y12  : signed(11 downto 0);
        variable v_gut, v_bord : std_logic;
        variable v_s12  : signed(11 downto 0);
        variable v_s13  : signed(12 downto 0);
        variable v_sp   : std_logic_vector(1 downto 0);
        variable v_ra, v_rb : unsigned(8 downto 0);
        variable v_yd1, v_yd2 : unsigned(10 downto 0);
        variable v_inx, v_iny : boolean;
        variable v_sy, v_su, v_sv : unsigned(11 downto 0);
        variable v_row, v_col : unsigned(5 downto 0);
    begin
        if rising_edge(clk) then
            s_prev_hsync_n <= data_in.hsync_n;
            s_prev_vsync_n <= data_in.vsync_n;

            av(1) <= data_in.avid;
            for i in 2 to 15 loop
                av(i) <= av(i - 1);
            end loop;

            --------------------------------------------------------------
            -- E1: capture, position, DDA advance, panel zones, bubble dx
            --------------------------------------------------------------
            y1  <= unsigned(data_in.y);
            -- the hardware carries chroma U<->V swapped vs BT.601: swap
            -- once here so the press works in BT.601 (u1c = Cb); the ink
            -- LUT is stored back in hardware order (see PH4)
            u1c <= unsigned(data_in.v);
            v1c <= unsigned(data_in.u);
            px_pipe(1) <= s_x_count;
            for i in 2 to 6 loop
                px_pipe(i) <= px_pipe(i - 1);
            end loop;
            if data_in.avid = '1' then
                s_x_count <= s_x_count + 1;
                s_seen    <= '1';
                acc_cu <= acc_cu + s_Ac;
                acc_cv <= acc_cv - s_Bc;
                acc_ku <= acc_ku + s_Ak;
                acc_yu <= acc_yu + resize(s_f, 12);
            end if;
            cu1 <= acc_cu;
            cv1 <= acc_cv;
            ku1 <= acc_ku;
            yu1 <= acc_yu;

            -- panel column-split distances (centres muxed per line)
            if s_x_count > rxa_ln then
                xda1 <= resize(s_x_count - rxa_ln, 11);
            else
                xda1 <= resize(rxa_ln - s_x_count, 11);
            end if;
            -- gate: rows split only right of the tall panel's edge, which
            -- IS the row's column split -- shares the comparator above
            if s_gate_en = '0' or s_x_count > rxa_ln then
                xg1 <= '1';
            else
                xg1 <= '0';
            end if;

            -- bubble sprite coords, pre-biased so E2 is slice/zero-test
            -- only; the tail mirror is folded into the subtract choice
            if s_btdir = '1' then
                dxb1 <= signed(resize(unsigned(s_bx), 12))
                        - signed(resize(s_x_count, 12));
            else
                dxb1 <= signed(resize(s_x_count, 12))
                        - signed(resize(unsigned(s_bx), 12));
            end if;
            dyl1 <= signed(resize(s_aline, 12))
                    - signed(resize(unsigned(s_bcya), 12));

            --------------------------------------------------------------
            -- E2: plate cell distances (M and K's v derived from line
            -- registers), chroma centre, sobel sums, panel masks, sprite
            -- address, noise hash
            --------------------------------------------------------------
            du2(0) <= f_fold10(cu1);
            dv2(0) <= f_fold10(cv1);
            v_um := r_lc - cv1;
            v_vm := r_ls - cu1;
            du2(1) <= f_fold10(v_um);
            dv2(1) <= f_fold10(v_vm);
            du2(2) <= f_fold10(yu1);
            dv2(2) <= (others => '0');
            v_vk := r_lk - ku1;
            du2(3) <= f_fold10(ku1);
            dv2(3) <= f_fold10(v_vk);

            uc2 <= resize(signed(resize(u1c, 11)) - 512, 11);
            vc2 <= resize(signed(resize(v1c, 11)) - 512, 11);
            y2  <= y1;

            -- Roberts cross on a 2x2 window (cur row + previous row)
            cur_d1 <= y1(9 downto 2);
            q1_d1  <= unsigned(q1);
            if y1(9 downto 2) > q1_d1 then
                v_ra := resize(y1(9 downto 2) - q1_d1, 9);
            else
                v_ra := resize(q1_d1 - y1(9 downto 2), 9);
            end if;
            if cur_d1 > unsigned(q1) then
                v_rb := resize(cur_d1 - unsigned(q1), 9);
            else
                v_rb := resize(unsigned(q1) - cur_d1, 9);
            end if;
            mag2 <= v_ra + v_rb;

            -- panel gutter / border: per-line row bands + column splits
            v_gut := '0';
            v_bord := '0';
            if xg1 = '1' then
                if ygut_ln = '1' then
                    v_gut := '1';
                elsif ybord_ln = '1' then
                    v_bord := '1';
                end if;
            end if;
            if xda1 < resize(s_gux, 11) then
                v_gut := '1';
            elsif xda1 < resize(s_gux, 11) + resize(s_bwx, 11) then
                v_bord := '1';
            end if;
            -- Page edge: paper margin, then a border ring -- so panels
            -- on the page edge are outlined exactly like interior ones.
            -- |x - 0| = x and |x - W| = W - x, so the edges need no new
            -- distance math, just the pre-computed ring thresholds.  A
            -- row/column gutter crossing the ring still wins (v_gut is
            -- never cleared here), which correctly breaks the outline
            -- between panels rather than boxing the whole page.
            if px_pipe(1) < resize(s_omx, 11)
               or px_pipe(1) >= s_wmg
               or ymar_ln = '1' then
                v_gut := '1';
            elsif px_pipe(1) < resize(s_omxb, 11)
               or px_pipe(1) >= s_wmgb
               or ymbd_ln = '1' then
                v_bord := '1';
            end if;
            gut2  <= v_gut and s_panels;
            bord2 <= v_bord and (not v_gut) and s_panels;

            -- bubble sprite address: pre-biased coords make this a
            -- couple of slice selects and zero tests
            -- (x and y scales are independent per-frame selects, so the
            -- sprite stays square in every mode)
            if s_bxs = '1' then
                v_inx := dxb1(11 downto 8) = "0000";
                v_col := unsigned(dxb1(7 downto 2));
            else
                v_inx := dxb1(11 downto 7) = "00000";
                v_col := unsigned(dxb1(6 downto 1));
            end if;
            case s_bys is
                when "10" =>
                    v_iny := dyl1(11 downto 8) = "0000";
                    v_row := unsigned(dyl1(7 downto 2));
                when "01" =>
                    v_iny := dyl1(11 downto 7) = "00000";
                    v_row := unsigned(dyl1(6 downto 1));
                when others =>
                    v_iny := dyl1(11 downto 6) = "000000";
                    v_row := unsigned(dyl1(5 downto 0));
            end case;
            if v_inx and v_iny then
                bval2 <= s_bslot_on and s_bubbles;
            else
                bval2 <= '0';
            end if;
            saddr2 <= v_row & v_col;

            -- keyed to the true frame line y = 2*aline + field (a bit
            -- concat, free): paper grain/ragged edges are a property of
            -- the PAPER at (x,y), so both fields must agree on them
            ha_n2 <= f_hash_a(px_pipe(1)(7 downto 0),
                              s_aline(6 downto 0) & s_fld, x"9D2C");

            --------------------------------------------------------------
            -- E3: fold to nearer of centre/corner, shape input select,
            -- RGB partials, sobel gx/gy, dropout hash
            --------------------------------------------------------------
            for p in 0 to 3 loop
                if p = 2 then
                    -- Y plate: vertical line screen, 1-D fold
                    if du2(2) > 256 then
                        rg3(2) <= '1';
                        v_eu := "0" & (not du2(2)(8 downto 0));
                    else
                        rg3(2) <= '0';
                        v_eu := du2(2);
                    end if;
                    sqa3(2) <= unsigned(C_SQ(to_integer(v_eu(8 downto 1))));
                else
                    if resize(du2(p), 11) + resize(dv2(p), 11) > 512 then
                        rg3(p) <= '1';
                        v_eu := "0" & (not du2(p)(8 downto 0));
                        v_ev := "0" & (not dv2(p)(8 downto 0));
                    else
                        rg3(p) <= '0';
                        v_eu := du2(p);
                        v_ev := dv2(p);
                    end if;
                    case s_shp is
                        when "000" =>       -- line screen
                            v_bx := v_ev(9 downto 2);
                            v_by := (others => '0');
                        when "001" =>       -- diamond
                            v_bx := resize(shift_right(
                                resize(v_eu, 11) + resize(v_ev, 11), 2), 8);
                            v_by := (others => '0');
                        when "100" =>       -- square
                            if v_eu > v_ev then
                                v_bx := v_eu(9 downto 2);
                            else
                                v_bx := v_ev(9 downto 2);
                            end if;
                            v_by := (others => '0');
                        when others =>      -- round / elliptical
                            v_bx := v_eu(9 downto 2);
                            v_by := v_ev(9 downto 2);
                    end case;
                    sqa3(p) <= unsigned(C_SQ(to_integer(v_bx)));
                    sqb3(p) <= unsigned(C_SQ(to_integer(v_by)));
                end if;
            end loop;


            -- BT.601-ish RGB (shift-add): R=Y+1.375Vc, B=Y+1.75Uc,
            -- G=Y-0.34375Uc-0.6875Vc
            r3 <= resize(signed(resize(y2, 11)), 12) + resize(vc2, 12)
                  + resize(shift_right(vc2, 2), 12)
                  + resize(shift_right(vc2, 3), 12);
            b3 <= resize(signed(resize(y2, 11)), 12) + resize(uc2, 12)
                  + resize(shift_right(uc2, 1), 12)
                  + resize(shift_right(uc2, 2), 12);
            g3 <= resize(signed(resize(y2, 11)), 12)
                  - resize(shift_right(uc2, 2), 12)
                  - resize(shift_right(uc2, 4), 12)
                  - resize(shift_right(uc2, 5), 12)
                  - resize(shift_right(vc2, 1), 12)
                  - resize(shift_right(vc2, 3), 12)
                  - resize(shift_right(vc2, 4), 12);

            -- linework decision (Roberts x4 matches the Sobel scale)
            if s_lineon = '1' and s_rowok = '1'
               and (mag2 & "00") > resize(s_th, 11) then
                edge3 <= '1';
            else
                edge3 <= '0';
            end if;

            bval3 <= bval2;
            nz3 <= f_hash_b(ha_n2);
            y3t <= y2;
            y4t <= y3t;
            y5t <= y4t;

            --------------------------------------------------------------
            -- E4: the squares (ROM data re-registered), RGB clamp, sobel magnitude,
            -- sprite decode, grain hold
            --------------------------------------------------------------
            for p in 0 to 3 loop
                qa4(p) <= sqa3(p);
                qb4(p) <= sqb3(p);
            end loop;
            rg4 <= rg3;

            r4 <= f_cu10(r3);
            g4 <= f_cu10(g3);
            b4 <= f_cu10(b3);

            e3d1 <= edge3;
            e3d2 <= e3d1;
            e3d3 <= e3d2;
            ed4 <= edge3
                   or (e3d1 and (s_dil(1) or s_dil(0)))
                   or (e3d2 and s_dil(1))
                   or (e3d3 and s_dil(1) and s_dil(0));

            -- noise (per-frame amount) and bias folded once for all plates
            case s_nsel is
                when "00"   => v_nz := resize(shift_right(
                                   signed('0' & nz3(5 downto 0)) - 32, 1), 8);
                when "01"   => v_nz := resize(
                                   signed('0' & nz3(5 downto 0)) - 32, 8);
                when others => v_nz := resize(
                                   signed('0' & nz3(5 downto 0)) - 32, 8)
                                   + resize(
                                   signed('0' & nz3(5 downto 0)) - 32, 8);
            end case;
            bn4 <= resize(v_nz, 10) - s_bias;
            if px_pipe(3)(1 downto 0) = "00" then
                gsn4 <= resize(shift_right(
                    signed('0' & nz3) - 128, to_integer(s_gsh)), 6);
            end if;

            case s_bk_v is
                when "00"   => v_sp := spq_s;
                when "01"   => v_sp := spq_t;
                when others => v_sp := spq_b;
            end case;
            bfill4 <= bval3 when v_sp = "01" else '0';
            bink4  <= bval3 when (v_sp = "10" or v_sp = "11") else '0';

            --------------------------------------------------------------
            -- E5: spot threshold.  Centre region: T = scaled square sum
            -- (0..512); corner region: 1024 - sum.  Ink dots grow in
            -- highlights, 50% checkerboards, shadows open white dots.
            --------------------------------------------------------------
            for p in 0 to 3 loop
                if p = 2 then
                    v_sum := resize(qa4(2)(9 downto 0), 12);
                else
                    case s_sac is
                        when "00" =>
                            v_sum := resize(qa4(p)(9 downto 0), 12);
                        when "01" =>
                            v_sum := resize(qa4(p)(9 downto 1), 12);
                        when others =>
                            v_sum := (others => '0');
                    end case;
                    case s_sbc is
                        when "00" =>
                            v_sum := v_sum
                                     + resize(qb4(p)(9 downto 0), 12);
                        when "01" =>
                            v_sum := v_sum
                                     + resize(qb4(p)(9 downto 1), 12);
                        when others =>
                            null;
                    end case;
                end if;
                if rg4(p) = '1' then
                    v_mac := to_signed(1024, 13)
                             - signed(resize(v_sum, 13));
                else
                    v_mac := signed(resize(v_sum, 13));
                end if;
                v_mac := v_mac + resize(bn4, 13);
                T5(p) <= resize(v_mac, 12);
            end loop;

            c5  <= 1023 - r4;
            -- SPOT: the red plate prints min(M, Y) -- the warm tones --
            -- so blue sky stays off it (plain M put red dots in the sky)
            if s_spm = '1' and b4 > g4 then
                m5 <= 1023 - b4;
            else
                m5 <= 1023 - g4;
            end if;
            yy5 <= 1023 - b4;
            v_t := 1023 - r4;
            if 1023 - g4 < v_t then
                v_t := 1023 - g4;
            end if;
            if 1023 - b4 < v_t then
                v_t := 1023 - b4;
            end if;
            kmin5 <= v_t;


            --------------------------------------------------------------
            -- E6: GCR + B&W tone, h-dilate
            --------------------------------------------------------------
            v_t := kmin5 - resize(kmin5(9 downto 2), 10);
            if s_bw = '1' then
                k6 <= 1023 - y5t;
            else
                k6 <= v_t;
            end if;
            c6  <= c5 - v_t;
            m6  <= m5 - v_t;
            y6k <= yy5 - v_t;

            edv5 <= ed4 or (ebq(0) and (s_dil(1) or s_dil(0)));
            T_p(6) <= T5;

            --------------------------------------------------------------
            -- E7: posterize (off / half / full comic flats); the B&W
            -- 3-level quantizer only exists on the K plate
            --------------------------------------------------------------
            for p in 0 to 3 loop
                case p is
                    when 0      => v_t := c6;
                    when 1      => v_t := m6;
                    when 2      => v_t := y6k;
                    when others => v_t := k6;
                end case;
                if p = 3 and s_bw = '1' then
                    if v_t > 682 then
                        v_q := to_unsigned(1023, 10);
                    elsif v_t > 341 then
                        v_q := to_unsigned(512, 10);
                    else
                        v_q := to_unsigned(0, 10);
                    end if;
                else
                    case v_t(9 downto 8) is
                        when "00"   => v_q := to_unsigned(0, 10);
                        when "01"   => v_q := to_unsigned(341, 10);
                        when "10"   => v_q := to_unsigned(682, 10);
                        when others => v_q := to_unsigned(1023, 10);
                    end case;
                end if;
                if s_pa = 4 then
                    v_t := v_q;
                elsif s_pa = 2 then
                    v_t := resize(('0' & v_t(9 downto 1))
                           + ('0' & v_q(9 downto 1)), 10);
                end if;
                t8(p) <= v_t;
                if v_t < 512 then
                    mn8(p) <= v_t;
                else
                    mn8(p) <= 1023 - v_t;
                end if;
            end loop;
            T_p(7) <= T_p(6);

            --------------------------------------------------------------
            -- E8: dot gain (single shift term; cannot overflow)
            --------------------------------------------------------------
            for p in 0 to 3 loop
                case s_gc is
                    when "00" =>
                        tf9(p) <= t8(p) + resize(mn8(p)(9 downto 1), 10);
                    when "01" =>
                        tf9(p) <= t8(p) + resize(mn8(p)(9 downto 2), 10);
                    when "10" =>
                        tf9(p) <= t8(p) + resize(mn8(p)(9 downto 3), 10);
                    when others =>
                        tf9(p) <= t8(p);
                end case;
            end loop;
            T_p(8) <= T_p(7);

            --------------------------------------------------------------
            -- E9: ink decisions -> combination index
            --------------------------------------------------------------
            for p in 0 to 3 loop
                if signed(resize(tf9(p), 12)) > T_p(8)(p) then
                    v_ink(p) := '1';
                else
                    v_ink(p) := '0';
                end if;
            end loop;
            v_cmb := v_ink(3) & v_ink(2) & v_ink(1) & v_ink(0);
            if s_bw = '1' then
                v_cmb := v_ink(3) & "000";
            end if;
            if gut_p(9) = '1' or bfill_p(9) = '1' then
                v_cmb := "0000";
            end if;
            combo10 <= v_cmb;   -- E9-registered; EBR read during E10

            --------------------------------------------------------------
            -- E10: LUT EBR read cycle (address = combo10, data lands E11)
            -- E11: paper grain (print mottle) + bubble paper lift
            --------------------------------------------------------------
            -- one add + clamp after the BRAM read; everything else about
            -- the grain was folded in upstream
            v_y12 := signed(resize(unsigned(lutq(29 downto 20)), 12))
                     + resize(goff10, 12);
            wy12 <= f_cu10(v_y12);
            wu12 <= unsigned(lutq(19 downto 10));
            wv12 <= unsigned(lutq(9 downto 0));

            --------------------------------------------------------------
            -- E12: overlay compose (bubble ink > bubble paper > border >
            -- gutter > linework > halftone)
            --------------------------------------------------------------
            if bink_p(11) = '1' then
                wy13 <= s_ink_y;
                wu13 <= s_ink_u;
                wv13 <= s_ink_v;
            elsif bfill_p(11) = '1' or gut_p(11) = '1' then
                wy13 <= wy12;
                wu13 <= wu12;
                wv13 <= wv12;
            elsif bord_p(11) = '1' or edge_p(11) = '1' then
                wy13 <= s_ink_y;
                wu13 <= s_ink_u;
                wv13 <= s_ink_v;
            else
                wy13 <= wy12;
                wu13 <= wu12;
                wv13 <= wv12;
            end if;

            --------------------------------------------------------------
            -- E13: dry/wet blend, 4 steps + endpoints on the press ramp
            -- (dry video from the BRAM delay ring); the blend is convex
            -- so no clamps are needed
            --------------------------------------------------------------
            if s_wet10(9 downto 5) = "11111" then
                oy14 <= wy13;
                ou14 <= wu13;
                ov14 <= wv13;
            else
                v_t  := unsigned(ring_q(29 downto 20));
                v_dq := signed(resize(wy13, 12)) - signed(resize(v_t, 12));
                v_mac := signed(resize(v_t, 13));
                if s_wet10(9) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 1), 13);
                end if;
                if s_wet10(8) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 2), 13);
                end if;
                oy14 <= unsigned(v_mac(9 downto 0));
                v_t  := unsigned(ring_q(19 downto 10));
                v_dq := signed(resize(wu13, 12)) - signed(resize(v_t, 12));
                v_mac := signed(resize(v_t, 13));
                if s_wet10(9) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 1), 13);
                end if;
                if s_wet10(8) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 2), 13);
                end if;
                ou14 <= unsigned(v_mac(9 downto 0));
                v_t  := unsigned(ring_q(9 downto 0));
                v_dq := signed(resize(wv13, 12)) - signed(resize(v_t, 12));
                v_mac := signed(resize(v_t, 13));
                if s_wet10(9) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 1), 13);
                end if;
                if s_wet10(8) = '1' then
                    v_mac := v_mac + resize(shift_right(v_dq, 2), 13);
                end if;
                ov14 <= unsigned(v_mac(9 downto 0));
            end if;

            --------------------------------------------------------------
            -- E14: output conditioning -- horizontal [1 2 1]/4 on Y, U
            -- and V around the pixel one back (g1 is the centre, g2 and
            -- the new pixel its neighbours).  Halftone dots are the
            -- textbook HD HDMI bar trigger: full-swing pixel-to-pixel
            -- edges moving with the video.  (damier v0.4.4, A/B on HW)
            --------------------------------------------------------------
            g1_y <= oy14;  g2_y <= g1_y;
            g1_u <= ou14;  g2_u <= g1_u;
            g1_v <= ov14;  g2_v <= g1_v;
            v_sy := resize(g2_y, 12) + shift_left(resize(g1_y, 12), 1)
                    + resize(oy14, 12);
            v_su := resize(g2_u, 12) + shift_left(resize(g1_u, 12), 1)
                    + resize(ou14, 12);
            v_sv := resize(g2_v, 12) + shift_left(resize(g1_v, 12), 1)
                    + resize(ov14, 12);
            sm_y <= v_sy(11 downto 2);
            sm_u <= v_su(11 downto 2);
            sm_v <= v_sv(11 downto 2);

            --------------------------------------------------------------
            -- E15: blanking gate -- neutral whenever the latency-aligned
            -- avid is low (the press draws paper and ink colours into
            -- blanking otherwise)
            --------------------------------------------------------------
            if av(14) = '0' then
                oy16 <= to_unsigned(64, 10);
                ou16 <= to_unsigned(512, 10);
                ov16 <= to_unsigned(512, 10);
            else
                oy16 <= sm_y;
                ou16 <= sm_u;
                ov16 <= sm_v;
            end if;

            --------------------------------------------------------------
            -- flag/value pipes
            --------------------------------------------------------------
            gut_p(3) <= gut2;
            bord_p(3) <= bord2;
            for i in 4 to 11 loop
                gut_p(i) <= gut_p(i - 1);
                bord_p(i) <= bord_p(i - 1);
            end loop;
            bfill_p(5) <= bfill4;
            bink_p(5) <= bink4;
            for i in 6 to 11 loop
                bfill_p(i) <= bfill_p(i - 1);
                bink_p(i) <= bink_p(i - 1);
            end loop;
            edge_p(6) <= edv5;
            for i in 7 to 11 loop
                edge_p(i) <= edge_p(i - 1);
            end loop;
            gsn5 <= gsn4; gsn6 <= gsn5; gsn7 <= gsn6;
            gsn8 <= gsn7; gsn9 <= gsn8;
            -- fold the bubble paper lift in BEFORE the BRAM data lands
            if bfill_p(9) = '1' then
                goff10 <= resize(gsn9, 7) + 24;
            else
                goff10 <= resize(gsn9, 7);
            end if;

            --------------------------------------------------------------
            -- per-line layout flags, free-running off the latched line
            -- number (constant during active video).  NOTE: splitting
            -- this cone across two registered stages REGRESSES timing at
            -- this utilization -- the extra registers cost more in
            -- routing than the shorter logic path buys (ice40 high-util
            -- rule).  Measured: all 6 configs closed as one stage; as two
            -- stages HD Analog/HDMI missed on every seed.
            --------------------------------------------------------------
            if al_nx < s_ry1 then
                rxa_ln <= s_rxaA;
            else
                rxa_ln <= s_rxaB;
            end if;
            if al_nx > s_ry1 then
                v_yd1 := al_nx - s_ry1;
            else
                v_yd1 := s_ry1 - al_nx;
            end if;
            if al_nx > s_ry2 then
                v_yd2 := al_nx - s_ry2;
            else
                v_yd2 := s_ry2 - al_nx;
            end if;
            if v_yd1 < resize(s_guy, 11)
               or v_yd2 < resize(s_guy, 11) then
                ygut_ln <= '1';
                ybord_ln <= '0';
            elsif v_yd1 < resize(s_guy, 11) + resize(s_bwy, 11)
               or v_yd2 < resize(s_guy, 11) + resize(s_bwy, 11) then
                ygut_ln <= '0';
                ybord_ln <= '1';
            else
                ygut_ln <= '0';
                ybord_ln <= '0';
            end if;
            -- pick the bubble slot that owns the coming line: this is the
            -- whole per-line cost -- two compares driving a RAM address
            if al_nx < s_b3a then
                bra <= to_unsigned(0, 8);
            elsif al_nx < s_b3b then
                bra <= to_unsigned(1, 8);
            else
                bra <= to_unsigned(2, 8);
            end if;

            if al_nx < resize(s_omy, 11) or al_nx >= s_hmg then
                ymar_ln <= '1';
                ymbd_ln <= '0';
            elsif al_nx < resize(s_omyb, 11) or al_nx >= s_hmgb then
                ymar_ln <= '0';
                ymbd_ln <= '1';
            else
                ymar_ln <= '0';
                ymbd_ln <= '0';
            end if;

            --------------------------------------------------------------
            -- Screen line advance: step to the next DISPLAYED line when
            -- active video ENDS, never on a blanking hsync.
            --
            -- Blanking hsyncs must not move the screen.  In interlace one
            -- field's vsync coincides with an hsync edge and the other's
            -- falls mid-line, so the number of blanking hsyncs after vsync
            -- DIFFERS BY ONE between fields.  Advancing on them added 4*Ac
            -- of phase to one field only -- a near-arbitrary fraction of a
            -- dot cell (48% at an 8 px screen).  The fields' dot grids then
            -- failed to interleave, adjacent display lines disagreed, and
            -- the result was 30 Hz twitter -- worst at ~50% tone, i.e. over
            -- blue sky (C ~ 50% is the checkerboard region, and blue is
            -- drawn ONLY by the two rotated screens; Y is a vertical line
            -- screen with no vertical structure and K ~ 0 there).
            --
            -- Now the phase is a pure function of (x, y):
            --   top field,    line L -> y = 2L
            --   bottom field, line L -> y = 2L+1
            -- so the two fields interleave into one screen.
            --
            -- Each advance is ONE frame row; an interlaced field line is
            -- two rows, so the advance fires twice there (4 and 5 clocks
            -- after avid falls) and once on a progressive source.  (v0.1
            -- always stepped two rows: on 1080p every screen was squashed
            -- 2:1 vertically -- flat dots, angles 28/82/63 instead of
            -- 15/75/45, no rosette.)
            --
            -- Fires after the last real pixel has cleared E2 (which reads
            -- these registers), and before the hsync edge by the front
            -- porch.  The enable is a free DFFE CE, so the load above
            -- stays a plain copy -- as a mux on the adder output this cost
            -- 8 MHz.
            if (av(5) = '1' and av(4) = '0')
               or (s_wide = '1' and av(6) = '1' and av(5) = '0') then
                lu_c <= lu_c + s_Bc;
                lv_c <= lv_c + s_Ac;
                lu_k <= lu_k + s_Ak;
                r_lc <= r_lc + (s_Ac(10 downto 0) & '0');
                r_ls <= r_ls + (s_Bc(10 downto 0) & '0');
                r_lk <= r_lk + (s_Ak(10 downto 0) & '0');
            end if;

            --------------------------------------------------------------
            -- line / field bookkeeping
            --------------------------------------------------------------
            if data_in.hsync_n = '0' and s_prev_hsync_n = '1' then
                if s_seen = '1' then
                    s_w <= s_x_count;
                end if;
                s_x_count <= (others => '0');
                if s_seen = '1' then
                    s_seen <= '0';
                    -- 11 bits, no cap: v0.1 stopped at line 1000, which
                    -- on 1080p froze the grain on the bottom 80 lines and
                    -- read the page as 1000 tall (fat bottom margin)
                    s_aline <= s_aline + 1;
                    -- field height, captured on every ACTIVE line.
                    -- It CANNOT be latched at vsync: the first
                    -- blanking hsync (which precedes vsync) has
                    -- already reset s_aline to 0, so a vsync capture
                    -- reads 0 -- that killed every horizontal panel
                    -- split and the bottom margin.  s_h holds the
                    -- last field's height throughout blanking, which
                    -- is when the sequencer reads it.
                    s_h <= s_aline + 1;
                else
                    s_aline <= (others => '0');
                end if;
                if s_aline >= 2 then
                    s_rowok <= '1';
                else
                    s_rowok <= '0';
                end if;
                -- latch the coming line number; the layout flags are
                -- derived in a free-running stage below (they settle
                -- during blanking, long before active pixels)
                if s_seen = '1' then
                    al_nx <= s_aline + 1;
                else
                    al_nx <= (others => '0');
                end if;
                -- The line registers hold the value for the line NOW
                -- scanning, and are advanced when active video ENDS (see
                -- p_pix above), so this is a pure register copy: no adder,
                -- no mux, nothing on the path.
                acc_cu <= lu_c;
                acc_cv <= lv_c;
                acc_ku <= lu_k;
                acc_yu <= s_ouy;
            end if;
            if data_in.vsync_n = '0' and s_prev_vsync_n = '1' then
                s_aline <= (others => '0');
                -- Bottom field (odd rows) is field_n = '0' (the SDK
                -- stimulus; ribbon's HW comb confirmed it) -- v0.1 seeded
                -- the opposite field.  HD inputs tie field_n high, so a
                -- progressive source always starts at y = 0.
                s_fld <= not data_in.field_n;
                if data_in.field_n = '0' then       -- y = 1 on line 0
                    lu_c <= s_Bc + s_ouc;
                    lv_c <= s_Ac + s_ovc;
                    lu_k <= s_Ak;
                    r_lc <= (s_Ac(10 downto 0) & '0') + s_lco;
                    r_ls <= (s_Bc(10 downto 0) & '0') + s_lso;
                    r_lk <= s_Ak(10 downto 0) & '0';
                else                                -- y = 0 on line 0
                    lu_c <= s_ouc;
                    lv_c <= s_ovc;
                    lu_k <= (others => '0');
                    r_lc <= s_lco;
                    r_ls <= s_lso;
                    r_lk <= (others => '0');
                end if;
            end if;
        end if;
    end process p_pix;

    ------------------------------------------------------------------------
    -- luma line buffers (canonical 1W1R): read col x combinationally at
    -- s_x_count (lands aligned with y1), write one cycle later -- the
    -- write pointer trails the read (redshift trick)
    ------------------------------------------------------------------------
    p_lb1 : process(clk)
    begin
        if rising_edge(clk) then
            q1 <= lb1(to_integer(s_x_count));
            if av(1) = '1' then
                lb1(to_integer(px_pipe(1)))
                    <= std_logic_vector(y1(9 downto 2));
            end if;
        end if;
    end process p_lb1;

    ------------------------------------------------------------------------
    -- 1-bit edge line buffer for the vertical linework dilate
    ------------------------------------------------------------------------
    p_eb : process(clk)
    begin
        if rising_edge(clk) then
            ebq <= ebuf(to_integer(px_pipe(3)));
            if av(4) = '1' then
                ebuf(to_integer(px_pipe(4)))(0) <= ed4;
            end if;
        end if;
    end process p_eb;

    ------------------------------------------------------------------------
    -- ink combination LUT (EBR): sequencer writes during vblank and reads
    -- through the same port; during active video the port serves the
    -- pixel path at the combo address
    ------------------------------------------------------------------------
    p_lut : process(clk)
    begin
        if rising_edge(clk) then
            if s_ph /= 0 then
                lutq <= lut_ram(to_integer(s_lra));
            else
                lutq <= lut_ram(to_integer(combo10));
            end if;
            if s_lwen = '1' then
                lut_ram(to_integer(s_lwa)) <= s_lwd;
            end if;
        end if;
    end process p_lut;

    ------------------------------------------------------------------------
    -- bubble slot RAM: the sequencer writes one slot per tick during
    -- vblank, the pixel path reads the slot that owns the current line
    ------------------------------------------------------------------------
    p_bslot : process(clk)
    begin
        if rising_edge(clk) then
            bq <= bslot(to_integer(bra));
            if bwen = '1' then
                bslot(to_integer(bwa)) <= bwd;
            end if;
        end if;
    end process p_bslot;

    ------------------------------------------------------------------------
    -- bubble sprite ROMs (2 bit: 0 clear, 1 paper fill, 2 outline ink,
    -- 3 grawlix ink) -- separately named constants (GHDL ROM lesson)
    ------------------------------------------------------------------------
    p_spr : process(clk)
    begin
        if rising_edge(clk) then
            spq_s <= C_SPR_SPEECH(to_integer(saddr2));
            spq_t <= C_SPR_THOUGHT(to_integer(saddr2));
            spq_b <= C_SPR_BURST(to_integer(saddr2));
        end if;
    end process p_spr;

    ------------------------------------------------------------------------
    -- dry video delay ring (BRAM): read pointer trails the write pointer
    -- by 11 so the registered output aligns with the wet pixel at E13
    ------------------------------------------------------------------------
    p_ring : process(clk)
    begin
        if rising_edge(clk) then
            ring_wp <= ring_wp + 1;
            dring(to_integer(ring_wp))
                <= data_in.y & data_in.u & data_in.v;
            ring_q <= dring(to_integer(ring_wp - 11));
        end if;
    end process p_ring;


    ------------------------------------------------------------------------
    -- sync delay + output
    ------------------------------------------------------------------------
    p_sync : process(clk)
    begin
        if rising_edge(clk) then
            s_avid_sr    <= data_in.avid    & s_avid_sr   (0 to C_LATENCY - 2);
            s_hsync_n_sr <= data_in.hsync_n & s_hsync_n_sr(0 to C_LATENCY - 2);
            s_vsync_n_sr <= data_in.vsync_n & s_vsync_n_sr(0 to C_LATENCY - 2);
            s_field_n_sr <= data_in.field_n & s_field_n_sr(0 to C_LATENCY - 2);
        end if;
    end process p_sync;

    s_io_align_in.y       <= std_logic_vector(oy16);
    s_io_align_in.u       <= std_logic_vector(ou16);
    s_io_align_in.v       <= std_logic_vector(ov16);
    s_io_align_in.avid    <= s_avid_sr(C_LATENCY - 1);
    s_io_align_in.hsync_n <= s_hsync_n_sr(C_LATENCY - 1);
    s_io_align_in.vsync_n <= s_vsync_n_sr(C_LATENCY - 1);
    s_io_align_in.field_n <= s_field_n_sr(C_LATENCY - 1);

    -- IO-align pad: video and syncs delayed together, so only the total
    -- latency changes (15 -> 16).
    p_io_align_pad : process(clk)
    begin
        if rising_edge(clk) then
            s_io_align_pad(0) <= s_io_align_in;
        end if;
    end process p_io_align_pad;

    data_out <= s_io_align_pad(0);

end architecture pulp;

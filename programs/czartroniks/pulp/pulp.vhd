    ----------------------------------------------------------------------
    -- helpers
    ----------------------------------------------------------------------
    function f_cu10(v : signed) return unsigned is
    begin
        if v < 0 then
            return to_unsigned(0, 10);
        elsif v > 1023 then
            return to_unsigned(1023, 10);
        else
            return resize(unsigned(v), 10);
        end if;
    end function;

    function f_sat10(v : unsigned) return unsigned is
    begin
        if v > 1023 then
            return to_unsigned(1023, 10);
        else
            return resize(v, 10);
        end if;
    end function;

    -- |frac - half| on a 12b cell fraction -> 10b half-cell distance
    -- (one's-complement mirror: off by 1 LSB, carry-free)
    function f_fold10(f12 : unsigned(11 downto 0)) return unsigned is
    begin
        if f12(11) = '1' then
            return '0' & f12(10 downto 2);
        else
            return '0' & (not f12(10 downto 2));
        end if;
    end function;

    -- value-noise hash, two stages (inferno lesson)
    function f_hash_a(cx, cy : unsigned(7 downto 0);
                      seed   : unsigned(15 downto 0)) return unsigned is
        variable h16 : unsigned(15 downto 0);
        variable h   : unsigned(11 downto 0);
    begin
        h16 := ((cx & cy)) xor seed;
        h16 := h16 xor (x"0" & h16(15 downto 4));
        h   := h16(11 downto 0);
        return h + rotate_left(h, 5);
    end function;

    function f_hash_b(hin : unsigned(11 downto 0)) return unsigned is
        variable h : unsigned(11 downto 0);
    begin
        h := hin xor rotate_left(hin, 9);
        h := h + rotate_left(h, 3);
        h := h xor ("00000" & h(11 downto 5));
        return h(9 downto 2);
    end function;

    -- 16-bit galois LFSR
    function f_lfsr(x : unsigned(15 downto 0)) return unsigned is
        variable v : unsigned(15 downto 0);
    begin
        v := shift_right(x, 1);
        if x(0) = '1' then
            v := v xor x"B400";
        end if;
        return v;
    end function;

